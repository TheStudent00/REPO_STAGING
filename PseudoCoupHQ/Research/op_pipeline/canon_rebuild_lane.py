#!/usr/bin/env python3
"""canon_rebuild_lane.py -- write lanes/pc_canon_rebuild.sh.

the owner's ruling: the run of record is a lane.  This packages the whole
rebuild of 2026-08-25 as one lane:

  1. result_types.py  -- ask the compilers what each c, c++ and rust
                         probe's result type actually is, and read the
                         answer out of the debug information they emit
  2. canon.py         -- rename every unit into THE CANONICAL RUNNABLE
                         FORM, with traced-variables-priority eviction
  3. roundtrip.py     -- assemble the canonical text and disassemble it
                         again; the bytes it produces are the canonical
                         bytes
  4. dominant_table2.py -- rebuild the table with the result type in the
                         class key and with z3-proved and canonical-byte
                         edges
  5. check_no_spelling_keys.py -- the mechanical guard, on every product

The lane carries its inputs and its programs inside itself (a gzipped
tar, base64-armoured), so it needs nothing from the network.  Products
go to /out.

usage:
  canon_rebuild_lane.py
"""

import base64
import io
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))

LANGS = ["c", "cpp", "go", "rust", "swift"]


def input_names():
    names = ["verdicts4.json", "verdicts3b.json",
             "dominant_table.py", "dominant_table2.py",
             "canon.py", "roundtrip.py", "result_types.py",
             "result_vocab.py", "check_no_spelling_keys.py"]
    for lang in LANGS:
        names.append("core_modes_%s.json" % lang)
        names.append("op_units_%s.json" % lang)
        names.append("sem_anchored_%s.json" % lang)
        names.append("probe_manifest_%s.json" % lang)
    return names


def payload():
    buf = io.BytesIO()
    tar = tarfile.open(fileobj=buf, mode="w:gz")
    for name in input_names():
        tar.add(os.path.join(HERE, name), arcname=name)
    tar.close()
    raw = buf.getvalue()
    text = base64.b64encode(raw).decode("ascii")
    lines = []
    i = 0
    while i < len(text):
        lines.append(text[i:i + 76])
        i = i + 76
    return "\n".join(lines), len(raw)


HEAD = """#!/bin/sh
# pc_canon_rebuild -- the rebuild of 2026-08-25: the canonical runnable
# form, traced-variables-priority eviction, the result type in the class
# key, and z3-proved edges.  Generated by
# Research/op_pipeline/canon_rebuild_lane.py .  Do not hand-edit.
#
# Inputs and programs travel inside this file (gzipped tar, base64).
# Nothing is fetched.  Products land in /out.
set -u
export HOME=/work
export PATH=/persist/swift/usr/bin:$PATH
ROOT=/work/pc_canon
echo "=== pc_canon_rebuild -- the canonical runnable form ==="
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
for TOOL in python3 clang clang++ rustc objdump readelf; do
  if ! $TOOL --version >/dev/null 2>&1; then
    echo "!! REFUSING TO START: $TOOL is not runnable in this container."
    exit 4
  fi
done
python3 -c 'import sys; print("python " + sys.version.split()[0])'
clang --version 2>&1 | head -1
rustc --version 2>&1 | head -1
objdump --version 2>&1 | head -1
rm -rf "$ROOT"
mkdir -p "$ROOT" /out
df -Pm /work | awk 'NR==2{print "free /work: " $4 " MB"}'
FREE=`df -Pm /work | awk 'NR==2{print $4}'`
if [ "$FREE" -lt 300 ]; then
  echo "!! REFUSING TO START: only $FREE MB free on /work, need 300"
  exit 3
fi
echo "unpacking the embedded inputs (%d bytes packed)"
base64 -d <<'PC_CANON_EOF' > "$ROOT/inputs.tgz"
%s
PC_CANON_EOF
tar --no-same-owner -xzf "$ROOT/inputs.tgz" -C "$ROOT"
if [ $? -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the embedded inputs did not unpack."
  exit 5
fi
ls -la "$ROOT" | sed -n '1,40p'
cd "$ROOT"

echo "--- step 1 of 5: what does each compiler say the result type is"
python3 "$ROOT/result_types.py" --in "$ROOT" --out "$ROOT" \\
        --work "$ROOT" --cc clang --cxx clang++
RC=$?
if [ "$RC" -ne 0 ]; then
  echo "!! result-type recovery exited $RC"
  exit "$RC"
fi

echo "--- step 2 of 5: the canonical runnable form"
python3 "$ROOT/canon.py" --in "$ROOT" --out "$ROOT" --every 200
RC=$?
if [ "$RC" -ne 0 ]; then
  echo "!! canonicalisation exited $RC"
  exit "$RC"
fi

echo "--- step 3 of 5: assemble the canonical text and read it back"
python3 "$ROOT/roundtrip.py" --in "$ROOT" --out "$ROOT" \\
        --work "$ROOT" --cc clang --every 200
RC=$?
if [ "$RC" -ne 0 ]; then
  echo "!! the round trip exited $RC"
  exit "$RC"
fi

echo "--- step 4 of 5: rebuild the table"
python3 "$ROOT/dominant_table2.py" --in "$ROOT" --out "$ROOT" --every 200
RC=$?
if [ "$RC" -ne 0 ]; then
  echo "!! the table builder exited $RC"
  exit "$RC"
fi

echo "--- step 5 of 5: THE SPELLING BAN -- the mechanical guard"
python3 "$ROOT/check_no_spelling_keys.py" \\
        "$ROOT/dominant_table2.json" \\
        "$ROOT/canon_roundtrip.json" \\
        "$ROOT/canon_units_c.json" \\
        "$ROOT/canon_units_cpp.json" \\
        "$ROOT/canon_units_go.json" \\
        "$ROOT/canon_units_rust.json" \\
        "$ROOT/canon_units_swift.json" \\
        "$ROOT/result_types_c.json" \\
        "$ROOT/result_types_cpp.json" \\
        "$ROOT/result_types_rust.json"
RC=$?
if [ "$RC" -ne 0 ]; then
  echo "!! THE GUARD FAILED: refusing to publish these products."
  exit "$RC"
fi

echo "--- publishing"
cp "$ROOT/canon_units_"*.json /out/
cp "$ROOT/canon_roundtrip.json" /out/
cp "$ROOT/result_types_"*.json /out/
cp "$ROOT/dominant_table2.json" /out/
cp "$ROOT/dominant_table2.md" /out/
cp "$ROOT/table_digest2.md" /out/
cp "$ROOT/canon_roundtrip.s" /out/canon_roundtrip.s
ls -la /out
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
echo "=== pc_canon_rebuild done ==="
"""


def main():
    body, size = payload()
    text = HEAD % (size, body)
    outdir = os.path.join(HERE, "lanes")
    if not os.path.isdir(outdir):
        os.makedirs(outdir)
    path = os.path.join(outdir, "pc_canon_rebuild.sh")
    fh = open(path, "w")
    fh.write(text)
    fh.close()
    print("wrote %s (%d bytes; %d bytes of packed input)"
          % (path, len(text), size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
