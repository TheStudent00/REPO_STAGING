#!/usr/bin/env python3
"""l3_interval_ruby.py -- the ruby half of the interval lane.

Kept in its own module only because it carries three nested source
texts (a `/bin/sh` lane, a ruby driver, a python runner) and quoting
them all inside one file is how mistakes happen.

Route C: execution is the only acceptance evidence ruby has (CORE_0_3_2
ruling 5; log_026 finding 2), so every ordered NUMERIC holder pair
times the operator menu gets an interval row.

Two hazards the edge-value runs never met, and what is done about each:

  1  An interval sample reaches 2**127.  `a ** b` and `a << b` at that
     magnitude are unbounded ALLOCATIONS.  The address space is capped
     at 2 GB, so such a probe stops fast instead of swapping the host.
     Whether ruby recovers with `NoMemoryError` (a RAISE) or the VM
     stops outright (an ABORT) is itself part of what the probe
     measured, and both are recorded faithfully -- the runner restarts
     the driver past a probe that stopped it, the same discipline
     `l3_exec.py` already uses for the compiled languages.

  2  An answer can be an exact integer of millions of digits.  Printing
     it costs minutes, and TRUNCATING its decimal spelling would be
     silently mis-read as a smaller number -- a correctness fault, not
     a cosmetic one.  So an oversized answer travels as a declared
     token: sign, exact bit length, and the leading 512 bits.

A bignum computation is a C-level loop no in-language alarm reaches, so
the runner also carries an inactivity watchdog: silence longer than the
stall budget means the probe is stuck, the process is stopped, and the
probe is recorded ABORT.

VOCABULARY (absolute): super-node / sub-node / co-node / sub-tree;
the OS-stopped outcome is ABORT.
"""

SH = """#!/bin/sh
# layer-3 INTERVAL lane -- ruby -- generated by
# Research/kind_fuzz_clustering/l3_interval_gen.py .  Do not hand-edit.
set -u
export HOME=/work
ROOT=/work/iv_ruby_00
rm -rf "$ROOT"; mkdir -p "$ROOT"
echo "=== layer-3 INTERVAL -- ruby -- __NP__ samples over __NC__ cells ==="
date -u +%Y-%m-%dT%H:%M:%SZ
base64 -d <<'T_EOF' | gunzip > "$ROOT/table.json"
__TABLE__
T_EOF
base64 -d <<'DRV_EOF' > "$ROOT/drv.rb"
__DRIVER__
DRV_EOF
python3 - "$ROOT" <<'PY_EOF'
__RUNNER__
PY_EOF
rm -rf "$ROOT"
date -u +%Y-%m-%dT%H:%M:%SZ
echo "=== interval lane ruby done ==="
"""


DRIVER = r"""ROOT = ARGV[0]
START = (ARGV[1] || "0").to_i
require 'json'
require 'bigdecimal'
$VERBOSE = nil            # ruby's "in a**b, b may be too big" warning
begin
  Process.setrlimit(Process::RLIMIT_AS, 2 * 1024 * 1024 * 1024)
rescue StandardError
end
T = JSON.parse(File.read(File.join(ROOT, "table.json")))
HS = T["holders"]; OPS = T["ops"]; NS = T["n_samples"]

BIGBITS = 4096
TOPBITS = 512

def _top(a)
  bl = a.bit_length
  [bl, (bl > TOPBITS ? (a >> (bl - TOPBITS)) : a).to_s(16)]
end

def ser(r)
  case r
  when Integer
    a = r.abs
    if a.bit_length > BIGBITS
      bl, hx = _top(a)
      "BIGNUM:#{r < 0 ? -1 : 1}:#{bl}:#{hx}"
    else
      "Integer:#{r}"
    end
  when Rational
    n = r.numerator; d = r.denominator
    if n.abs.bit_length > BIGBITS || d.bit_length > BIGBITS
      nb, nh = _top(n.abs); db, dh = _top(d)
      "BIGRAT:#{n < 0 ? -1 : 1}:#{nb}:#{nh}:#{db}:#{dh}"
    else
      "Rational:#{n}/#{d}"
    end
  when Float
    "Float:#{r.inspect}"
  when BigDecimal
    s = r.to_s
    s.length > 4000 ? "BIGDEC:#{r.sign}:#{r.exponent}:#{s[0, 200]}" : "BigDecimal:#{s}"
  when String
    "String:#{r.length > 2000 ? r[0, 2000] : r}"
  else
    "#{r.class}:#{r.inspect[0, 400]}"
  end
end

PROBES = []
HS.each do |ha|
  HS.each do |hb|
    OPS.each_with_index do |op, k|
      NS.times do |s|
        PROBES << ["V#{k}_#{ha['i']}_#{hb['i']}_#{s}",
                   ha["a"][s], hb["b"][s], op]
      end
    end
  end
end
$stdout.sync = true
i = START
while i < PROBES.size
  pid, da, db, op = PROBES[i]
  src = da + "\n" + db + "\n__r = ((a) #{op} (b))\n__r"
  begin
    r = eval(src)
    puts "#{pid}|ANSWER|#{ser(r)}"
  rescue SyntaxError
    puts "#{pid}|REFUSE|SyntaxError"
  rescue Exception => e
    puts "#{pid}|RAISE|#{e.class}"
  end
  i += 1
end
puts "__END__"
"""


RUNNER = r"""
import json
import os
import queue
import subprocess
import sys
import threading
import time

ROOT = sys.argv[1]
T = json.load(open(os.path.join(ROOT, "table.json")))
OUT = T["out"]
STALL = 10.0          # seconds of silence before a probe is called stuck

HS, OPS, NS = T["holders"], T["ops"], T["n_samples"]
ids = []
for ha in HS:
    for hb in HS:
        for k, op in enumerate(OPS):
            for s in range(NS):
                ids.append("V%d_%d_%d_%d" % (k, ha["i"], hb["i"], s))
pos = dict((p, k) for k, p in enumerate(ids))
print("interval ruby: %d numeric holders, %d operations, %d ordered "
      "pairs, %d samples per side, %d probes"
      % (len(HS), len(OPS), len(HS) ** 2, NS, len(ids)))
sys.stdout.flush()


def pump(fh, q):
    for line in fh:
        q.put(line.rstrip("\n"))
    q.put(None)


got = {}
start = 0
restarts = 0
t0 = time.time()
while start < len(ids) and restarts < 600:
    pr = subprocess.Popen(["ruby", os.path.join(ROOT, "drv.rb"), ROOT,
                           str(start)],
                          stdout=subprocess.PIPE,
                          stderr=subprocess.DEVNULL, text=True, bufsize=1)
    q = queue.Queue()
    threading.Thread(target=pump, args=(pr.stdout, q), daemon=True).start()
    last = start - 1
    ended = stalled = False
    while True:
        try:
            line = q.get(timeout=STALL)
        except queue.Empty:
            stalled = True
            break
        if line is None:
            break
        if line == "__END__":
            ended = True
            continue
        if "|" not in line:
            continue
        pid = line.split("|", 1)[0]
        k = pos.get(pid)
        if k is None:
            continue
        got[pid] = line
        if k > last:
            last = k
    if stalled:
        try:
            pr.kill()          # the subprocess API's own name; the
                               # OUTCOME this produces is ABORT
        except OSError:
            pass
    pr.wait()
    if ended or last >= len(ids) - 1:
        break
    nxt = last + 1
    why = ("stalled>%.0fs" % STALL) if stalled else ("rc%s" % pr.returncode)
    got[ids[nxt]] = "%s|ABORT|%s" % (ids[nxt], why)
    start = nxt + 1
    restarts += 1
    print("[restart %d] %s stopped the process (%s); continuing at "
          "%d/%d after %.1f s"
          % (restarts, ids[nxt], why, start, len(ids), time.time() - t0))
    sys.stdout.flush()

el = time.time() - t0
ans = raises = aborts = refused = missing = 0
with open(OUT, "w") as f:
    for pid in ids:
        line = got.get(pid, "%s|MISSING|" % pid)
        f.write(line + "\n")
        kind = line.split("|")[1]
        if kind == "ANSWER":
            ans += 1
        elif kind == "RAISE":
            raises += 1
        elif kind == "ABORT":
            aborts += 1
        elif kind == "REFUSE":
            refused += 1
        else:
            missing += 1
    f.write("__SUMMARY__|ruby|%d|%d|%d|%d|%d|%.3f\n"
            % (len(ids), ans, raises, aborts, refused, el))
print("== interval ruby: %d probes, %d answers, %d raises, %d aborts, "
      "%d refusals, %d missing, %d restarts, %.2f s"
      % (len(ids), ans, raises, aborts, refused, missing, restarts, el))
"""
