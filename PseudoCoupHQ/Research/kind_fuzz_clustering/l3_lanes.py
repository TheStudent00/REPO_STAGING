def payload(lang):
    raw = open(os.path.join(HERE, "probes_ac_%s.jsonl" % lang), "rb").read()
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0) as g:
        g.write(raw)
    b = base64.b64encode(buf.getvalue()).decode()
    return "\n".join(b[i:i+76] for i in range(0, len(b), 76))


def build(lang):
    n = sum(1 for _ in open(os.path.join(HERE, "probes_ac_%s.jsonl" % lang)))
    drv = DRIVER.replace("{LANG}", lang).replace("{EXT}", EXT[lang]) \
                .replace("{MODE}", MODES[lang])
    drv = drv.replace("{{", "{").replace("}}", "}")
    drv = drv.replace("DRV_CS", "'''" + DRV_CS + "'''") \
             .replace("KDRV_JAVA", "'''" + KDRV_JAVA + "'''") \
             .replace("JDRV_JAVA", "r'''" + JDRV_JAVA + "'''") \
             .replace("TDRV_JS", "r'''" + TDRV_JS + "'''")
    head = (PRELUDE.replace("{LANG}", lang)
                   .replace("{ROUTE}", ROUTES[lang])
                   .replace("{N}", str(n))
                   .replace("{PAYLOAD}", payload(lang))
                   .replace("{{", "{").replace("}}", "}"))
    setup = ""
    if lang == "typescript":
        # the shipped checker has to BE there.  /persist survives a
        # container restart, so this is a no-op on every run after the
        # first; it is written so the lane is self-sufficient.
        setup = ('if [ ! -f /persist/tv/ts5/node_modules/typescript/lib/'
                 'typescript.js ]; then\n'
                 '  mkdir -p /persist/tv/ts5 && cd /persist/tv/ts5 && \\\n'
                 '  npm install typescript@5 --no-audit --no-fund '
                 '>/dev/null 2>&1\n'
                 'fi\n'
                 'node -e "var t=require(\'/persist/tv/ts5/node_modules/'
                 'typescript/lib/typescript.js\');'
                 'console.log(\'typescript \'+t.version)"\n')
    p = os.path.join(LANES, "ac_%s.sh" % lang)
    open(p, "w").write(head + setup + drv)
    os.chmod(p, 0o755)
    print("wrote %s  (%d probes, %.1f KB)"
          % (p, n, os.path.getsize(p) / 1024.0))


