# ================================================== the reference, in c =====
C_DECODE = {
    "b":   "    _Bool %s = (p%d & 1u) != 0;",
    "i32": "    int32_t %s = (int32_t)(uint32_t)p%d;",
    "i64": "    int64_t %s = (int64_t)p%d;",
    "u64": "    uint64_t %s = (uint64_t)p%d;",
    "f32": "    float %s; { uint32_t t_ = (uint32_t)p%d; memcpy(&%s, &t_, 4); }",
    "f64": "    double %s; { uint64_t t_ = p%d; memcpy(&%s, &t_, 8); }",
}

C_MIN = {"i32": "INT32_MIN", "i64": "INT64_MIN"}
C_CT = {"i32": "int32_t", "i64": "int64_t", "u64": "uint64_t"}

C_PREAMBLE = r"""/* generated by scripts/verify_arch_units_int.py
 *
 * The reference: the arch-unit's own source expression, in c, at host -O2.
 * The result TYPE is the C compiler's own, taken with __typeof__, so the
 * usual arithmetic conversions are not assumed anywhere in this file.
 * AU_WIDEN presents the answer in the same convention the emulation uses:
 * the result type's own bit pattern, zero-extended into a uint64.
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static uint64_t auw_bool(_Bool v) { return v ? UINT64_C(1) : UINT64_C(0); }
static uint64_t auw_i(int v) { return (uint64_t)(uint32_t)v; }
static uint64_t auw_u(unsigned int v) { return (uint64_t)(uint32_t)v; }
static uint64_t auw_l(long v) { return (uint64_t)v; }
static uint64_t auw_ul(unsigned long v) { return (uint64_t)v; }
static uint64_t auw_ll(long long v) { return (uint64_t)v; }
static uint64_t auw_ull(unsigned long long v) { return (uint64_t)v; }
static uint64_t auw_f(float v) { uint32_t t; memcpy(&t, &v, 4); return t; }
static uint64_t auw_d(double v) { uint64_t t; memcpy(&t, &v, 8); return t; }
#define AU_WIDEN(x) _Generic((x), \
    _Bool: auw_bool, int: auw_i, unsigned int: auw_u, long: auw_l, \
    unsigned long: auw_ul, long long: auw_ll, \
    unsigned long long: auw_ull, float: auw_f, double: auw_d)(x)

static uint64_t S_;
static void seed(void) { S_ = %(SEED)sULL; }
static uint64_t rnd(void) { S_ ^= S_ << 13; S_ ^= S_ >> 7; S_ ^= S_ << 17;
                            return S_; }
static const char *DIR_;
"""


def c_ref_fn(u):
    """the arch-unit's own expression, as a native c function."""
    tags = [S.SRC_TAG[u["lhs_type"]]]
    names = ["a"]
    if u["rhs_type"] is not None:
        tags.append(S.SRC_TAG[u["rhs_type"]])
        names.append("b")
    L = ["static uint64_t ref_%03d(uint64_t *fl_, %s)"
         % (u["index"], ", ".join("uint64_t p%d" % i
                                  for i in range(len(names)))),
         "{", "    *fl_ = 0;"]
    for i, (nm, t) in enumerate(zip(names, tags)):
        line = C_DECODE[t]
        L.append(line % ((nm, i, nm) if S.kind(t) == "f" else (nm, i)))
    expr = u["expression"]
    if u["operator"] == "&" and u["rhs_type"] is None:
        expr = "*(&a)"                             # the stated reduction
    if u["operator"] in ("/", "%") and u["rhs_type"] is not None:
        ct = S.c_usual(tags[0], tags[1])
        cn = C_CT[ct]
        g = ["    {   /* C leaves both of these undefined and the host faults",
             "         * on them, so the reference has no answer here. */",
             "        %s ca_ = (%s)a, cb_ = (%s)b; (void)ca_;" % (cn, cn, cn)]
        if S.signed(ct):
            g.append("        if (cb_ == 0 || (ca_ == %s && cb_ == (%s)-1))"
                     % (C_MIN[ct], cn))
        else:
            g.append("        if (cb_ == 0)")
        g += ["            { *fl_ = 2; return 0; }", "    }"]
        L += g
    L.append("    __typeof__(%s) r_ = (%s);" % (expr, expr))
    L.append("    return AU_WIDEN(r_);")
    L.append("}")
    return "\n".join(L)


def gen_ref_c(units):
    cu = [u for u in units if u["lang"] == "c"]
    L = [C_PREAMBLE % {"SEED": SEED}, ""]
    for u in cu:
        L.append(c_ref_fn(u))
        L.append("")
    for u in cu:
        L.append(gen_stream_c(u))
        L.append("")
    L.append("int main(int argc, char **argv)\n{\n    DIR_ = argv[1];"
             " (void)argc;")
    for u in cu:
        L.append("    stream_%03d();" % u["index"])
    L.append("    return 0;\n}")
    return "\n".join(L) + "\n"


def gen_stream_c(u):
    tags, edges, total = plan(u)
    n = len(tags)
    idx = u["index"]
    L = []
    for i, e in enumerate(edges):
        L.append("static const unsigned long long E_%03d_%d[] = {%s};"
                 % (idx, i, ",".join("0x%xULL" % v for v in e)))
    L += ["static void stream_%03d(void)" % idx, "{",
          "    uint64_t *buf = (uint64_t *)malloc(%dULL * 8);" % total,
          "    unsigned char *flg = (unsigned char *)malloc(%dULL);" % total,
          "    unsigned long long k = 0;",
          "    uint64_t f_;",
          "    unsigned long long %s;" % ", ".join("c%d" % i for i in range(n)),
          "    char path[512];",
          "    seed();"]
    body = ("        buf[k] = ref_%03d(&f_, %s); flg[k] = (unsigned char)f_;"
            " k++;" % (idx, ", ".join("c%d" % i for i in range(n))))
    for i in range(n):
        L.append("    %sfor (unsigned long long i%d = 0; i%d < %d; i%d++) {"
                 % ("    " * i, i, i, len(edges[i]), i))
    for i in range(n):
        L.append("    %sc%d = E_%03d_%d[i%d];" % ("    " * n, i, idx, i, i))
    L.append(body)
    L.append("    " + "}" * n)
    L.append("    for (unsigned long long q = 0; q < %dULL; q++) {" % N_RAND)
    for i, t in enumerate(tags):
        L.append(S.uniform_line("c", i, t, "        "))
    L.append(body)
    L.append("    }")
    L.append("    for (unsigned long long q = 0; q < %dULL; q++) {" % N_BAND)
    L += S.band_lines("c", tags, "        ")
    L.append(body)
    L.append("    }")
    L += ['    snprintf(path, sizeof path, "%s/' + ("%03d.bin" % idx)
          + '", DIR_);',
          '    { FILE *f = fopen(path, "wb"); fwrite(buf, 8, k, f);'
          " fclose(f); }",
          '    snprintf(path, sizeof path, "%s/' + ("%03d.flg" % idx)
          + '", DIR_);',
          '    { FILE *f = fopen(path, "wb"); fwrite(flg, 1, k, f);'
          " fclose(f); }",
          "    free(buf); free(flg);",
          '    printf("REF %d %%llu\\n", k);' % idx,
          "}"]
    return "\n".join(L)


# ================================================= the reference, in go =====
GO_DECODE = {
    "b":   "\t%s := p%d&1 != 0",
    "i32": "\t%s := int32(uint32(p%d))",
    "i64": "\t%s := int64(p%d)",
    "u64": "\t%s := p%d",
    "f32": "\t%s := math.Float32frombits(uint32(p%d))",
    "f64": "\t%s := math.Float64frombits(p%d)",
}
GO_WIDEN = {
    "b":   "\tif r_ {\n\t\treturn 1, 0\n\t}\n\treturn 0, 0",
    "i32": "\treturn uint64(uint32(r_)), 0",
    "i64": "\treturn uint64(r_), 0",
    "u64": "\treturn r_, 0",
    "f32": "\treturn uint64(math.Float32bits(r_)), 0",
    "f64": "\treturn math.Float64bits(r_), 0",
}

GO_PANICS = {"/", "%", "<<", ">>"}


def go_ref_fn(u):
    tags = [S.SRC_TAG[u["lhs_type"]]]
    names = ["a"]
    if u["rhs_type"] is not None:
        tags.append(S.SRC_TAG[u["rhs_type"]])
        names.append("b")
    L = ["func ref_%03d(%s) (out uint64, fl byte) {"
         % (u["index"], ", ".join("p%d uint64" % i
                                  for i in range(len(names))))]
    if u["operator"] in GO_PANICS and u["rhs_type"] is not None:
        # observe go's own panic rather than assume the condition
        L.append("\tdefer func() { if recover() != nil { out, fl = 0, 1 } }()")
    for i, (nm, t) in enumerate(zip(names, tags)):
        L.append(GO_DECODE[t] % (nm, i))
    expr = u["expression"]
    if u["operator"] == "&" and u["rhs_type"] is None:
        L.append("\tq_ := &a")
        expr = "*q_"
    L.append("\tr_ := (%s)" % expr)
    L.append(GO_WIDEN[S.result_tag(u)])
    L.append("}")
    return "\n".join(L)


