#!/usr/bin/env python3
"""sret_render.py -- TASK 31: the erase-and-re-render round trip for a
unit whose answer is written into caller-provided memory.

WHAT A ROUND TRIP MEANS HERE, concretely, on rust/op_786.

  step 0, the unit's OWN SHIP TEXT (ground truth, read off
  canon4_units_rust.json's `mnem`):

      mov %rdi,%rax
      mov %esi,(%rdi)
      mov %edx,0x4(%rdi)
      movb $0x0,0x8(%rdi)
      ret

  step 1, ERASE. Every register spelling is replaced by the
  DESIGNATION its seat carries in the three-seat entry contract
  (entry_contract3.build_contract). The copy into the answer register
  is a pure move -- the ABI's own bookkeeping -- so it is erased and
  recorded as the EXIT ADAPTER, not as computation. What is left is a
  list of field writes:

      store  offset 0   width 32   value = a
      store  offset 4   width 32   value = b
      store  offset 8   width  8   value = $0x0
      exit   result-destination is returned in the answer register

  step 2, RE-RENDER. The field writes are emitted in ASCENDING OFFSET
  ORDER, each at the seat register its designation owns; then the exit
  adapter is regenerated by rule; then `ret`:

      mov %esi,(%rdi)
      mov %edx,0x4(%rdi)
      movb $0x0,0x8(%rdi)
      mov %rdi,%rax
      ret

THE RE-RENDERED TEXT IS NOT A COPY OF THE SHIP TEXT. The exit adapter
moved from the FIRST line to the second-to-last. That is a deliberate
consequence of the rendering rule (writes first, contract adapters
last) and it is what keeps the gate in `sret_gate.py` from comparing a
text with itself -- the defect log_112 found in canon4.py, where
`blocks` and `derived_blocks` were the same list object.

MOVING THE ADAPTER IS ONLY SOUND UNDER A STATED GUARD, and the guard
is mechanical, not a judgement: the re-render REFUSES BY NAME unless
(a) no store's source register is in the answer register's family, and
(b) the destination register is written by nothing except the adapter
itself. Under those two conditions the adapter commutes with every
store. Both are checked on every unit; a unit failing either is
refused, never rendered.

THE SPELLING BAN, pasted verbatim as required:

"THE SPELLING BAN, ABSOLUTE (the owner, restated in anger 2026-08-25 after
a second violation). No operator token may appear in ANY key,
grouping, pairing, row structure, candidate selection, or comparison
scope, anywhere in this line -- not in matching, not in "which pairs
get compared", not in report rows, not in dropdowns. The candidate
set for comparison comes from machine-form evidence (clusters,
connections, type pairs) or from ratified intention -- never from the
token. The token appears exactly once per unit: as a display label on
the member. HISTORY OF VIOLATIONS, so the pattern is visible: (1) the
arch campaign's cross-language matrix (caught by the owner 2026-08-24); (2)
verdicts.py's row pairing (caught by the owner 2026-08-25 -- the fix brief
itself reintroduced it as "same-operator pairs"). MECHANICAL GUARD
REQUIRED: every pipeline stage that groups or pairs units must run
the spelling-key check (op_pipeline/check_no_spelling_keys.py) and
refuse its own output on failure. A brief handed to any subagent for
this line MUST paste this paragraph verbatim."

Coding discipline: no complex/compound one-liner statements.
"""

import entry_contract3 as EC3


class NotRenderable(Exception):
    pass


# the spelling each (class, width) pair is written back at -- the
# instruction the re-render emits for one field write.
INT_NAME_AT_WIDTH = {
    ("rdi", 64): "rdi", ("rdi", 32): "edi",
    ("rdi", 16): "di", ("rdi", 8): "dil",
    ("rsi", 64): "rsi", ("rsi", 32): "esi",
    ("rsi", 16): "si", ("rsi", 8): "sil",
    ("rdx", 64): "rdx", ("rdx", 32): "edx",
    ("rdx", 16): "dx", ("rdx", 8): "dl",
    ("rcx", 64): "rcx", ("rcx", 32): "ecx",
    ("rcx", 16): "cx", ("rcx", 8): "cl",
    ("rax", 64): "rax", ("rax", 32): "eax",
    ("rax", 16): "ax", ("rax", 8): "al",
}

FLOAT_STORE_MNEM = {32: "movss", 64: "movsd"}
INT_IMMEDIATE_MNEM = {8: "movb", 16: "movw", 32: "movl", 64: "movq"}


def erase(lang, meta, mnem_lines):
    """(erased_form, contract, evidence) -- the unit reduced to named
    field writes plus the exit contract."""
    contract, evidence = EC3.build_contract(lang, meta, mnem_lines)
    if not contract.get("displaced"):
        raise NotRenderable(
            "this unit carries no result-destination seat -- "
            "sret_render only handles the displaced ABI")
    destination = evidence["destination_register"]
    steps = []
    for s in evidence["stores"]:
        source = s["source"]
        if source.startswith("$"):
            steps.append({
                "kind": "store-immediate",
                "offset": s["offset"],
                "width_bits": s["width_bits"],
                "value": source,
            })
            continue
        if not source.startswith("%"):
            raise NotRenderable(
                "store source %r is neither an immediate nor a "
                "register" % source)
        name = source[1:]
        designation = EC3.designation_of_register(contract, name)
        if designation is None:
            raise NotRenderable(
                "store source %%%s occupies no seat of this unit's "
                "entry contract %r -- the value being written has no "
                "name" % (name, [x["designation"] + "=" +
                                 x["register"]
                                 for x in contract["seats"]]))
        family = EC3.FAMILY_OF_REGISTER[name]
        if family == "rax":
            raise NotRenderable(
                "store source %%%s is in the answer register's "
                "family, so moving the exit adapter would change the "
                "answer -- refused by the commuting guard" % name)
        steps.append({
            "kind": "store-value",
            "offset": s["offset"],
            "width_bits": s["width_bits"],
            "value": designation,
            "class": EC3.seat_of(contract, designation)["class"],
        })
    written = EC3.registers_written(mnem_lines)
    destination_family = EC3.FAMILY_OF_REGISTER[destination]
    if destination_family in written:
        raise NotRenderable(
            "the result destination %%%s is written inside the unit, "
            "so the exit adapter does not commute with the stores -- "
            "refused by the commuting guard" % destination)
    occupied = {}
    for step in steps:
        start = step["offset"]
        end = start + step["width_bits"] // 8
        for byte in range(start, end):
            if byte in occupied:
                raise NotRenderable(
                    "two field writes overlap at byte %d, so their "
                    "order is load-bearing and the ascending-offset "
                    "re-render is not sound -- refused by the "
                    "disjointness guard" % byte)
            occupied[byte] = True
    erased = {
        "steps": steps,
        "exit_adapter": {
            "kind": "exit-adapter",
            "from": "result-destination",
            "to": "answer-register",
        },
    }
    return erased, contract, evidence


def render_store(step, contract):
    """one field write, emitted at the seat register its designation
    owns."""
    seat = EC3.seat_of(contract, "result-destination")
    base = seat["register"]
    if step["offset"] == 0:
        address = "(%%%s)" % base
    else:
        address = "0x%x(%%%s)" % (step["offset"], base)
    if step["kind"] == "store-immediate":
        mnem = INT_IMMEDIATE_MNEM.get(step["width_bits"])
        if mnem is None:
            raise NotRenderable(
                "no immediate-store spelling for %d bits"
                % step["width_bits"])
        return "%s %s,%s" % (mnem, step["value"], address)
    value_seat = EC3.seat_of(contract, step["value"])
    if value_seat is None:
        raise NotRenderable(
            "designation %r has no seat" % step["value"])
    if value_seat["class"] == "float":
        mnem = FLOAT_STORE_MNEM.get(step["width_bits"])
        if mnem is None:
            raise NotRenderable(
                "no float-store spelling for %d bits"
                % step["width_bits"])
        return "%s %%%s,%s" % (mnem, value_seat["register"], address)
    name = INT_NAME_AT_WIDTH.get(
        (value_seat["register"], step["width_bits"]))
    if name is None:
        raise NotRenderable(
            "no %d-bit spelling of integer seat %%%s"
            % (step["width_bits"], value_seat["register"]))
    return "mov %%%s,%s" % (name, address)


def render(erased, contract):
    """the canonical runnable text: field writes in ascending offset
    order, then the exit adapter, then `ret`."""
    steps = sorted(erased["steps"], key=lambda s: s["offset"])
    lines = []
    for step in steps:
        lines.append(render_store(step, contract))
    seat = EC3.seat_of(contract, "result-destination")
    lines.append("mov %%%s,%%%s"
                 % (seat["register"], EC3.ANSWER_REGISTER))
    lines.append("ret")
    return lines


def canonical_text(lang, meta, mnem_lines):
    """(lines, erased_form, contract, evidence) -- the whole round
    trip for one unit."""
    erased, contract, evidence = erase(lang, meta, mnem_lines)
    lines = render(erased, contract)
    return lines, erased, contract, evidence
