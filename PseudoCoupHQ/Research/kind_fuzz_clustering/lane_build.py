#!/usr/bin/env python3
"""lane_build.py -- wrap the generated probes into a SandboxDesign lane.

The lane is self-contained: the runner container cannot see this repo, so the
probe payload travels INSIDE the script, exactly as the layer-2 audit lane
carried its source. Two passes, both inside the sandbox, so both are measured
rather than asserted:

  pass 1  COMPILE each probe on its own.  Python's compiler is reachable at run
          time, so a refusal isolates to its exact probe with no bisecting --
          the engineering crux the CORE records applies to the ten compiled
          languages, not to this one.  A refusal is recorded as
          `<compile-error:NAME>` and the probe does not run.
  pass 2  RUN each compiled probe in a fresh namespace, inside its own
          try/except, under a wall-clock alarm and an address-space limit.
          Catching is HARNESS mechanics: it is how a raise is READ, and is
          never itself a probed operation.

Every line of /out/l3_python.txt is PROBE_ID|RESULT.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

DRIVER = r'''
import json, resource, signal, sys, traceback

OUT = open("/out/l3_python.txt", "w", buffering=1)
PAYLOAD = "/work/l3_python/probes.jsonl"
BUDGET_SECONDS = 2.0
resource.setrlimit(resource.RLIMIT_AS, (2 << 30, 2 << 30))


class Budget(Exception):
    pass


def _ring(signum, frame):
    raise Budget()


signal.signal(signal.SIGALRM, _ring)


def guard(on):
    signal.setitimer(signal.ITIMER_REAL, BUDGET_SECONDS if on else 0.0)


def canon(value):
    """One printable answer: the type the compiler produced, then the value."""
    name = type(value).__name__
    try:
        if isinstance(value, (set, frozenset)):
            body = "{" + ", ".join(sorted(map(repr, value))) + "}"
        elif isinstance(value, dict):
            body = "{" + ", ".join("%r: %r" % kv for kv in value.items()) + "}"
        else:
            body = repr(value)
    except BaseException as exc:
        body = "<unreadable:" + type(exc).__name__ + ">"
    body = body.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r")
    body = body.replace("|", "\\x7c").replace("\t", "\\t")
    if len(body) > 160:
        body = body[:160] + "<trunc>"
    return name + ":" + body


def main():
    probes = [json.loads(line) for line in open(PAYLOAD)]
    codes = {}
    refused = 0
    for probe in probes:
        pid = probe["id"]
        try:
            guard(True)
            codes[pid] = compile(probe["src"], "<probe:" + pid + ">", "exec")
            guard(False)
        except Budget:
            guard(False)
            OUT.write(pid + "|<compile-timeout>\n")
            refused += 1
        except BaseException as exc:
            guard(False)
            OUT.write(pid + "|<compile-error:" + type(exc).__name__ + ">\n")
            refused += 1
    sys.stderr.write("compiled %d, refused %d\n" % (len(codes), refused))

    ran = 0
    for probe in probes:
        pid = probe["id"]
        code = codes.get(pid)
        if code is None:
            continue
        space = {}
        try:
            guard(True)
            exec(code, space)
            guard(False)
            if "_r" in space:
                answer = canon(space["_r"])
            else:
                answer = "<no-answer>"
        except Budget:
            guard(False)
            answer = "<timeout>"
        except MemoryError:
            guard(False)
            answer = "<raise:MemoryError>"
        except BaseException as exc:
            guard(False)
            answer = "<raise:" + type(exc).__name__ + ">"
        OUT.write(pid + "|" + answer + "\n")
        ran += 1
    sys.stderr.write("ran %d\n" % ran)
    OUT.close()


main()
'''

HEAD = """#!/bin/sh
# layer-3 kind fuzz -- python -- generated by
# Research/kind_fuzz_clustering/lane_build.py . Do not hand-edit; regenerate.
# Every line of /out/l3_python.txt is PROBE_ID|RESULT.
set -u
ROOT=/work/l3_python
rm -rf "$ROOT"; mkdir -p "$ROOT"
export HOME=/work
OUT=/out/l3_python.txt
: > "$OUT"
echo "=== layer-3 kind fuzz -- python ==="
date -u +%Y-%m-%dT%H:%M:%SZ
if ! command -v python3 >/dev/null 2>&1; then
  echo "python: TOOLCHAIN ABSENT -- nothing run"
  echo "__ABSENT__|<absent>" >> "$OUT"
  exit 0
fi
python3 -V
cd "$ROOT"
"""

TAIL = """
START=$(date +%s)
timeout 1800 python3 driver.py
RC=$?
END=$(date +%s)
echo "driver exit=$RC seconds=$((END-START))"
echo "=== l3_python complete: $(wc -l < "$OUT") result lines ==="
"""


def main():
    data = json.load(open(os.path.join(HERE, "probes_python.json")))
    probes = data["probes"]
    lines = [json.dumps({"id": p["id"], "src": p["src"]}, sort_keys=True)
             for p in probes]
    path = os.path.join(HERE, "lanes", "l3_python.sh")
    with open(path, "w") as h:
        h.write(HEAD)
        h.write("cat > probes.jsonl <<'L3_PAYLOAD_EOF'\n")
        h.write("\n".join(lines))
        h.write("\nL3_PAYLOAD_EOF\n")
        h.write("cat > driver.py <<'L3_DRIVER_EOF'\n")
        h.write(DRIVER)
        h.write("\nL3_DRIVER_EOF\n")
        h.write(TAIL)
    print("wrote %s  probes=%d  bytes=%d"
          % (path, len(probes), os.path.getsize(path)))


if __name__ == "__main__":
    main()
