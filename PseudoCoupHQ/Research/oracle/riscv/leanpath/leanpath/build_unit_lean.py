"""build_unit_lean(arch_unit, arch_opcode_leans) -- step 2.

An arch-unit is a sequence of arch-opcodes.  Every arch-opcode is a full-body
Lean expression in the emitted model (`execute_<CLAUSE>`).  So the unit's Lean
is those clauses, in order, with this unit's own operands.  Nothing is written
by hand: the constructor and its components come from the model's own
assembly clause (`from_asm`), and the clause bodies are Sail's.

    python3 -m leanpath.build_unit_lean <LeanIM dir> <units.json> <out dir>
"""
import collections
import json
import os
import re
import sys

from . import from_asm

HEAD = """-- generated by leanpath/build_unit_lean.py
-- step 2: compiler-operators, lowered to arch-units, in Lean with full body
import LeanIM.Model
open LeanIM
open LeanIM.Functions
set_option maxRecDepth 100000
"""


def lean_name(unit):
    return "unit_" + re.sub(r"[^A-Za-z0-9_]", "_", unit)


def qualify(comp):
    """`regidx.Regidx 0x0a#5` is `LeanIM.regidx.Regidx ...`; `.SLTIU` and a
    bare literal are already fine under `open LeanIM`."""
    if (comp.startswith(".") or comp.startswith("0x")
            or comp.startswith("0b") or comp.startswith("{")
            or comp in ("true", "false")
            or re.match(r"^\d+$", comp)):
        return comp
    return "LeanIM." + comp


SIG = re.compile(r'^def execute_([A-Za-z0-9_]+) .*?: (SailM )?ExecutionResult',
                 re.M)


def clause_kinds(lean_dir):
    """clause -> True when its body is monadic.  Sail emits some execute
    clauses pure (`: ExecutionResult`) and some in SailM; a unit made of both
    has to bind each in the right way."""
    text = from_asm.model_text(lean_dir)
    return {m.group(1): bool(m.group(2)) for m in SIG.finditer(text)}


def unit_lean(unit, reader, kinds):
    calls = []
    words = unit.get("words") or [None] * len(unit["body"])
    for line, word in zip(unit["body"], words):
        ctor, comps, why = reader.read(line, word)
        if ctor is None:
            return None, why
        args = " ".join("(%s)" % qualify(c) for c in comps)
        calls.append(("execute_%s" % ctor, args, line.strip()))
    # the whole emitted model sits in a `noncomputable section`
    body = ["noncomputable def %s : SailM ExecutionResult := do"
            % lean_name(unit["unit"])]
    for i, (fn, args, asm) in enumerate(calls):
        monadic = kinds.get(fn[len("execute_"):], True)
        last = i == len(calls) - 1
        if last:
            call = "%s %s" % (fn, args) if monadic else "pure (%s %s)" % (fn, args)
            lead = "  "
        else:
            lead = "  let _ ← " if monadic else "  let _ := "
            call = "%s %s" % (fn, args)
        body.append("%s%s%s-- %s" % (lead, call,
                                     " " * max(1, 36 - len(call)), asm))
    return "\n".join(body), None


def main():
    lean_dir, units_json, out_dir = sys.argv[1:4]
    reader = from_asm.Reader(lean_dir)
    kinds = clause_kinds(lean_dir)
    print("  execute clauses: %d monadic, %d pure"
          % (sum(1 for v in kinds.values() if v),
             sum(1 for v in kinds.values() if not v)))
    units = json.load(open(units_json))["units"]
    os.makedirs(out_dir, exist_ok=True)
    per_lang = collections.defaultdict(list)
    built, refused = [], collections.Counter()
    why_first = {}
    for u in units:
        text, why = unit_lean(u, reader, kinds)
        if text is None:
            words = u.get("words") or [None] * len(u["body"])
            mn = [l.strip().split()[0] for l, w in zip(u["body"], words)
                  if reader.read(l, w)[0] is None]
            key = mn[0] if mn else "?"
            refused[key] += 1
            why_first.setdefault(key, why)
            continue
        per_lang[u["lang"]].append(text)
        built.append(u["unit"])
    modules = []
    for lang, texts in sorted(per_lang.items()):
        mod = "Unit" + lang.capitalize()
        open(os.path.join(out_dir, mod + ".lean"), "w").write(
            HEAD + "\n" + "\n\n".join(texts) + "\n")
        modules.append(mod)
        print("  %-6s %4d arch-units  %s.lean" % (lang, len(texts), mod))
    open(os.path.join(out_dir, "All.lean"), "w").write(
        "\n".join("import Units." + m for m in modules) + "\n")
    print("  built %d of %d; refused %d" % (len(built), len(units),
                                            sum(refused.values())))
    for k, n in refused.most_common(10):
        print("    %-14s %4d   %s" % (k, n, (why_first.get(k) or "")[:70]))
    json.dump({"built": built, "refused": dict(refused),
               "modules": modules,
               "assembly_clauses_readable": len(reader.rules),
               "assembly_clauses_unreadable": len(reader.unreadable)},
              open(os.path.join(out_dir, "_built.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
