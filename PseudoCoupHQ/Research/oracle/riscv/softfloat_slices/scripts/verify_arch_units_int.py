def gen_stream_go(u):
    tags, edges, total = plan(u)
    n = len(tags)
    idx = u["index"]
    L = []
    for i, e in enumerate(edges):
        L.append("var e_%03d_%d = []uint64{%s}"
                 % (idx, i, ",".join("0x%x" % v for v in e)))
    L += ["func stream_%03d() {" % idx,
          "\tbuf := make([]uint64, 0, %d)" % total,
          "\tflg := make([]byte, 0, %d)" % total,
          "\tvar %s uint64" % ", ".join("c%d" % i for i in range(n)),
          "\t_ = c0",
          "\tseed()"]
    body = ("\t\tvv, ff := ref_%03d(%s); buf = append(buf, vv);"
            " flg = append(flg, ff)"
            % (idx, ", ".join("c%d" % i for i in range(n))))
    for i in range(n):
        L.append("\t%sfor _, x%d := range e_%03d_%d {"
                 % ("\t" * i, i, idx, i))
    for i in range(n):
        L.append("\t%sc%d = x%d" % ("\t" * n, i, i))
    L.append(body)
    L.append("\t" + "}" * n)
    L.append("\tfor q := 0; q < %d; q++ {" % N_RAND)
