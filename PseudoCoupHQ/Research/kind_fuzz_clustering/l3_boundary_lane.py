#!/usr/bin/env python3
"""l3_boundary_lane.py -- wrap the generated bisection sources in one
sandbox lane script.  One compile per language, one run per language,
products into /out.  Build commands copied from the log-032 execution
lanes so the instruments are the same ones that made the answers.

    python3 l3_boundary_lane.py <lane-name> [lang,lang,...]
"""

import base64
import gzip
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BND = os.path.join(HERE, "bnd")
LANES = os.path.join(HERE, "lanes")
PROG = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
DROP = os.path.join(PROG, "SandboxDesign", "agent", "drop")

FILES = {
    "python": "bnd_python.py",
    "ruby": "bnd_ruby.rb",
    "php": "bnd_php.php",
    "typescript": "bnd_typescript.ts",
    "dart": "bnd_dart.dart",
    "java": "BND.java",
    "kotlin": "bnd_kotlin.kt",
    "csharp": "BND.cs",
    "go": "bnd_go.go",
    "cpp": "bnd_cpp.cpp",
    "rust": "bnd_rust.rs",
}

RUN = {
    "python": """
  python3 "$R/bnd_python.py" > /out/bnd_python.out 2> /out/bnd_python.err
""",
    "ruby": """
  ruby "$R/bnd_ruby.rb" > /out/bnd_ruby.out 2> /out/bnd_ruby.err
""",
    "php": """
  php -d memory_limit=1G "$R/bnd_php.php" > /out/bnd_php.out 2> /out/bnd_php.err
""",
    "typescript": """
  cat > "$R/tr.js" <<'JS'
const ts = require('/persist/tv/ts5/node_modules/typescript/lib/typescript.js');
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8');
const o = ts.transpileModule(src, {compilerOptions: {target: 'ES2020'}});
fs.writeFileSync(process.argv[3], o.outputText);
JS
  node "$R/tr.js" "$R/bnd_typescript.ts" "$R/bnd_typescript.js" \\
      > /out/bnd_typescript.build 2>&1
  node "$R/bnd_typescript.js" > /out/bnd_typescript.out \\
      2> /out/bnd_typescript.err
""",
    "dart": """
  /persist/dart-sdk/bin/dart compile exe "$R/bnd_dart.dart" -o "$R/dartbin" \\
      > /out/bnd_dart.build 2>&1 &&
  "$R/dartbin" > /out/bnd_dart.out 2> /out/bnd_dart.err
""",
    "java": """
  javac -nowarn -d "$R/cls" "$R/BND.java" > /out/bnd_java.build 2>&1 &&
  java -cp "$R/cls" BND > /out/bnd_java.out 2> /out/bnd_java.err
""",
    "kotlin": """
  /persist/kotlinc/bin/kotlinc -nowarn -d "$R/kcls" "$R/bnd_kotlin.kt" \\
      > /out/bnd_kotlin.build 2>&1 &&
  java -cp "$R/kcls:/persist/kotlinc/lib/kotlin-stdlib.jar" Bnd_kotlinKt \\
      > /out/bnd_kotlin.out 2> /out/bnd_kotlin.err
""",
    "csharp": """
  REFD=$(ls -d /persist/dotnet/packs/Microsoft.NETCore.App.Ref/*/ref/net* | tail -1)
  CSC=$(ls /persist/dotnet/sdk/*/Roslyn/bincore/csc.dll | tail -1)
  VER=$(echo "$REFD" | awk -F/ '{print $(NF-2)}')
  TFM=$(echo "$REFD" | awk -F/ '{print $NF}')
  printf '{"runtimeOptions":{"tfm":"%s","framework":{"name":"Microsoft.NETCore.App","version":"%s"}}}' \\
      "$TFM" "$VER" > "$R/BND.runtimeconfig.json"
  REFS=""
  for f in "$REFD"/*.dll; do REFS="$REFS -reference:$f"; done
  /persist/dotnet/dotnet exec "$CSC" -nologo -nowarn:CS0168 \\
      -out:"$R/BND.dll" -target:exe $REFS "$R/BND.cs" \\
      > /out/bnd_csharp.build 2>&1 &&
  /persist/dotnet/dotnet "$R/BND.dll" > /out/bnd_csharp.out \\
      2> /out/bnd_csharp.err
""",
    "go": """
  mkdir -p "$R/gomod" && cp "$R/bnd_go.go" "$R/gomod/main.go"
  ( cd "$R/gomod" && go build -o "$R/gobin" main.go ) \\
      > /out/bnd_go.build 2>&1 &&
  "$R/gobin" > /out/bnd_go.out 2> /out/bnd_go.err
""",
    "cpp": """
  g++ -std=c++20 -O0 -w -o "$R/cppbin" "$R/bnd_cpp.cpp" \\
      > /out/bnd_cpp.build 2>&1 &&
  "$R/cppbin" > /out/bnd_cpp.out 2> /out/bnd_cpp.err
""",
    "rust": """
  rustc -C debug-assertions=on -C opt-level=0 -A warnings \\
      -o "$R/rustbin" "$R/bnd_rust.rs" > /out/bnd_rust.build 2>&1 &&
  "$R/rustbin" > /out/bnd_rust.out 2> /out/bnd_rust.err
""",
}


def main():
    name = sys.argv[1]
    langs = sys.argv[2].split(",") if len(sys.argv) > 2 else list(FILES)
    out = ["#!/bin/sh",
           "# log 042 -- BOUNDARY bisection lane -- generated by "
           "l3_boundary_lane.py.",
           "set -u",
           "export HOME=/work",
           "export GO111MODULE=off",
           "export GOFLAGS=-mod=mod",
           "export GOCACHE=/work/.gocache",
           "export GOPATH=/work/.gopath",
           "export PATH=/persist/dart-sdk/bin:/persist/dotnet:$PATH",
           "export DOTNET_CLI_TELEMETRY_OPTOUT=1",
           "export DOTNET_NOLOGO=1",
           'R=/work/%s' % name,
           'rm -rf "$R"; mkdir -p "$R"',
           'echo "=== boundary bisection -- %s ==="' % " ".join(langs),
           "date -u +%Y-%m-%dT%H:%M:%SZ",
           "df -Pm /work | awk 'NR==2{print \"free /work: \" $4 \" MB\"}'"]
    for lang in langs:
        f = FILES[lang]
        src = open(os.path.join(BND, f), "rb").read()
        blob = base64.b64encode(gzip.compress(src)).decode()
        out.append("base64 -d <<'S_EOF' | gunzip > \"$R/%s\"" % f)
        for i in range(0, len(blob), 76):
            out.append(blob[i:i + 76])
        out.append("S_EOF")
    for lang in langs:
        out.append('echo "--- %s ---"; date -u +%%H:%%M:%%S' % lang)
        out.append('T0=$(date +%s)')
        out.append("(" + RUN[lang].strip() + "\n) ; rc=$?")
        out.append('T1=$(date +%s)')
        out.append('echo "%s rc=$rc elapsed=$((T1-T0))s"' % lang)
        out.append('tail -3 /out/bnd_%s.err 2>/dev/null' % lang)
        out.append('echo "lines: $(wc -l < /out/bnd_%s.out 2>/dev/null)"'
                   % lang)
    out.append('echo "=== lane done ==="')
    out.append("date -u +%Y-%m-%dT%H:%M:%SZ")
    text = "\n".join(out) + "\n"
    p = os.path.join(LANES, name + ".sh")
    open(p, "w").write(text)
    open(os.path.join(DROP, name + ".sh"), "w").write(text)
    print("wrote %s (%d bytes) and dropped it" % (p, len(text)))


if __name__ == "__main__":
    main()
