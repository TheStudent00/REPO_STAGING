#!/bin/bash
# L1 lane 13 —
#   [1/3] the renderer theorem's build output IN FULL, so each open case can
#         be named by the goal Lean is actually left holding
#   [2/3] the operator census again, after a tokenizer fix: the earlier form
#         matched a RUN of symbol characters, so `2*~x` counted as one token
#         `*~` instead of a multiply and a complement
#   [3/3] the 16-bit division identity once more with BOTH ceilings raised --
#         the SAT solver's to 600 s and the elaborator's heartbeat limit off
#         entirely, because at 600 s the 16-bit run stopped on the heartbeat
#         limit rather than on the solver
set -u
LEANDIR=PseudoCoupHQ/Research/op_pipeline/lean
export HOME=/work/L1home
mkdir -p "$HOME"

echo '[1/3] Render.lean build output, in full'
cd "$LEANDIR/archproof" || exit 1
lean Archproof/Render.lean > /work/render3_out.txt 2>&1
echo "--- lean exit $?"
grep -v 'linter.unusedSimpArgs\|Hint: Omit it\|^$' /work/render3_out.txt | head -160

echo '[2/3] the operator census, tokenizer fixed'
python3 "$LEANDIR/edges_L1.py" emitted 2>&1 | tail -45

echo '[3/3] the 16-bit division identity, both ceilings raised'
mkdir -p "$LEANDIR/archproof/Edges"
cat > "$LEANDIR/archproof/Edges/divide_identity_16_nolimit.lean" <<'LEAN'
-- generated by Research/op_pipeline/lean/lanes_L1/L1_l13_render_errors_and_heartbeats.sh
import Std.Tactic.BVDecide

set_option maxHeartbeats 0 in
theorem divide_identity_16_nolimit (a b : BitVec 16) :
    (if b == (0#16) then true else (((a / b) * b + a % b) == a)) = true := by
  bv_decide (config := { timeout := 600 })
LEAN
echo '--- the theorem, LITERAL'
cat "$LEANDIR/archproof/Edges/divide_identity_16_nolimit.lean"
python3 - <<'PY'
import resource, subprocess, time
t0 = time.time()
p = subprocess.Popen(["lean", "Edges/divide_identity_16_nolimit.lean"],
                     cwd="PseudoCoupHQ/Research/op_pipeline/lean/archproof",
                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
out, _ = p.communicate()
wall = time.time() - t0
peak = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
print("exit %s  wall %.1f s  child peak %.1f MB" % (p.returncode, wall, peak / 1024.0))
print(out.decode("utf-8", "replace").strip() or "(no output: the theorem was accepted)")
PY
echo "--- exit $?"
