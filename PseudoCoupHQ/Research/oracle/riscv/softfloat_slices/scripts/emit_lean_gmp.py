"""Step 1.2 -- GMP slice insertion.

The Sail RISC-V model in Lean is body-full everywhere except 67 `axiom`
declarations in RiscvExtras.lean: the Berkeley SoftFloat externals.  Each one
has a type and no body.  This writes the bodies, from the flattened slices,
over the 23 GMP primitives -- no float definition is assumed and none is
written by hand.

    LeanIM/Gmp/Helpers.lean   the four intrinsics BitVec has no spelling for
    LeanIM/Gmp/<Op>.lean      one file per sliced operation, 10 defs each
                              (5 rounding modes x {value, flags})
    LeanIM/Gmp.lean           the import list
    RiscvExtras.lean          `axiom riscv_X : T`  ->  `def riscv_X ... := ...`

Usage: python3 emit_lean_gmp.py <path to the LeanIM directory>
"""
import os
import re
import sys

import emit_emulations as E

HERE = os.path.dirname(os.path.abspath(__file__))
FLAT = os.path.join(os.path.dirname(HERE), "flattened")
MODES = [0, 1, 2, 3, 4]

AXIOM = re.compile(r"^axiom (riscv_\w+) : (.+)$", re.M)


# ------------------------------------------------------------------ names ---
def norm(s):
    """f16MulAdd and f16_mulAdd are the same operation."""
    return s.replace("_", "").lower()


def slice_ops():
    ops = set()
    for f in os.listdir(FLAT):
        if f.endswith(".flat.ll"):
            ops.add(f.split(".")[0])
    return sorted(ops)


def lean_name(op):
    return "".join(p[:1].upper() + p[1:] for p in op.split("_"))


# ---------------------------------------------------------------- helpers ---
HELPERS = '''-- generated by scripts/emit_lean_gmp.py
-- The four LLVM intrinsics the slices call that Lean's BitVec has no spelling
-- for.  Every don't-care is pinned to the same reading the C, C++, Rust, Go,
-- Java, Python, Ruby and JavaScript emulations carry, which scripts/pin_probe.sh
-- shows is unobservable: ctlz 0 is the width, abs of the most negative value is
-- itself, a funnel shift takes its amount modulo the width.
namespace LeanIM.Gmp

def sfCtlzGo (x : Nat) (w : Nat) : Nat -> Nat
  | 0 => w
  | (k + 1) => if (x >>> k) &&& 1 == 1 then w - (k + 1) else sfCtlzGo x w k

def sfCtlz {w : Nat} (x : BitVec w) : BitVec w :=
  BitVec.ofNat w (sfCtlzGo x.toNat w w)

def sfAbs {w : Nat} (x : BitVec w) : BitVec w :=
  if BitVec.slt x (0 : BitVec w) then (0 : BitVec w) - x else x

def sfUsubsat {w : Nat} (x y : BitVec w) : BitVec w :=
  if BitVec.ult x y then (0 : BitVec w) else x - y

def sfFshl {w : Nat} (a b c : BitVec w) : BitVec w :=
  let s := c.toNat % w
  (a <<< s) ||| (b >>> (w - s))

end LeanIM.Gmp
'''


# ------------------------------------------------------------------- slice --
def slice_lean(op, mode, variant, be):
    path = os.path.join(FLAT, "%s.rm%d.%s.flat.ll" % (op, mode, variant))
    fn = E.dce(E.parse(path))
    entry = "%s_rm%d_%s" % (op, mode, variant)
    text = E.emit(fn, be, entry)
    sig = {"params": [E.WIDTH[t] for _, t in fn["params"]],
           "ret": E.WIDTH[fn["ret"]],
           "insts": len(fn["insts"])}
    return text.strip("\n"), sig


# ----------------------------------------------------------------- wrapper --
def split_arrow(ty):
    """`BitVec 3 -> BitVec 64 -> (BitVec 5 x BitVec 64)` -> args, result."""
    parts = [p.strip() for p in ty.split("→")]
    return parts[:-1], parts[-1]


def arg_width(t):
    m = re.match(r"BitVec (\d+)$", t)
    return int(m.group(1)) if m else None      # None means Bool


def coerce_in(name, axty, want):
    if arg_width(axty) is None:                # Bool -> BitVec 1
        return "(BitVec.ofBool %s)" % name
    return "(BitVec.setWidth %d %s)" % (want, name)


def coerce_out(expr, axty):
    if arg_width(axty) is None:                # BitVec 1 -> Bool
        return "(%s != 0#1)" % expr
    return "(BitVec.setWidth %d %s)" % (arg_width(axty), expr)


def wrapper(name, ty, op, sigs):
    args, res = split_arrow(ty)
    rm = re.match(r"\(BitVec 5 × (.+)\)$", res)
    if not rm:
        raise ValueError("unexpected result %r for %s" % (res, name))
    vty = rm.group(1).strip()
    nslice = len(sigs[0]["params"])
    has_rm = len(args) - nslice == 1
    if not has_rm and len(args) != nslice:
        raise ValueError("%s: %d axiom args, %d slice params"
                         % (name, len(args), nslice))
    take = args[1:] if has_rm else args
    names = ["a%d" % i for i in range(len(take))]

    L = ["def %s %s : %s :=" % (
        name,
        " ".join("(%s : %s)" % (n, t) for n, t in
                 ([("rm", args[0])] if has_rm else []) + list(zip(names, take))),
        res)]
    for i, (n, t) in enumerate(zip(names, take)):
        L.append("  let x%d := %s" % (i, coerce_in(n, t, sigs[0]["params"][i])))
    call = " ".join("x%d" % i for i in range(len(names)))

    def pair(mode):
        return "(%s, %s)" % (
            "BitVec.setWidth 5 (%s_rm%d_flags %s)" % (op, mode, call),
            "(%s_rm%d_value %s) != 0#1" % (op, mode, call)
            if arg_width(vty) is None
            else "BitVec.setWidth %d (%s_rm%d_value %s)"
                 % (arg_width(vty), op, mode, call))

    if has_rm:
        for mode in MODES[:-1]:
            L.append("  %sif rm = %d#3 then" % ("" if mode == 0 else "else ",
                                                mode))
            L.append("    %s" % pair(mode))
        L.append("  else")
        L.append("    %s" % pair(MODES[-1]))
    else:
        L.append("  %s" % pair(MODES[0]))
    return "\n".join(L)


# -------------------------------------------------------------------- main --
def main():
    leanim = sys.argv[1]
    extras = os.path.join(leanim, "RiscvExtras.lean")
    src = open(extras).read()
    axioms = [(m.group(1), m.group(2).strip()) for m in AXIOM.finditer(src)]
    floats = [(n, t) for n, t in axioms if re.match(r"riscv_(f|i\d|ui\d)", n)]

    ops = slice_ops()
    by_norm = {norm(o): o for o in ops}
    pairs, missing = [], []
    for n, t in floats:
        key = norm(n[len("riscv_"):])
        if key in by_norm:
            pairs.append((n, t, by_norm[key]))
        else:
            missing.append(n)
    if missing:
        print("NO SLICE for: %s" % " ".join(missing))

    be = E.LeanBackend()
    gmp = os.path.join(leanim, "Gmp")
    os.makedirs(gmp, exist_ok=True)
    open(os.path.join(gmp, "Helpers.lean"), "w").write(HELPERS)

    total_insts, wraps, imports = 0, [], ["import LeanIM.Gmp.Helpers"]
    for name, ty, op in pairs:
        chunks = ["-- generated by scripts/emit_lean_gmp.py",
                  "import LeanIM.Gmp.Helpers",
                  "set_option maxRecDepth 8000000",
                  "namespace LeanIM.Gmp", ""]
        sigs = []
        for mode in MODES:
            for variant in ("value", "flags"):
                text, sig = slice_lean(op, mode, variant, be)
                chunks.append(text)
                chunks.append("")
                total_insts += sig["insts"]
                if variant == "value":
                    sigs.append(sig)
        chunks.append("end LeanIM.Gmp")
        mod = lean_name(op)
        open(os.path.join(gmp, mod + ".lean"), "w").write("\n".join(chunks))
        imports.append("import LeanIM.Gmp." + mod)
        wraps.append(wrapper(name, ty, op, sigs))
        print("%-18s %-22s %6d insts" % (op, name, sum(s["insts"] for s in sigs)))

    body = ["-- generated by scripts/emit_lean_gmp.py",
            "-- Step 1.2: the bodies of the 67 SoftFloat axioms, from the",
            "-- flattened slices, over the 24 GMP primitives."] + imports + [
            "", "set_option maxRecDepth 8000000", "open LeanIM.Gmp", ""]
    body += ["\n".join(wraps), ""]
    open(os.path.join(leanim, "Gmp.lean"), "w").write("\n".join(body))

    # the axioms these bodies replace: drop the declaration, import the body
    named = {p[0] for p in pairs}
    out, dropped = [], 0
    for line in src.split("\n"):
        m = re.match(r"^axiom (riscv_\w+) :", line)
        if m and m.group(1) in named:
            dropped += 1
            continue
        out.append(line)
    patched = "\n".join(out)
    if "import LeanIM.Gmp\n" not in patched:
        patched = patched.replace("import LeanIM.Defs\n",
                                  "import LeanIM.Defs\nimport LeanIM.Gmp\n", 1)
    open(extras, "w").write(patched)
    print("RiscvExtras.lean: %d axioms dropped, LeanIM.Gmp imported" % dropped)

    root = os.path.join(os.path.dirname(leanim), "LeanIM.lean")
    if os.path.exists(root):
        rs = open(root).read()
        add = [l for l in imports if l + "\n" not in rs]
        if add:
            open(root, "w").write("\n".join(add) + "\n" + rs)
            print("LeanIM.lean: %d modules added" % len(add))

    kept = [n for n, _ in axioms if n not in named]
    print("\n%d axioms, %d float, %d given a body, %d left: %s"
          % (len(axioms), len(floats), len(pairs), len(kept), " ".join(kept)))
    print("%d IR instructions walked into Lean" % total_insts)


if __name__ == "__main__":
    main()
