#!/usr/bin/env python3
"""inject_diary_region.py -- the EDIT half of `Graph.diary`'s producer,
widened from one hand-picked neighbourhood to the whole go lowering
region.

Plan node: hq.research.compiler_graph.graph, method `diary`
(node_0_3_5_9_graph/CORE_0_3_5_9_graph.md).

RELATION TO THE TWO FILES IT SITS BETWEEN
-----------------------------------------
  coverage.py           SELECTS the targets (`Graph.diary_targets`),
                        on the host, from the region graph. It imports
                        graph.py, which imports tree-sitter.
  THIS FILE             places one entry hook at each selected byte
                        coordinate, inside the container, where
                        tree-sitter is not installed. Stdlib only, so
                        it can run there. It folds into coverage.py's
                        class the day the container carries the same
                        dependencies; until then a standalone edit
                        step is the honest shape, not a second copy of
                        anything -- it shares no logic with coverage.py.
  inject_diary.py       the AUGUST ancestor (56 spots, 5 files). Left
                        exactly as it is, as the record of that lap.
                        Its `diary` go package is reproduced below
                        VERBATIM so the emitted record format, the
                        per-goroutine subject stack and the
                        COMPILER_DIARY switch are identical and the
                        August diaries stay comparable to these.

WHAT IS DIFFERENT FROM THE AUGUST ANCESTOR, AND WHY
---------------------------------------------------
1. TARGETS. August: 56 spots reached by three call hops out of one
   seed file. Here: every function body of the region, 1,549 of them,
   because "the nodes no probe visits" has to be a statement about the
   region, not about a neighbourhood chosen in advance.

2. THE BODY BRACE. August's finder took the first `{` whose rest of
   line is blank. At 56 hand-checked spots that held. Over 1,549 it
   does not: a one-line body (`func f() int { return 1 }`) has no such
   brace, so the scan would run past the function and inject into the
   NEXT one. Here the scan tracks round- and square-bracket depth,
   steps over strings, runes and comments, refuses a `{` that opens a
   `struct` or `interface` type, and is BOUNDED by the node's own
   end_byte. A target whose brace is not found inside its own bytes is
   SKIPPED and recorded, never guessed.

3. REFUSAL IS RECORDED. Every target not instrumented is written to
   the skip report with its cause. The coverage join reads that report
   so a body that was never instrumented is a named frontier and is
   never counted as "no probe visited it".

THE SPELLING BAN (the owner, absolute). No operator token appears in any key,
grouping, pairing, row structure, candidate selection or comparison
scope here. Targets are keyed by source coordinate only.

Coding discipline of this node (CORE 0_3_5): no complex statements.
"""

import argparse
import collections
import json
import os
import sys


DIARY_IMPORT = "cmd/compile/internal/diary"

# Reproduced VERBATIM from inject_diary.py (August), so the emitted
# record format is byte-identical to the August diaries.
DIARY_PACKAGE = '''// Code generated by inject_diary_region.py. DO NOT EDIT.
//
// The diary: each instrumented spot of the compiler writes its own map
// node id here AS IT IS ENTERED, so the ORDER of visits survives.
// Set COMPILER_DIARY to a file path to switch it on; with the variable
// unset the compiler behaves exactly as before.

package diary

import (
	"bufio"
	"os"
	"runtime"
	"strconv"
	"sync"
)

var lock sync.Mutex
var out *os.File
var writer *bufio.Writer
var opened bool
var seq int64
var subjects = make(map[int64][]string)

func openDiary() {
	path := os.Getenv("COMPILER_DIARY")
	if path == "" {
		return
	}
	flags := os.O_CREATE
	flags = flags | os.O_WRONLY
	flags = flags | os.O_APPEND
	handle, err := os.OpenFile(path, flags, 0o644)
	if err != nil {
		return
	}
	out = handle
	writer = bufio.NewWriterSize(handle, 1<<20)
}

// Flush is called from the compiler's exit path. Without it the last
// buffered lines of a diary are lost, and a diary that stops early is
// a diary that lies about the order it recorded.
func Flush() {
	lock.Lock()
	if writer != nil {
		writer.Flush()
	}
	lock.Unlock()
}

// goroutineID reads the number off the first line of this goroutine's own
// stack dump. The compiler compiles several functions at once, so the
// subject has to be per goroutine and not one global.
func goroutineID() int64 {
	var buf [64]byte
	size := runtime.Stack(buf[:], false)
	text := string(buf[:size])
	head := "goroutine "
	if len(text) < len(head) {
		return 0
	}
	if text[:len(head)] != head {
		return 0
	}
	text = text[len(head):]
	end := 0
	for end < len(text) {
		if text[end] < '0' {
			break
		}
		if text[end] > '9' {
			break
		}
		end = end + 1
	}
	value, err := strconv.ParseInt(text[:end], 10, 64)
	if err != nil {
		return 0
	}
	return value
}

func writeEvent(record string, subject string) {
	lock.Lock()
	if !opened {
		opened = true
		openDiary()
	}
	if writer == nil {
		lock.Unlock()
		return
	}
	seq++
	line := strconv.FormatInt(seq, 10)
	line = line + "\\t"
	line = line + subject
	line = line + "\\t"
	line = line + record
	line = line + "\\n"
	writer.WriteString(line)
	lock.Unlock()
}

func currentSubject(id int64) string {
	lock.Lock()
	stack := subjects[id]
	subject := "-"
	if len(stack) > 0 {
		subject = stack[len(stack)-1]
	}
	lock.Unlock()
	return subject
}

// Note writes one diary event. The record is fixed at injection time and
// carries the map node id, the spot's name, and its original file:line.
func Note(record string) {
	id := goroutineID()
	subject := currentSubject(id)
	writeEvent(record, subject)
}

// Enter opens a subject for the calling goroutine and returns the func that
// closes it. Injected as a single statement: defer diary.Enter(...)().
func Enter(spot string, subject string) func() {
	if subject == "" {
		subject = "?"
	}
	id := goroutineID()
	lock.Lock()
	stack := subjects[id]
	stack = append(stack, subject)
	subjects[id] = stack
	lock.Unlock()
	record := "-|subject_enter:" + spot + "|-"
	writeEvent(record, subject)
	return func() {
		leave(id)
	}
}

func leave(id int64) {
	lock.Lock()
	stack := subjects[id]
	if len(stack) > 0 {
		stack = stack[:len(stack)-1]
	}
	if len(stack) == 0 {
		delete(subjects, id)
	} else {
		subjects[id] = stack
	}
	lock.Unlock()
}
'''

# The subject spots, unchanged from inject_diary.py (August). A diary
# event says WHICH SPOT ran; the subject says WHOSE code the compiler
# had in hand when it ran.
SUBJECT_SPOTS = (
    {
        "file": "src/cmd/compile/internal/ssagen/ssa.go",
        "anchor": "func buildssa(fn *ir.Func, worker int, isPgoHot bool) *ssa.Func {",
        "label": "buildssa",
        "expr": "fn.Sym().Name",
    },
    {
        "file": "src/cmd/compile/internal/ssagen/ssa.go",
        "anchor": "func genssa(f *ssa.Func, pp *objw.Progs) {",
        "label": "genssa",
        "expr": "f.Name",
    },
    {
        "file": "src/cmd/compile/internal/gc/compile.go",
        "anchor": "func enqueueFunc(fn *ir.Func, symABIs *ssagen.SymABIs) {",
        "label": "enqueueFunc",
        "expr": "fn.Sym().Name",
    },
)

# Where the compiler's own exit path is, so the buffer is flushed.
# cmd/compile/main.go ends `gc.Main(archInit); base.Exit(0)`, and every
# error path calls base.Exit too, so this is THE exit. Without the flush
# the last buffered lines of a diary are lost, and a diary that stops
# early lies about the order it recorded.
FLUSH_SPOT = {
    "file": "src/cmd/compile/internal/base/base.go",
    "anchor": "func Exit(code int) {",
}


# ------------------------------------------------------- the brace scan --
#
# EVERYTHING BELOW WORKS ON BYTES, NOT ON TEXT. The region graph records
# start_byte / end_byte, and several files of this region contain
# non-ASCII characters (magic.go's comments use the mathematical ceiling
# brackets, three bytes each). Indexing a decoded string with a byte
# offset lands in the wrong place in exactly those files, silently, and
# a mis-placed edit would inject into a NEIGHBOURING function -- which is
# the one failure this pass must not have. Found by the first dry run: 75
# targets reported "no body brace in own bytes" and every one of them was
# a correctly-formed one-line body in a file with non-ASCII above it.


def find_body_brace(text, start, limit):
    """Index of the `{` that opens the body of the declaration at
    `start`, or -1. `text` is BYTES; `limit` is the declaration's own
    end byte.

    Tracks round- and square-bracket depth so a `{` inside a parameter
    list or a type argument list is not mistaken for the body; steps
    over string, raw-string, rune and comment text; and refuses a brace
    that opens a `struct` or `interface` type literal.
    """
    index = start
    round_depth = 0
    square_depth = 0
    while index < limit:
        char = text[index:index + 1]
        if char == b"/" and index + 1 < limit:
            following = text[index + 1:index + 2]
            if following == b"/":
                stop = text.find(b"\n", index)
                if stop < 0:
                    return -1
                index = stop + 1
                continue
            if following == b"*":
                stop = text.find(b"*/", index)
                if stop < 0:
                    return -1
                index = stop + 2
                continue
        if char == b'"' or char == b"'" or char == b"`":
            index = skip_quoted(text, index, limit)
            continue
        if char == b"(":
            round_depth = round_depth + 1
        elif char == b")":
            round_depth = round_depth - 1
        elif char == b"[":
            square_depth = square_depth + 1
        elif char == b"]":
            square_depth = square_depth - 1
        elif char == b"{":
            if round_depth == 0:
                if square_depth == 0:
                    if not opens_a_type_literal(text, index):
                        return index
        index = index + 1
    return -1


def skip_quoted(text, index, limit):
    """Index just past the string, raw string or rune starting at index."""
    quote = text[index:index + 1]
    index = index + 1
    while index < limit:
        char = text[index:index + 1]
        if char == b"\\" and quote != b"`":
            index = index + 2
            continue
        if char == quote:
            return index + 1
        index = index + 1
    return limit


def opens_a_type_literal(text, index):
    """True when the `{` at index opens `struct{...}` or `interface{...}`."""
    probe = index - 1
    while probe >= 0 and text[probe:probe + 1] in (b" ", b"\t", b"\n"):
        probe = probe - 1
    for word in (b"struct", b"interface"):
        start = probe - len(word) + 1
        if start < 0:
            continue
        if text[start:probe + 1] == word:
            return True
    return False


# ------------------------------------------------------- the import edit --

def add_import(text):
    """Add the diary import to BYTES. Returns (text, added, how)."""
    quoted = b'"' + DIARY_IMPORT.encode() + b'"'
    if quoted in text:
        return text, True, "already_present"
    marker = b"\nimport (\n"
    at = text.find(marker)
    if at >= 0:
        cut = at + len(marker)
        line = b"\t" + quoted + b"\n"
        return text[:cut] + line + text[cut:], True, "block"
    at = text.find(b'\nimport "')
    if at >= 0:
        stop = text.find(b"\n", at + 1)
        single = text[at + 1:stop]
        block = b"import (\n\t" + single[len(b"import "):] + b"\n\t" \
            + quoted + b"\n)"
        return text[:at + 1] + block + text[stop:], True, "single_to_block"
    at = text.find(b"\npackage ")
    if at < 0:
        return text, False, "no_package_clause"
    stop = text.find(b"\n", at + 1)
    block = b"\n\nimport (\n\t" + quoted + b"\n)\n"
    return text[:stop] + block + text[stop:], True, "new_block"


# ------------------------------------------------------------- the pass --

def inject(targets_path, src_root, report_path, dry_run):
    handle = open(targets_path)
    targets = json.load(handle)
    handle.close()

    by_file = collections.defaultdict(list)
    for record in targets:
        by_file[record["file"]].append(record)

    package_dir = os.path.join(src_root, "cmd", "compile", "internal", "diary")
    package_file = os.path.join(package_dir, "diary.go")
    if not dry_run:
        os.makedirs(package_dir, exist_ok=True)
        handle = open(package_file, "w")
        handle.write(DIARY_PACKAGE)
        handle.close()
    print("diary package: %s" % package_file)

    subjects_by_file = collections.defaultdict(list)
    for spot in SUBJECT_SPOTS:
        subjects_by_file[spot["file"]].append(spot)

    touched = set(by_file)
    touched |= set(subjects_by_file)
    touched.add(FLUSH_SPOT["file"])

    instrumented = []
    skipped = []
    subject_count = 0

    for rel_path in sorted(touched):
        records = by_file.get(rel_path, [])
        spots = subjects_by_file.get(rel_path, [])
        trimmed = rel_path
        if trimmed.startswith("src/"):
            trimmed = trimmed[4:]
        full = os.path.join(src_root, trimmed)
        if not os.path.exists(full):
            for record in records:
                skipped.append(dict(record, cause="file_not_on_disk"))
            continue
        handle = open(full, "rb")
        text = handle.read()
        handle.close()

        if b"diary.Note(" in text or b"diary.Enter(" in text:
            for record in records:
                skipped.append(dict(record, cause="already_instrumented"))
            print("SKIP already instrumented: %s" % full)
            continue

        edits = []
        for record in records:
            limit = record.get("end_byte") or len(text)
            if limit > len(text):
                limit = len(text)
            brace = find_body_brace(text, record["start_byte"], limit)
            if brace < 0:
                skipped.append(dict(record, cause="no_body_brace_in_own_bytes"))
                continue
            payload = record["id"]
            payload = payload + "|" + record["name"]
            payload = payload + "|" + rel_path
            payload = payload + ":" + str(record["start_line"])
            statement = ('\n\tdiary.Note("' + payload + '")\n').encode()
            edits.append((brace + 1, statement))
            instrumented.append(record)

        for spot in spots:
            at = text.find(spot["anchor"].encode())
            if at < 0:
                print("NO ANCHOR in %s: %s" % (full, spot["anchor"]))
                sys.exit(5)
            brace = find_body_brace(text, at, len(text))
            if brace < 0:
                print("NO BODY BRACE for subject spot %s" % spot["label"])
                sys.exit(3)
            statement = '\n\tdefer diary.Enter("' + spot["label"] + '", '
            statement = statement + spot["expr"] + ')()\n'
            statement = statement.encode()
            edits.append((brace + 1, statement))
            subject_count = subject_count + 1

        if rel_path == FLUSH_SPOT["file"]:
            at = text.find(FLUSH_SPOT["anchor"].encode())
            if at < 0:
                print("NO FLUSH ANCHOR in %s" % full)
                sys.exit(6)
            brace = find_body_brace(text, at, len(text))
            edits.append((brace + 1, b'\n\tdiary.Flush()\n'))

        if not edits:
            continue

        edits.sort(key=lambda item: item[0], reverse=True)
        for offset, statement in edits:
            text = text[:offset] + statement + text[offset:]

        text, added, how = add_import(text)
        if not added:
            print("NO IMPORT SITE in %s (%s)" % (full, how))
            sys.exit(4)

        if not dry_run:
            handle = open(full, "wb")
            handle.write(text)
            handle.close()
        print("instrumented %4d bodies (+%d subject, import %s) in %s"
              % (len(records) - 0, len(spots), how, rel_path))

    report = {
        "targets_read": len(targets),
        "instrumented": len(instrumented),
        "skipped": len(skipped),
        "subject_spots": subject_count,
        "instrumented_ids": [record["id"] for record in instrumented],
        "skipped_records": skipped,
    }
    if report_path:
        handle = open(report_path, "w")
        json.dump(report, handle, indent=1)
        handle.write("\n")
        handle.close()
    print("targets read : %d" % report["targets_read"])
    print("instrumented : %d" % report["instrumented"])
    print("skipped      : %d" % report["skipped"])
    causes = collections.Counter(
        record["cause"] for record in skipped
    )
    for cause, count in sorted(causes.items()):
        print("   %-32s %d" % (cause, count))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--targets", required=True)
    parser.add_argument("--src", required=True)
    parser.add_argument("--report", default="")
    parser.add_argument("--dry-run", action="store_true")
    arguments = parser.parse_args()
    inject(arguments.targets, arguments.src, arguments.report,
           arguments.dry_run)


if __name__ == "__main__":
    main()
