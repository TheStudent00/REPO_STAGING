def build_rust(units, work):
    rl = os.path.join(work, "rlib")
    os.makedirs(rl, exist_ok=True)
    must(["rustc", "-O", "--edition", "2021", "--crate-type=rlib",
          "--crate-name", "archunits_int",
          os.path.join(OUT, "rust", "lib_int.rs"),
          "--out-dir", rl, "-A", "warnings"], "rustc archunits_int")
    h = os.path.join(work, "h_rust.rs")
    open(h, "w").write(gen_harness_rust(units))
    must(["rustc", "-O", "--edition", "2021", h,
          "--extern", "archunits_int=" + os.path.join(rl,
                                                      "libarchunits_int.rlib"),
          "-L", "dependency=" + rl,
          "-o", os.path.join(work, "h_rust"), "-A", "warnings"],
         "rustc h_rust")


