#!/usr/bin/env python3
"""mirror_lane.py -- build the Airlock lane that runs the third
candidate rule, rebuilds the classes and re-runs the dom_op
construction, and fold its products back.

the owner's ruling: the run of record is a lane.  Local debugging is fine;
what is reported is what Airlock ran.

PseudoCoupHQ is not mounted in the container, so the passes, the
lifter's callers and the data travel INSIDE the lane script,
gzip+base64.  The solver and the lifter are installed from pip, the
lifter PINNED to the version the earlier tables were produced with, so
one model of the machine is used and not two.

Three passes run in order:
  1. candidates_mirror.py  -- the third candidate rule -> verdicts5
  2. dominant_table4.py    -- the classes rebuilt      -> table 4,
                              and bridges.json remapped onto the new
                              class ids (dominance.py is NOT re-run)
  3. dom_ops.py            -- the dom_op construction over table 4

dom_ops.py reads its table under the name `dominant_table3.json`.
That name is NOT changed in dom_ops.py -- the file is left untouched.
The lane stages table 4 under that name in a separate directory and
renames the products afterwards, so the artifact that ships is
`dom_ops2.json` and the earlier `dom_ops.json` is not overwritten.

usage:
  mirror_lane.py --build
  mirror_lane.py --fold
"""

import base64
import io
import json
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
KFC = os.path.join(os.path.dirname(HERE), "kind_fuzz_clustering")
_PROGRAMMING = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
AIRLOCK = os.path.join(_PROGRAMMING, "Airlock")

LANE = "pc_mirror.sh"

LANGS = ["c", "cpp", "go", "rust", "swift"]

PYVEX_PIN = "9.2.213"

PRODUCTS = ["verdicts5.json", "verdicts5.md",
            "dominant_table4.json", "dominant_table4.md",
            "bridges4.json",
            "dom_ops2.json", "dom_ops2.md", "dom_ops2_digest.md",
            "dom_ops2_digest_shape.json"]

CODE_KFC = ["arch_read.py", "arch_sem.py"]

CODE_HERE = ["sem_anchored.py", "verdicts.py", "verdicts3.py",
             "z3_ext.py", "result_vocab.py", "candidates_mirror.py",
             "dominant_table4.py", "dom_ops.py",
             "check_no_spelling_keys.py"]

DATA_HERE = ["dominant_table3.json", "bridges.json", "verdicts3b.json"]

DATA_PER_LANG = ["op_units_%s.json", "sem_anchored_%s.json",
                 "probe_manifest_%s.json", "core_modes_%s.json"]


def payload():
    buf = io.BytesIO()
    tar = tarfile.open(fileobj=buf, mode="w:gz")

    def add(path, name):
        data = open(path, "rb").read()
        info = tarfile.TarInfo(name)
        info.size = len(data)
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(data))

    for name in CODE_KFC:
        add(os.path.join(KFC, name), name)
    for name in CODE_HERE:
        add(os.path.join(HERE, name), name)
    for name in DATA_HERE:
        add(os.path.join(HERE, name), name)
    for lang in LANGS:
        for pattern in DATA_PER_LANG:
            name = pattern % lang
            add(os.path.join(HERE, name), name)
    tar.close()
    raw = buf.getvalue()
    return base64.b64encode(raw).decode("ascii"), len(raw)


HEAD = """#!/bin/sh
# pc_mirror -- THE THIRD CANDIDATE RULE, run.
#
# A unit alone in its equivalence class is nominated against every
# other class carrying the SAME class key (operand types and result
# type).  That is the rule the first two candidate rules -- shared
# bytes, shared sub-term -- cannot reach, because a condition-mirrored
# comparison shares no text with its counterpart.
#
# THE SPELLING BAN, ABSOLUTE (the owner, 2026-08-25).  No operator token
# takes part in any key, grouping, pairing, row structure, candidate
# selection or comparison scope here.  The token appears exactly once
# per unit, as a display label on the member.  Every JSON product is
# handed to check_no_spelling_keys.py and a FAIL refuses the publish.
#
# Generated by Research/op_pipeline/mirror_lane.py .  Do not hand-edit.
# PseudoCoupHQ is not mounted in the container, so the passes and the
# data travel INSIDE this script, gzip+base64 (%(size)d bytes packed).
set -u
export HOME=/work
ROOT=/work/pc_mirror
echo "=== op_pipeline -- the third candidate rule ==="
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
if ! python3 --version >/dev/null 2>&1; then
  echo "!! REFUSING TO START: python3 is not runnable in this container."
  exit 4
fi
python3 --version
rm -rf "$ROOT"; mkdir -p "$ROOT" "$ROOT/stage" /out
df -Pm /work | awk 'NR==2{print "free /work: " $4 " MB"}'
FREE=`df -Pm /work | awk 'NR==2{print $4}'`
if [ "$FREE" -lt 500 ]; then
  echo "!! REFUSING TO START: only $FREE MB free on /work, need 500"
  exit 3
fi

echo "-- installing the solver and the lifter"
python3 -m pip install --quiet --disable-pip-version-check \\
    z3-solver pyvex==%(pyvex)s archinfo==%(pyvex)s capstone 2>&1 | tail -5
if ! python3 -c "import z3, pyvex, archinfo, capstone" 2>&1; then
  echo "!! REFUSING TO CONTINUE: a dependency did not import."
  exit 4
fi
python3 -c "import z3, pyvex, archinfo, capstone; \\
print('z3', z3.get_version_string(), '/ pyvex', pyvex.__version__, \\
'/ archinfo', archinfo.__version__, '/ capstone', capstone.__version__)"

echo "-- unpacking the embedded passes and their data"
cd "$ROOT"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d > payload.tgz
md5sum payload.tgz
tar xzf payload.tgz --no-same-owner --no-same-permissions
if [ $? -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the embedded inputs did not unpack."
  exit 5
fi
rm -f payload.tgz
ls -l | awk '{print "   " $5 "  " $9}'

echo "-- the translation's own guard tests, before any pair is judged"
python3 z3_ext.py --selfcheck
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the translation failed its own guards."
  exit 5
fi

echo "-- pass 1: the third candidate rule (progress every 200 pairs)"
python3 -u candidates_mirror.py --in "$ROOT" --out "$ROOT"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the candidate pass exited $rc"
  exit $rc
fi

echo "-- pass 2: the classes rebuilt"
python3 -u dominant_table4.py --in "$ROOT" --out "$ROOT"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the table pass exited $rc"
  exit $rc
fi

echo "-- pass 3: the dom_op construction over table 4"
# dom_ops.py reads its table under the name dominant_table3.json.  The
# file is left untouched; table 4 is STAGED under that name here, and
# the products are renamed below.
cp "$ROOT/dominant_table4.json" "$ROOT/stage/dominant_table3.json"
cp "$ROOT/bridges4.json" "$ROOT/stage/bridges.json"
cp "$ROOT/verdicts3b.json" "$ROOT/stage/"
cp "$ROOT"/probe_manifest_*.json "$ROOT/stage/"
cp "$ROOT"/core_modes_*.json "$ROOT/stage/"
python3 -u dom_ops.py --in "$ROOT/stage" --out "$ROOT/stage" --every 500
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the dom_op pass exited $rc"
  exit $rc
fi
mv "$ROOT/stage/dom_ops.json"              "$ROOT/dom_ops2.json"
mv "$ROOT/stage/dom_ops.md"                "$ROOT/dom_ops2.md"
mv "$ROOT/stage/dom_ops_digest.md"         "$ROOT/dom_ops2_digest.md"
mv "$ROOT/stage/dom_ops_digest_shape.json" "$ROOT/dom_ops2_digest_shape.json"

echo "-- THE SPELLING BAN: the mechanical guard, on every product"
python3 check_no_spelling_keys.py \\
        "$ROOT/verdicts5.json" \\
        "$ROOT/dominant_table4.json" \\
        "$ROOT/bridges4.json" \\
        "$ROOT/dom_ops2.json" \\
        "$ROOT/dom_ops2_digest_shape.json"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! THE GUARD FAILED: refusing to publish these products."
  exit $rc
fi

echo "-- publishing"
for f in verdicts5.json verdicts5.md dominant_table4.json \\
         dominant_table4.md bridges4.json dom_ops2.json dom_ops2.md \\
         dom_ops2_digest.md dom_ops2_digest_shape.json; do
  cp "$ROOT/$f" /out/
done
ls -la /out
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
echo "=== pc_mirror done ==="
exit 0
__PAYLOAD__
"""


def build():
    blob, size = payload()
    head = HEAD % dict(size=size, pyvex=PYVEX_PIN)
    lines = []
    i = 0
    while i < len(blob):
        lines.append(blob[i:i + 76])
        i = i + 76
    text = head + "\n".join(lines) + "\n"
    # the established habit: the lane script is archived beside its
    # co-lanes BEFORE it is dropped.  The daemon fires on close_write,
    # so the drop is written last and nothing races it.
    archive = os.path.join(HERE, "lanes", LANE)
    fh = open(archive, "w")
    fh.write(text)
    fh.close()
    path = os.path.join(AIRLOCK, "agent", "drop", LANE)
    fh = open(path, "w")
    fh.write(text)
    fh.close()
    os.chmod(path, 0o755)
    print("packed payload  %d bytes" % size)
    print("archived        %s" % archive)
    print("lane            %s (%d bytes)" % (path, len(text)))
    return 0


def fold():
    outdir = os.path.join(AIRLOCK, "agent", "out")
    moved = 0
    for name in PRODUCTS:
        src = os.path.join(outdir, name)
        if not os.path.exists(src):
            print("!! missing from the lane output: %s" % name)
            continue
        data = open(src, "rb").read()
        dst = os.path.join(HERE, name)
        fh = open(dst, "wb")
        fh.write(data)
        fh.close()
        print("folded %s (%d bytes)" % (name, len(data)))
        moved = moved + 1
    if moved != len(PRODUCTS):
        print("!! %d of %d products folded" % (moved, len(PRODUCTS)))
        return 1
    doc = json.load(open(os.path.join(HERE, "verdicts5.json")))
    print("nominations       %d" % doc["nominations"])
    print("distinct pairs    %d" % doc["distinct_pairs"])
    print("tally             %s" % json.dumps(doc["tally"]))
    table = json.load(open(os.path.join(HERE, "dominant_table4.json")))
    print("classes           %d (was %d)"
          % (table["stats"]["classes"], table["stats"]["classes_before"]))
    print("classes of size 1 %d (was %d)"
          % (table["stats"]["classes_size_1"],
             table["stats"]["classes_size_1_before"]))
    ops = json.load(open(os.path.join(HERE, "dom_ops2.json")))
    print("dom_ops           %d" % ops["dom_op_count"])
    print("unattached nodes  %d" % ops["nodes_with_no_surviving_edge"])
    return 0


def main(argv):
    if "--build" in argv:
        return build()
    if "--fold" in argv:
        return fold()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
