#!/usr/bin/env python3
"""dom_ops_lane.py -- build the Airlock lane that runs dom_ops.py, and
fold its products back.

the owner's ruling: the run of record is a lane.  Local debugging is fine;
what is reported is what Airlock ran.  This pass is fast -- the lane is
for visibility, so the owner can watch it.

PseudoCoupHQ is not mounted in the container, so the pass and its data
travel INSIDE the lane script, gzip+base64.  Nothing is fetched: this
pass needs no solver and no lifter, only python3.

usage:
  dom_ops_lane.py --build
  dom_ops_lane.py --fold
"""

import base64
import io
import json
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
_PROGRAMMING = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
AIRLOCK = os.path.join(_PROGRAMMING, "Airlock")

LANE = "pc_dom_ops.sh"

LANGS = ["c", "cpp", "go", "rust", "swift"]

PRODUCTS = ["dom_ops.json", "dom_ops.md", "dom_ops_digest.md",
            "dom_ops_digest_shape.json"]

CODE = ["dom_ops.py", "check_no_spelling_keys.py"]

DATA = ["dominant_table3.json", "bridges.json", "verdicts3b.json"]


def payload():
    buf = io.BytesIO()
    tar = tarfile.open(fileobj=buf, mode="w:gz")

    def add_file(name):
        path = os.path.join(HERE, name)
        data = open(path, "rb").read()
        info = tarfile.TarInfo(name)
        info.size = len(data)
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(data))

    for name in CODE:
        add_file(name)
    for name in DATA:
        add_file(name)
    # the guard reads its operator inventory out of the manifests, and
    # the pass reads each probe's provenance out of them.  They are the
    # ONE place a token is authored.
    for lang in LANGS:
        add_file("probe_manifest_%s.json" % lang)
        add_file("core_modes_%s.json" % lang)
    tar.close()
    raw = buf.getvalue()
    return base64.b64encode(raw).decode("ascii"), len(raw)


HEAD = """#!/bin/sh
# pc_dom_ops -- THE DOM_OP CONSTRUCTION RULE, run.
#
# the owner, 2026-08-26: dominant operators are DISCOVERED from machine
# evidence by matching, never asserted.  Nodes are (language,
# grammar-operator, ARITY); edges only between languages, weighted by
# shared equivalence-class count; each node keeps its strongest
# counterpart per foreign language, kept only when mutual; the
# connected components are the dominant operators.
#
# Generated by Research/op_pipeline/dom_ops_lane.py .  Do not
# hand-edit.  PseudoCoupHQ is not mounted in the container, so the pass
# and its data travel INSIDE this script, gzip+base64 (%(size)d bytes
# packed).  Products land in /out.
set -u
export HOME=/work
ROOT=/work/pc_dom_ops
echo "=== op_pipeline -- the dominant operators ==="
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
if ! python3 --version >/dev/null 2>&1; then
  echo "!! REFUSING TO START: python3 is not runnable in this container."
  exit 4
fi
python3 --version
rm -rf "$ROOT"; mkdir -p "$ROOT" /out
df -Pm /work | awk 'NR==2{print "free /work: " $4 " MB"}'
FREE=`df -Pm /work | awk 'NR==2{print $4}'`
if [ "$FREE" -lt 100 ]; then
  echo "!! REFUSING TO START: only $FREE MB free on /work, need 100"
  exit 3
fi

echo "-- unpacking the embedded pass and its data"
cd "$ROOT"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d > payload.tgz
md5sum payload.tgz
tar xzf payload.tgz --no-same-owner --no-same-permissions
if [ $? -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the embedded inputs did not unpack."
  exit 5
fi
rm -f payload.tgz
ls -l | awk '{print "   " $5 "  " $9}'

echo "-- the pass: progress every 200 classes walked"
python3 -u dom_ops.py --in "$ROOT" --out "$ROOT" --every 200
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the dom_op pass exited $rc"
  exit $rc
fi

echo "-- THE SPELLING BAN: the mechanical guard, on every product"
python3 check_no_spelling_keys.py \\
        "$ROOT/dom_ops.json" \\
        "$ROOT/dom_ops_digest_shape.json"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! THE GUARD FAILED: refusing to publish these products."
  exit $rc
fi

echo "-- publishing"
cp "$ROOT/dom_ops.json" /out/
cp "$ROOT/dom_ops.md" /out/
cp "$ROOT/dom_ops_digest.md" /out/
cp "$ROOT/dom_ops_digest_shape.json" /out/
ls -la /out
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
echo "=== pc_dom_ops done ==="
exit 0
__PAYLOAD__
"""


def build():
    blob, size = payload()
    head = HEAD % dict(size=size)
    lines = []
    i = 0
    while i < len(blob):
        lines.append(blob[i:i + 76])
        i = i + 76
    text = head + "\n".join(lines) + "\n"
    path = os.path.join(AIRLOCK, "agent", "drop", LANE)
    fh = open(path, "w")
    fh.write(text)
    fh.close()
    os.chmod(path, 0o755)
    print("packed payload  %d bytes" % size)
    print("lane            %s (%d bytes)" % (path, len(text)))
    return 0


def fold():
    outdir = os.path.join(AIRLOCK, "agent", "out")
    moved = 0
    for name in PRODUCTS:
        src = os.path.join(outdir, name)
        if not os.path.exists(src):
            print("!! missing from the lane output: %s" % name)
            continue
        data = open(src, "rb").read()
        dst = os.path.join(HERE, name)
        fh = open(dst, "wb")
        fh.write(data)
        fh.close()
        print("folded %s (%d bytes)" % (name, len(data)))
        moved = moved + 1
    if moved != len(PRODUCTS):
        print("!! %d of %d products folded" % (moved, len(PRODUCTS)))
        return 1
    doc = json.load(open(os.path.join(HERE, "dom_ops.json")))
    print("nodes             %d" % doc["nodes"])
    print("by arity bucket   %s"
          % json.dumps(doc["nodes_by_arity_bucket"]))
    print("edges before      %d"
          % doc["edges_before_the_mutual_filter"])
    print("edges after       %d"
          % doc["edges_after_the_mutual_filter"])
    print("dom_ops           %d" % doc["dom_op_count"])
    print("without arity     %s"
          % json.dumps(doc["without_the_arity_fix"]))
    print("assertion ran     %s, collisions %d"
          % (doc["same_language_assertion"]["ran"],
             doc["same_language_assertion"]["violations"]))
    return 0


def main(argv):
    if "--build" in argv:
        return build()
    if "--fold" in argv:
        return fold()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
