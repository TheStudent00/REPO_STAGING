FIELDS = ("tested", "mismatch", "reference_undefined", "trap_agreements",
          "cross_lang_mismatch")


def parse_out(text):
    res, ex = {}, []
    for line in text.splitlines():
        f = line.split()
        if not f:
            continue
        if f[0] == "RESULT":
            res[int(f[1])] = dict(zip(FIELDS, [int(x) for x in f[2:7]]))
        elif f[0] == "EX":
            ex.append(line)
    return res, ex


def main():
    units = json.load(open(os.path.join(OUT, "_units_int.json")))["units"]
    if ONLY:
        keep = set(int(x) for x in ONLY.split(","))
        units = [u for u in units if u["index"] in keep]
    work = SCRATCH
    refd, emud = os.path.join(work, "ref"), os.path.join(work, "emu")
    for d in (work, refd, emud):
        os.makedirs(d, exist_ok=True)

    note("building the references (the native operator, host -O2) ...")
    build_ref(units, work)
    note("building the four integer harnesses ...")
    build_c(units, work)
    build_cpp(units, work)
    build_rust(units, work)
    build_go(units, work)

    note("running the references ...")
    must([os.path.join(work, "ref_c"), refd], "ref_c run")
    must([os.path.join(work, "ref_go"), refd], "ref_go run")

    out = {}
    note("running c   (writes the cross-language reference stream) ...")
    out["c"] = parse_out(must([os.path.join(work, "h_c"), refd, emud, "1"],
                              "h_c run"))
    for lang in ("cpp", "rust", "go"):
        note("running %s ..." % lang)
        out[lang] = parse_out(must([os.path.join(work, "h_" + lang), refd,
                                    emud, "0"], "h_%s run" % lang))

    summary = {"n_rand": N_RAND, "n_band": N_BAND, "seed": SEED,
               "per_unit": {}, "examples": {l: out[l][1] for l in out}}
    tot = {l: {k: 0 for k in FIELDS} for l in out}
    for u in units:
        i = u["index"]
        rec = {}
        for lang in out:
            r = out[lang][0].get(i)
            rec[lang] = r
            if r:
                for k in tot[lang]:
                    tot[lang][k] += r[k]
        summary["per_unit"][str(i)] = rec
    summary["totals"] = tot
    json.dump(summary, open(os.path.join(work, "verdict.json"), "w"), indent=1)
    note(json.dumps(tot, indent=1))
    for lang in out:
        for line in out[lang][1][:20]:
            note(lang, line)
    note("verdict written to", os.path.join(work, "verdict.json"))


if __name__ == "__main__":
    main()
