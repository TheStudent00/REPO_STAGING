#!/usr/bin/env python3
"""Measure what the arch-unit leaves in the ANSWER REGISTER above its result.

The emulations answer at the result type's own width, because that is what the
compiler-operator's result is.  This probe asks the separate question: does the
arch-unit leave the FULL 64-bit answer register in the canonical form the
psABI asks for -- a 32-bit result sign-extended into XLEN, a boolean result as
0 or 1?

It recomposes every arch-unit with the final mask removed and runs it over the
same edge values plus PROBE_N random draws, counting the inputs where the raw
answer register is not the canonical widening of the result.  Nothing under
arch_units/ is written; the probe is a single self-contained C file in the
scratch directory.

    python3 scripts/probe_answer_width.py
"""

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
OUT = os.path.join(BASE, "arch_units")
sys.path.insert(0, HERE)
import rv_int_spec as S                                        # noqa: E402
import build_arch_units_int as B                               # noqa: E402

SCRATCH = os.environ.get(
    "AU_SCRATCH",
    "/tmp/claude-1000/-home-<user>-Programming/"
    "88f5a9f5-d844-4f11-895c-c5dafdfde323/scratchpad/archunits_int")
PROBE_N = int(os.environ.get("PROBE_N", 200000))
SEED = "0x9E3779B97F4A7C15"


def main():
    units = json.load(open(os.path.join(OUT, "_units_int.json")))["units"]
    # the arch-units the question is about: a result narrower than the register
    cand = [u for u in units
            if u["result_bits"] < 64 and not u["reduced"]
            and S.kind(u["result_tag"]) != "f"]
    be = B.C()
    L = ["/* generated by scripts/probe_answer_width.py */",
         "#include <stdint.h>", "#include <stdio.h>",
         '#include "au_int.h"', "",
         "static uint64_t S_;",
         "static void seed(void) { S_ = %sULL; }" % SEED,
         "static uint64_t rnd(void) { S_ ^= S_ << 13; S_ ^= S_ >> 7;"
         " S_ ^= S_ << 17; return S_; }", ""]
    rows = json.load(open(B.ATTEST))["rows"]
    byunit = {r["unit"]: r for r in rows}
    for u in cand:
        r = byunit[u["unit"]]
        body = B.Composer(be, r, "value", False).run()
        fn = be.fn_open("raw_%03d" % u["index"], u["n_params"])
        fn[0] = "static " + fn[0]
        L += fn + body + be.fn_close() + [""]
    for u in cand:
        L.append(gen_check(u))
        L.append("")
    L.append("int main(void)\n{")
    for u in cand:
        L.append("    check_%03d();" % u["index"])
    L.append("    return 0;\n}")
    work = SCRATCH
    os.makedirs(work, exist_ok=True)
    src = os.path.join(work, "answer_width.c")
    open(src, "w").write("\n".join(L) + "\n")
    p = subprocess.run(["clang", "-O2", "-std=c17", src,
                        "-I" + os.path.join(OUT, "c"),
                        "-o", os.path.join(work, "answer_width")],
                       capture_output=True, text=True)
    if p.returncode:
        raise SystemExit(p.stderr[-6000:])
    out = subprocess.run([os.path.join(work, "answer_width")],
                         capture_output=True, text=True).stdout

    rep = {}
    for line in out.splitlines():
        f = line.split()
        if f and f[0] == "AW":
            rep[int(f[1])] = {"tested": int(f[2]), "non_canonical": int(f[3])}
    byidx = {u["index"]: u for u in units}
    bad = [i for i, v in rep.items() if v["non_canonical"]]
    doc = {
        "what": "inputs where the arch-unit leaves the answer register in a "
                "form that is NOT the canonical widening of its own result "
                "(a 32-bit result sign-extended into XLEN, a boolean 0/1)",
        "probed": len(rep),
        "arch_units_with_a_non_canonical_answer_register": len(bad),
        "per_unit": {str(i): rep[i] for i in sorted(rep)},
        "units": [{"index": i, "name": byidx[i]["name"],
                   "lang": byidx[i]["lang"],
                   "expression": byidx[i]["expression"],
                   "lhs_type": byidx[i]["lhs_type"],
                   "rhs_type": byidx[i]["rhs_type"],
                   "result_type": byidx[i]["result_type"],
                   "body": byidx[i]["body"],
                   "inputs": rep[i]["tested"],
                   "non_canonical": rep[i]["non_canonical"]}
                  for i in sorted(bad)],
    }
    json.dump(doc, open(os.path.join(OUT, "_answer_width.json"), "w"),
              indent=1)
    print("probed %d arch-units whose result is narrower than the register"
          % len(rep))
    print("%d leave the answer register non-canonical:" % len(bad))
    for i in sorted(bad):
        u = byidx[i]
        print("  %3d %-40s %-4s %-12s %s   %d/%d"
              % (i, u["name"], u["lang"], u["expression"],
                 " | ".join(u["body"]), rep[i]["non_canonical"],
                 rep[i]["tested"]))
    print("written to", os.path.join(OUT, "_answer_width.json"))


def gen_check(u):
    tags, edges, _ = S.plan(u, 0, 0)
    n = len(tags)
    idx = u["index"]
    L = []
    for i, e in enumerate(edges):
        L.append("static const unsigned long long G_%03d_%d[] = {%s};"
                 % (idx, i, ",".join("0x%xULL" % v for v in e)))
    L += ["static void check_%03d(void)" % idx, "{",
          "    unsigned long long k = 0, bad = 0;",
          "    unsigned long long %s;" % ", ".join("c%d" % i for i in range(n)),
          "    seed();"]
    args = ", ".join("c%d" % i for i in range(n))
    if u["result_bits"] == 1:
        canon = "(raw == 0 || raw == 1)"
    else:
        canon = "(raw == au_sext32(raw))"
    chk = "\n".join([
        "        {",
        "            uint64_t raw = raw_%03d(%s);" % (idx, args),
        "            if (!%s) bad++;" % canon,
        "            k++;",
        "        }"])
    for i in range(n):
        L.append("    %sfor (unsigned long long i%d = 0; i%d < %d; i%d++) {"
                 % ("    " * i, i, i, len(edges[i]), i))
    for i in range(n):
        L.append("    %sc%d = G_%03d_%d[i%d];" % ("    " * n, i, idx, i, i))
    L.append(chk)
    L.append("    " + "}" * n)
    L.append("    for (unsigned long long q = 0; q < %dULL; q++) {" % PROBE_N)
    for i, t in enumerate(tags):
        L.append(S.uniform_line("c", i, t, "        "))
    L.append(chk)
    L.append("    }")
    L.append("    for (unsigned long long q = 0; q < %dULL; q++) {"
             % (PROBE_N // 2))
    L += S.band_lines("c", tags, "        ")
    L.append(chk)
    L.append("    }")
    L.append('    printf("AW %d %%llu %%llu\\n", k, bad);' % idx)
    L.append("}")
    return "\n".join(L)


if __name__ == "__main__":
    main()
