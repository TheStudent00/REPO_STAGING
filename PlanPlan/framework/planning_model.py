#!/usr/bin/env python3
"""Planning-tree data model: PlanningNode and PlanningTree.

Parses a planning tree's on-disk grammar into plain data — frontmatter,
definition, sections, the sub-node register, and the paths of the files
a node folder carries. Holds no checking logic and no rendering logic;
`checks.py` and `render_plan.py` both build on what is here.

Depends on nothing but the standard library, and imports no other
framework file.
"""
import os
import re

import schema

CORE_RE = re.compile(r"^CORE_.*\.md$")
SUPPORT_RE = re.compile(r"^SUPPORT_.*")
NODE_RE = re.compile(r"^node_.*")
# A node's test sits beside its CORE and mirrors its name, with any
# extension — `.md` for a by-hand check, `.py` for a runnable one
# (the owner, 2026-07-31; framework §3b).
CHECK_RE = re.compile(r"^CHECK_.*")


class PlanningNode:
    """One node folder: what its CORE says about itself, and the paths
    of the other files (PROGRESS, CHECK, DASHBOARD, SUPPORT) and
    sub-node folders it holds. A `*_path` attribute is the file's real
    path if present, `None` if absent — this class does no grammar
    checking of its own, so a missing or malformed file is simply
    represented as missing, never flagged."""

    def __init__(self, path, address):
        self.path = path
        self.address = address
        self.core_path = None
        self.frontmatter = {}
        self.definition = ""
        self.sections = []
        self.register = None
        # The 2026-08-02 edge fields. `*_status` says which of absent /
        # null / empty / ok / malformed the field was, so a leaf that
        # says `sub_nodes: []` on purpose is never confused with a CORE
        # that simply has no such field.
        # `node` (2026-08-02) is the node's statement about ITSELF, in
        # the same shape as an edge. It exists because a CORE could
        # name the repo above it and not the one it was in.
        self.self_edge = None
        self.self_status = "absent"
        self.super_edge = None
        self.super_edge_status = "absent"
        self.sub_edges = []
        self.sub_edges_status = "absent"
        self.progress_path = None
        self.check_path = None
        self.dashboard_path = None
        self.support_paths = []
        self.sub_nodes = []
        # kept for rendering, alongside the attributes above
        self.title = ""
        self.words = 0
        self.progress_status = None

    @classmethod
    def load(cls, dirpath, address):
        """Scan one node folder and recurse into its sub-nodes. Best
        effort: a missing or malformed CORE leaves the node's fields at
        their defaults rather than raising — reporting that is
        `checks.GrammarCheck`'s business, not this loader's."""
        node = cls(dirpath, address)
        core_names, support_names, check_names, subdirs = [], [], [], []

        for entry in sorted(os.listdir(dirpath)):
            full = os.path.join(dirpath, entry)
            if entry.startswith("."):
                continue
            if os.path.isdir(full):
                if NODE_RE.match(entry):
                    subdirs.append(entry)
                continue
            if CORE_RE.match(entry):
                core_names.append(entry)
            elif entry == "PROGRESS.md":
                node.progress_path = full
            elif SUPPORT_RE.match(entry):
                support_names.append(entry)
            elif entry == "DASHBOARD.md":
                # generated by generate_dashboards.py — a legitimate node
                # file, not hand-written (framework §1).
                node.dashboard_path = full
            elif CHECK_RE.match(entry):
                check_names.append(entry)
            # anything else is a stray entry — checks.GrammarCheck's
            # business, not this loader's.

        node.support_paths = [os.path.join(dirpath, s) for s in sorted(support_names)]
        if check_names:
            node.check_path = os.path.join(dirpath, check_names[0])
        if core_names:
            node.core_path = os.path.join(dirpath, core_names[0])
            core = cls.read_core(node.core_path)
            node.frontmatter = core["fields"]
            node.title = core["title"]
            node.definition = core["definition"]
            node.sections = core["sections"]
            node.words = core["words"]
            node.register = cls.register_of(node.frontmatter)
            node.self_status, node.self_edge = cls.parse_edge(
                node.frontmatter.get(schema.Fields.NODE))
            node.super_edge_status, node.super_edge = cls.parse_edge(
                node.frontmatter.get(schema.Fields.SUPER_NODE))
            node.sub_edges_status, node.sub_edges = cls.parse_edge_register(
                node.frontmatter.get(schema.Fields.SUB_NODES))
        if node.progress_path:
            with open(node.progress_path, encoding="utf-8") as fh:
                pf, _ = cls.read_frontmatter(fh.read())
            node.progress_status = pf.get("status")

        for d in subdirs:
            node.sub_nodes.append(cls.load(os.path.join(dirpath, d), d))
        return node

    # ------------------------------------------------------------ parsing

    @staticmethod
    def read_frontmatter(text):
        """Return (fields, body). Frontmatter is the block between two
        `---` markers at the very top. Absent frontmatter is not an error
        here — it is reported as a grammar problem instead.

        A key with a value on its own line stays EXACTLY what it was
        before 2026-08-02: the raw string to the right of the colon. A
        key with an empty value, followed by more-indented lines, takes
        those lines as a block and becomes a dict or a list of dicts —
        which is what `super_node` and `sub_nodes` need (PROTOCOL §1,
        the owner, 2026-08-02).

        The split is deliberate. Every field that existed before this
        change reads back as the same string it always did, so nothing
        built on the old reader had to be touched at the same time as
        the reader itself."""
        if not text.startswith("---"):
            return {}, text
        end = text.find("\n---", 3)
        if end == -1:
            return {}, text
        head = text[3:end]
        body = text[end + 4:]
        fields = {}
        lines = head.splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]
            if not line.strip() or line.lstrip().startswith("#") \
                    or ":" not in line or line[:1].isspace():
                i += 1
                continue
            key, _, value = line.partition(":")
            key, value = key.strip(), value.strip()
            if value:
                fields[key] = value
                i += 1
                continue
            block, i = PlanningNode._collect_block(lines, i + 1)
            fields[key] = PlanningNode._parse_block(block) if block else ""
        return fields, body

    @staticmethod
    def _collect_block(lines, start):
        """The indented lines beneath a key that had no inline value.
        Returns (block_lines, next_index). Blank lines inside the block
        are kept out; the block ends at the first line that is neither
        blank nor indented."""
        block = []
        i = start
        while i < len(lines):
            line = lines[i]
            if not line.strip():
                i += 1
                continue
            if not line[:1].isspace():
                break
            block.append(line)
            i += 1
        return block, i

    @staticmethod
    def _parse_block(block):
        """A block is either a sequence of mappings (its first line
        starts `- `) or one mapping. Anything else returns None, which
        the checks report — never guessed at, per PROTOCOL §1."""
        first = block[0].strip()
        if first.startswith("- "):
            return PlanningNode._parse_sequence(block)
        return PlanningNode._parse_mapping(block)

    @staticmethod
    def _parse_mapping(block):
        """`key: value` lines at one indent. Returns a dict, or None if
        any line is not a `key: value` pair."""
        out = {}
        for line in block:
            s = line.strip()
            if ":" not in s:
                return None
            k, _, v = s.partition(":")
            out[k.strip()] = v.strip()
        return out or None

    @staticmethod
    def _parse_sequence(block):
        """`- key: value` starts an entry; plainer `key: value` lines
        beneath continue it. Returns a list of dicts, or None if any
        line is neither."""
        out = []
        for line in block:
            s = line.strip()
            if s.startswith("- "):
                s = s[2:].strip()
                out.append({})
            elif not out:
                return None
            if ":" not in s:
                return None
            k, _, v = s.partition(":")
            out[-1][k.strip()] = v.strip()
        return out or None

    @staticmethod
    def parse_sections(body):
        """Split a CORE body into its `## ` sections. Returns
        [(heading, [lines]), ...] in document order. Text above the first
        `## ` is the definition and is handled separately."""
        secs, cur = [], None
        for line in body.splitlines():
            if line.startswith("## "):
                cur = (line[3:].strip(), [])
                secs.append(cur)
            elif cur is not None:
                cur[1].append(line)
        return secs

    @staticmethod
    def sections_of(body):
        """The `## ` headings of a body, in order. FENCE-AWARE: a `## `
        line inside a fenced code block is code, not a heading — the case
        (the owner, 2026-08-01) that disqualified markdown as the register."""
        out, fenced = [], False
        for line in body.splitlines():
            if line.lstrip().startswith("```"):
                fenced = not fenced
                continue
            if not fenced and line.startswith("## "):
                out.append(line.strip())
        return out

    @staticmethod
    def iter_body_lines_with_sections(body):
        """Yield (line, section) where section is the current `## ` heading
        or None above the first one. FENCE-AWARE: a line starting ```
        toggles fenced-code mode, and headings inside a fence are code —
        the exact case (the owner, 2026-08-01) that made markdown untrustworthy
        as the register."""
        section = None
        fenced = False
        for line in body.splitlines():
            if line.lstrip().startswith("```"):
                fenced = not fenced
                yield line, section
                continue
            if not fenced and line.startswith("## "):
                section = line.strip()
            yield line, section

    @classmethod
    def read_core(cls, path):
        """Pull what a CORE file says about itself: frontmatter, title, and
        the definition — the first ordinary paragraph under the title, which
        by the framework's own style is the one-line statement of what the
        node is."""
        with open(path, "r", encoding="utf-8") as fh:
            text = fh.read()
        fields, body = cls.read_frontmatter(text)
        title, definition, lines = "", "", body.splitlines()
        i = 0
        while i < len(lines):
            s = lines[i].strip()
            if s.startswith("# "):
                title = s[2:].strip()
                i += 1
                break
            i += 1
        para = []
        while i < len(lines):
            s = lines[i].strip()
            if s.startswith("#"):
                break
            if not s:
                if para:
                    break
                i += 1
                continue
            para.append(s)
            i += 1
        definition = " ".join(para)
        return {
            "fields": fields,
            "title": title,
            "definition": definition,
            "sections": cls.parse_sections(body),
            "words": len(text.split()),
            "path": path,
        }

    @staticmethod
    def parse_nodes_register(value):
        """Parse the frontmatter `nodes` field (PROTOCOL §1, the owner,
        2026-08-01): the inline form `[a, b, c]` or `[]`, titles only,
        address order. Deliberately DUMB — strip brackets, split on
        commas. The field was put in YAML precisely so no intelligent
        parsing is ever needed; a malformed register returns None and is
        reported, never guessed at. (Markdown was rejected as the
        register because `## ...` inside a fenced code block would fool
        any naive heading scan.)"""
        v = value.strip()
        if not (v.startswith("[") and v.endswith("]")):
            return None
        inner = v[1:-1].strip()
        if not inner:
            return []
        return [t.strip() for t in inner.split(",")]

    @classmethod
    def register_of(cls, fields):
        """The sub-node titles this CORE registers, in address order —
        the one place anything asks that question.

        Read from `sub_nodes` when it is there, falling back to the
        superseded inline `nodes` field when it is not. Both exist for
        as long as the trees are being brought over chain by chain, and
        this is where the two are reconciled instead of at five call
        sites.

        Only the IN-TREE entries count. `nodes` never meant anything
        but sub-node folders in this same tree, and a cross-repo entry
        in `sub_nodes` has no folder here to register — `hq.projects`
        registers nothing while naming three repos, and both halves of
        that are correct.

        Returns None when neither field is readable, which is what the
        checks report as a missing register."""
        status, entries = cls.parse_edge_register(fields.get(schema.Fields.SUB_NODES))
        if status == "ok":
            # A `realize: false` entry has no path; it is in-tree by
            # definition and keeps its address slot in this list.
            return [e["name"] for e in entries
                    if not e.get("path", "").startswith("~")]
        if status == "empty":
            return []
        if status == "malformed":
            return None
        return cls.parse_nodes_register(fields.get(schema.Fields.NODES_SUPERSEDED, ""))

    @classmethod
    def register_entries_of(cls, fields):
        """The register as full entry mappings, in address order, or
        None — the richer sibling of `register_of` for tools that need
        `realize`/`designation`. Superseded-`nodes` trees get minimal
        `{name}` entries, which read as realized (no `realize` key)."""
        status, entries = cls.parse_edge_register(fields.get(schema.Fields.SUB_NODES))
        if status == "ok":
            return [e for e in entries
                    if not e.get("path", "").startswith("~")]
        if status == "empty":
            return []
        if status == "malformed":
            return None
        titles = cls.parse_nodes_register(
            fields.get(schema.Fields.NODES_SUPERSEDED, ""))
        if titles is None:
            return None
        return [{"name": t} for t in titles]

    # An edge entry names where the other end is, and nothing else.
    # `repo` and `remote` appear only when the edge leaves the repo
    # (PROTOCOL §1, the owner, 2026-08-02).
    EDGE_REQUIRED = schema.EdgeKeys.REQUIRED
    EDGE_OPTIONAL = schema.EdgeKeys.OPTIONAL

    @classmethod
    def parse_edge(cls, entry):
        """One edge entry. Returns (status, entry) where status is one
        of `ok`, `absent`, `null`, `malformed`. Malformed is reported
        rather than repaired: a missing `path` and a misspelled `path`
        are the same defect, and guessing at either is how a wrong edge
        survives."""
        if entry is None or entry == "":
            return "absent", None
        if isinstance(entry, str):
            return ("null", None) if entry.strip() == "null" else ("malformed", None)
        if not isinstance(entry, dict):
            return "malformed", None
        # A `realize: false` entry (PROTOCOL §1, the owner, 2026-08-02) is
        # structure that stays in the super's file: NAME required,
        # DESIGNATION allowed, PATH forbidden — there is no file to
        # locate, and the pairing is enforced both ways here (a path
        # on an unrealized entry, or `realize` set to anything but
        # false, is malformed rather than guessed at).
        if schema.EdgeKeys.REALIZE in entry:
            # The frontmatter reader keeps scalar values as raw strings
            # (its 2026-08-02 compatibility contract), so `false`
            # arrives as the string "false". Normalized to the boolean
            # HERE, once, so every downstream `is False` means one
            # thing.
            val = entry.get(schema.EdgeKeys.REALIZE)
            if not (val is False or (isinstance(val, str)
                                     and val.strip().lower() == "false")):
                return "malformed", None
            entry[schema.EdgeKeys.REALIZE] = False
            for k in schema.EdgeKeys.UNREALIZED_REQUIRED:
                if not entry.get(k):
                    return "malformed", None
            for k in entry:
                if k not in (schema.EdgeKeys.UNREALIZED_REQUIRED
                             + schema.EdgeKeys.UNREALIZED_OPTIONAL):
                    return "malformed", None
            return "ok", entry
        for k in cls.EDGE_REQUIRED:
            if not entry.get(k):
                return "malformed", None
        for k in entry:
            if k not in cls.EDGE_REQUIRED + cls.EDGE_OPTIONAL:
                return "malformed", None
        return "ok", entry

    @classmethod
    def parse_edge_register(cls, value):
        """The `sub_nodes` field. Returns (status, entries). The empty
        form `sub_nodes: []` is a LEAF stated on purpose, which is a
        different thing from the field being absent — so they get
        different statuses and the checks can tell them apart."""
        if value is None or value == "":
            return "absent", []
        if isinstance(value, str):
            return ("empty", []) if value.strip() == "[]" else ("malformed", [])
        if not isinstance(value, list):
            return "malformed", []
        out = []
        for entry in value:
            status, parsed = cls.parse_edge(entry)
            if status != "ok":
                return "malformed", []
            out.append(parsed)
        return "ok", out


class PlanningTree:
    """A planning root (a node_0 folder) and the PlanningNode tree
    scanned from it."""

    def __init__(self, root_path, root_node):
        self.root_path = root_path
        self.root_node = root_node

    @classmethod
    def load(cls, root_path):
        root_node = PlanningNode.load(root_path, os.path.basename(root_path))
        return cls(root_path, root_node)

    def walk(self):
        """Yield (depth, node) for the root and every sub-node beneath it,
        depth-first, depth 0 at the root."""
        def _walk(node, depth):
            yield depth, node
            for s in node.sub_nodes:
                yield from _walk(s, depth + 1)
        yield from _walk(self.root_node, 0)
