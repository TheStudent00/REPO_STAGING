def gen_check_c(u, cpp):
    tags, edges, total = plan(u)
    n = len(tags)
    idx = u["index"]
    lg = "cpp" if cpp else "c"
    name = u["languages"][lg]["entry"]
    trap = u["languages"][lg]["trap_entry"]
    args = ", ".join("c%d" % i for i in range(n))
    L = []
    for i, e in enumerate(edges):
        L.append("static const unsigned long long F_%03d_%d[] = {%s};"
                 % (idx, i, ",".join("0x%xULL" % v for v in e)))
    L += ["static void check_%03d(void)" % idx, "{",
          "    uint64_t *ref = slurp(REF_, %d, %dULL);" % (idx, total),
          "    unsigned char *flg = slurpf(REF_, %d, %dULL);" % (idx, total),
          "    uint64_t *xl = W_ ? NULL : slurp(EMU_, %d, %dULL);"
          % (idx, total),
          "    uint64_t *mine = (uint64_t *)malloc(%dULL * 8);" % total,
          "    unsigned long long k = 0, mism = 0, undef = 0, trapok = 0,"
          " xlm = 0, shown = 0;",
          "    unsigned long long %s;" % ", ".join("c%d" % i for i in range(n)),
          "    seed();"]
    ex = " ".join('printf(" 0x%%llx", c%d);' % i for i in range(n))

    def shout(kindtxt, extra=""):
        return ('if (shown < 4) { shown++; printf("EX %d %s");'
                ' %s printf("%s\\n"); }' % (idx, kindtxt, ex, extra))

    chk = "\n".join([
        "        {",
        "            uint64_t got = %s(%s);" % (name, args),
        "            uint64_t tr = %s;"
        % (("%s(%s)" % (trap, args)) if trap else "0"),
        "            unsigned char f = flg[k];",
        "            mine[k] = got;",
        "            if (f == 2) {",
        "                undef++;",
        "            } else if (f == 1) {",
        "                if (tr) { trapok++; }",
        "                else { mism++; %s }" % shout("TRAP-MISSED"),
        "            } else if (tr) {",
        "                mism++; %s" % shout("TRAP-SPURIOUS"),
        "            } else if (got != ref[k]) {",
        "                mism++;",
        '                if (shown < 4) { shown++; printf("EX %d MISMATCH");'
        ' %s printf(" want 0x%%llx got 0x%%llx\\n",'
        " (unsigned long long)ref[k], (unsigned long long)got); }"
        % (idx, ex),
        "            }",
        "            if (xl && got != xl[k]) xlm++;",
        "            k++;",
        "        }"])
    for i in range(n):
        L.append("    %sfor (unsigned long long i%d = 0; i%d < %d; i%d++) {"
                 % ("    " * i, i, i, len(edges[i]), i))
    for i in range(n):
        L.append("    %sc%d = F_%03d_%d[i%d];" % ("    " * n, i, idx, i, i))
    L.append(chk)
    L.append("    " + "}" * n)
    L.append("    for (unsigned long long q = 0; q < %dULL; q++) {" % N_RAND)
    for i, t in enumerate(tags):
        L.append(S.uniform_line("c", i, t, "        "))
    L.append(chk)
    L.append("    }")
    L.append("    for (unsigned long long q = 0; q < %dULL; q++) {" % N_BAND)
    L += S.band_lines("c", tags, "        ")
    L.append(chk)
    L.append("    }")
    L += ["    if (W_) { char path[512];",
          '        snprintf(path, sizeof path, "%s/' + ("%03d.bin" % idx)
          + '", EMU_);',
          '        FILE *f = fopen(path, "wb"); fwrite(mine, 8, k, f);'
          " fclose(f); }",
          '    printf("RESULT %d %%llu %%llu %%llu %%llu %%llu\\n", k, mism,'
          " undef, trapok, xlm);" % idx,
          "    free(ref); free(flg); free(mine); if (xl) free(xl);",
          "}"]
    return "\n".join(L)


