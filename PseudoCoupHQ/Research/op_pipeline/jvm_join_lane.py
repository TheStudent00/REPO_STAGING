#!/usr/bin/env python3
"""jvm_join_lane.py -- build the Airlock lane that canonicalises the
JVM unit, matches it against the table and re-runs the dom_op
construction with java in the language list; and fold its products
back.

the owner's ruling: the run of record is a lane.

No solver and no lifter are needed: the match is level 1, byte
identity after canonicalisation.  What the lane does need is an
ASSEMBLER, because the canonical form is runnable machine code and its
bytes are what the match compares -- so `as` and `objdump` are checked
before anything runs.

usage:
  jvm_join_lane.py --build
  jvm_join_lane.py --fold
"""

import base64
import io
import json
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
_PROGRAMMING = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
AIRLOCK = os.path.join(_PROGRAMMING, "Airlock")

LANE = "pc_jvm_join.sh"

LANGS = ["c", "cpp", "go", "rust", "swift"]

PRODUCTS = ["jvm_canon.json", "add_java.json", "dominant_table5.json",
            "probe_manifest_java.json", "core_modes_java.json",
            "dom_ops3.json", "dom_ops3.md", "dom_ops3_digest.md",
            "dom_ops3_digest_shape.json"]

CODE = ["jvm_canon.py", "add_java.py", "dom_ops_java.py", "dom_ops.py",
        "check_no_spelling_keys.py"]

DATA = ["interp_jvm.json", "canon_roundtrip.json",
        "dominant_table4.json", "bridges4.json", "verdicts3b.json"]


def payload():
    buf = io.BytesIO()
    tar = tarfile.open(fileobj=buf, mode="w:gz")

    def add(name):
        path = os.path.join(HERE, name)
        data = open(path, "rb").read()
        info = tarfile.TarInfo(name)
        info.size = len(data)
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(data))

    for name in CODE:
        add(name)
    for name in DATA:
        add(name)
    for lang in LANGS:
        add("probe_manifest_%s.json" % lang)
        add("core_modes_%s.json" % lang)
    tar.close()
    raw = buf.getvalue()
    return base64.b64encode(raw).decode("ascii"), len(raw)


HEAD = """#!/bin/sh
# pc_jvm_join -- the JVM unit joins the table.
#
# The JVM printed the machine code its C2 compiler produced for a
# warmed Java method.  Around the arithmetic sits runtime furniture:
# an entry barrier, a return safepoint poll, the frame that serves
# them, and out-of-line stubs.  This lane strips that furniture BY
# NAMED RULE -- an unmatched pattern is a refusal with the offending
# line, never a guess -- renames the JVM's own parameter registers
# into THE CANONICAL RUNNABLE FORM, assembles the result, and compares
# the bytes with the classes the table already holds.
#
# The evidence class is weaker than the rest of the table and is
# marked on the member: these bytes are the JVM's testimony about code
# it generated at run time, carved out of a print by our lane, not an
# ELF section a compiler wrote to disk.
#
# THE SPELLING BAN, ABSOLUTE (the owner, 2026-08-25).  No operator token
# takes part in any key, grouping, pairing, row structure, candidate
# selection or comparison scope here.  Every JSON product is handed to
# check_no_spelling_keys.py and a FAIL refuses the publish.
#
# Generated by Research/op_pipeline/jvm_join_lane.py .  Do not
# hand-edit.  %(size)d bytes packed.
set -u
export HOME=/work
ROOT=/work/pc_jvm_join
echo "=== op_pipeline -- the JVM unit joins the table ==="
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
if ! python3 --version >/dev/null 2>&1; then
  echo "!! REFUSING TO START: python3 is not runnable in this container."
  exit 4
fi
python3 --version
if ! as --version >/dev/null 2>&1; then
  echo "!! REFUSING TO START: as is not runnable, and the canonical"
  echo "!! form is runnable machine code -- its bytes are the match."
  exit 4
fi
as --version 2>&1 | head -1
if ! objdump --version >/dev/null 2>&1; then
  echo "!! REFUSING TO START: objdump is not runnable."
  exit 4
fi
objdump --version 2>&1 | head -1
rm -rf "$ROOT"; mkdir -p "$ROOT" /out
df -Pm /work | awk 'NR==2{print "free /work: " $4 " MB"}'

echo "-- unpacking the embedded passes and their data"
cd "$ROOT"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d > payload.tgz
md5sum payload.tgz
tar xzf payload.tgz --no-same-owner --no-same-permissions
if [ $? -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the embedded inputs did not unpack."
  exit 5
fi
rm -f payload.tgz
ls -l | awk '{print "   " $5 "  " $9}'

echo "-- pass 1: strip the furniture, rename, assemble"
python3 -u jvm_canon.py --in "$ROOT" --out "$ROOT"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the canonicalisation refused; the reason is in jvm_canon.json"
  cp "$ROOT/jvm_canon.json" /out/ 2>/dev/null
  exit $rc
fi

echo "-- pass 2: match against the classes by canonical bytes"
python3 -u add_java.py --in "$ROOT" --out "$ROOT"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! no match; where it diverges is in add_java.json"
  cp "$ROOT/jvm_canon.json" "$ROOT/add_java.json" /out/ 2>/dev/null
  exit $rc
fi

echo "-- pass 3: the dom_op construction with java in the list"
python3 -u dom_ops_java.py --in "$ROOT" --out "$ROOT" --every 500
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the dom_op pass exited $rc"
  exit $rc
fi

echo "-- THE SPELLING BAN: the mechanical guard, on every product"
python3 check_no_spelling_keys.py \\
        "$ROOT/jvm_canon.json" \\
        "$ROOT/add_java.json" \\
        "$ROOT/dominant_table5.json" \\
        "$ROOT/core_modes_java.json" \\
        "$ROOT/dom_ops3.json" \\
        "$ROOT/dom_ops3_digest_shape.json"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! THE GUARD FAILED: refusing to publish these products."
  exit $rc
fi

echo "-- publishing"
for f in jvm_canon.json add_java.json dominant_table5.json \\
         probe_manifest_java.json core_modes_java.json \\
         dom_ops3.json dom_ops3.md dom_ops3_digest.md \\
         dom_ops3_digest_shape.json; do
  cp "$ROOT/$f" /out/
done
ls -la /out
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
echo "=== pc_jvm_join done ==="
exit 0
__PAYLOAD__
"""


def build():
    blob, size = payload()
    head = HEAD % dict(size=size)
    lines = []
    i = 0
    while i < len(blob):
        lines.append(blob[i:i + 76])
        i = i + 76
    text = head + "\n".join(lines) + "\n"
    archive = os.path.join(HERE, "lanes", LANE)
    fh = open(archive, "w")
    fh.write(text)
    fh.close()
    path = os.path.join(AIRLOCK, "agent", "drop", LANE)
    fh = open(path, "w")
    fh.write(text)
    fh.close()
    os.chmod(path, 0o755)
    print("packed payload  %d bytes" % size)
    print("archived        %s" % archive)
    print("lane            %s (%d bytes)" % (path, len(text)))
    return 0


def fold():
    outdir = os.path.join(AIRLOCK, "agent", "out")
    moved = 0
    for name in PRODUCTS:
        src = os.path.join(outdir, name)
        if not os.path.exists(src):
            print("!! missing from the lane output: %s" % name)
            continue
        data = open(src, "rb").read()
        dst = os.path.join(HERE, name)
        fh = open(dst, "wb")
        fh.write(data)
        fh.close()
        print("folded %s (%d bytes)" % (name, len(data)))
        moved = moved + 1
    if moved != len(PRODUCTS):
        print("!! %d of %d products folded" % (moved, len(PRODUCTS)))
        return 1
    jvm = json.load(open(os.path.join(HERE, "jvm_canon.json")))
    print("canonical form    %s" % jvm["canonical_form"])
    print("canonical bytes   %s" % jvm["canonical_bytes"])
    add = json.load(open(os.path.join(HERE, "add_java.json")))
    print("matched class     %s" % add.get("matched_class"))
    print("matched against   %s" % add.get("matched_against"))
    return 0


def main(argv):
    if "--build" in argv:
        return build()
    if "--fold" in argv:
        return fold()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
