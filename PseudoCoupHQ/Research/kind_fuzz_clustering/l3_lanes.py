#!/usr/bin/env python3
"""l3_lanes.py -- emit the self-contained acceptance lanes.

One lane per language.  The runner cannot see this repo, so each lane
carries its probe payload inside itself (gzip+base64), exactly as the
layer-2 audit lane and log_024's l3_python lane did.

Route per language is the one PROVEN in a2_verify.sh (log_027 section 2),
not the one guessed:

  go     A2  go build            per-file parallel
  rust   A2  rustc --emit=metadata   per-file parallel
  cpp    A2  g++ -fsyntax-only   per-file parallel
  swift  A2  swiftc -typecheck   per-file parallel
  dart   A2  dart analyze <dir>  ONE invocation for a whole chunk
  csharp A1  Roslyn in-process   one process, no subprocess per probe
  kotlin A1  K2JVMCompiler in-process, warm JVM

Batching-by-bisect is NOT used: bisect_race.sh measured it losing to
per-file parallel by 5.4x on go, because under full enumeration refusals
are the majority and a bisect on a mostly-refusing batch costs MORE
compiles than one per probe (796 compiles for 400 probes, measured).
"""

