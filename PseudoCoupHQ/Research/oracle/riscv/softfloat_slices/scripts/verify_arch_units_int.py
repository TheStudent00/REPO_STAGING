#!/usr/bin/env python3
"""Verify every integer-only arch-unit emulation against the ORIGINAL
compiler-operator.

For each of the 318 arch-units the reference is the source expression the
arch-unit came from -- `!a`, `a / b`, `a >> b`, `sizeof a` -- written as a
native function in the arch-unit's OWN language (c for the 235 c units, go for
the 83 go units) and compiled for the HOST at -O2.  The C reference takes the
result type from the C compiler itself with `__typeof__`, exactly as the
corpus's probe did, so nothing about C's usual arithmetic conversions is
assumed here.  That native function is run over an input stream; the same
stream is then run through the integer emulation in ALL FOUR languages and
compared bit for bit.

Three comparisons come out of one run:

  native   each language's emulation against the native operator.
  trap     for the 18 go arch-units that carry a guard branch to a runtime
           panic, the emulation's `_trap` predicate against whether go's own
           operator actually panicked (observed with recover(), not assumed).
  cross    every language's emulation against c's, byte for byte.

Inputs where the C reference has NO answer -- a division by zero, and the
signed most-negative over minus one, both undefined in C and both a fault on
the host -- are flagged by the reference, counted apart, and excluded from the
native comparison only.  They are still compared across languages.

Everything is built and run under AU_SCRATCH; nothing outside
softfloat_slices/arch_units and softfloat_slices/scripts is written.
"""

