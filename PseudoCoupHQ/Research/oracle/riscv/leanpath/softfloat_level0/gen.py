#!/usr/bin/env python3
"""gen.py -- the level-0 check's two harnesses, generated from the texts
themselves. Nothing here is typed per operation.

  the operations   every definition in Kinds.lean's `namespace Axioms`
                   whose type text is EXACTLY the type of the axiom of the
                   same name in the cached emit's RiscvExtras.lean, and
                   which Sail's own softfloat_interface.sail binds to a
                   C++ function (`val <name> = pure {cpp: "<fn>", ...}`).
  the C++ side     calls that function with the arguments Sail's own val
                   declaration gives it (an argument of type `bits_rm` is
                   the rounding mode, every other one an operand in
                   order); linked against Sail's compiled riscv_softfloat
                   object by run_level0.sh.
  the Lean side    calls the Kinds.Axioms definition.

Both harnesses read lines `name rm a b` (hex) on standard input and print
`name rm a b flags result` (hex); a name a harness does not know prints
UNKNOWN in place of the two outputs.
"""
import argparse
import json
import os
import re


def norm(t):
    return re.sub(r"\s+", " ", t.strip())


def top_arrows(t):
    """A type text split at its top-level arrows."""
    parts, depth, cur = [], 0, ""
    for ch in t:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "→" and depth == 0:
            parts.append(cur.strip())
            cur = ""
            continue
        cur += ch
    parts.append(cur.strip())
    return parts


BV = re.compile(r"^BitVec (\d+)$")


def shape_of(typ):
    """(shape, width) of an axiom's type, or (None, None):
    rm2   BitVec 3 → BitVec w → BitVec w → (BitVec 5 × BitVec w)
    cmp2  BitVec w → BitVec w → (BitVec 5 × Bool)"""
    p = top_arrows(typ)
    if (len(p) == 4 and p[0] == "BitVec 3" and BV.match(p[1]) and p[1] == p[2]
            and p[3] == "(BitVec 5 × %s)" % p[1]):
        return "rm2", int(BV.match(p[1]).group(1))
    if len(p) == 3 and BV.match(p[0]) and p[0] == p[1] and p[2] == "(BitVec 5 × Bool)":
        return "cmp2", int(BV.match(p[0]).group(1))
    return None, None


def kinds_bodies(path):
    text = open(path).read()
    m = re.search(r"^namespace Axioms\s*$(.*?)^end Axioms\s*$", text, re.S | re.M)
    out = {}
    if not m:
        return out
    for ln in m.group(1).split("\n"):
        mm = re.match(r"^def\s+(\w+)\s*:\s*(.+?)\s*:=\s*(.+)$", ln)
        if mm:
            out[mm.group(1)] = norm(mm.group(2))
    return out


def emit_axioms(path):
    out = {}
    for ln in open(path):
        mm = re.match(r"^axiom\s+(\w+)\s*:\s*(.+?)\s*$", ln)
        if mm:
            out[mm.group(1)] = norm(mm.group(2))
    return out


def sail_vals(path):
    out = {}
    for ln in open(path):
        mm = re.match(r'^val\s+(\w+)\s*=\s*pure\s*\{cpp:\s*"(\w+)"[^}]*\}\s*:\s*\((.*?)\)\s*->\s*\((.*?)\)\s*$', ln)
        if mm:
            out[mm.group(1)] = {"cpp": mm.group(2),
                                "args": [a.strip() for a in mm.group(3).split(",")],
                                "ret": mm.group(4).strip()}
    return out


CPP = """// harness.cpp -- GENERATED by gen.py. The level-0 check's SoftFloat side:
// each operation calls the C++ function Sail's own softfloat_interface.sail
// binds it to, with the arguments Sail's own val declaration gives; linked
// against Sail's compiled riscv_softfloat object and libsoftfloat, the
// objects the model's simulator links. Nothing here is typed per operation.
#include "riscv_softfloat.h"
#include <cinttypes>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>

int main() {
  char name[128], rs[64], as[64], bs[64];
  while (std::scanf("%127s %63s %63s %63s", name, rs, as, bs) == 4) {
    uint64_t rm = std::strtoull(rs, nullptr, 16);
    uint64_t a = std::strtoull(as, nullptr, 16);
    uint64_t b = std::strtoull(bs, nullptr, 16);
    uint64_t fl = 0, res = 0;
    bool known = true;
    (void)rm;
    if (false) {
    }
@ENTRIES@
    else {
      known = false;
    }
    if (known)
      std::printf("%s %s %s %s %" PRIx64 " %" PRIx64 "\\n", name, rs, as, bs, fl, res);
    else
      std::printf("%s %s %s %s UNKNOWN\\n", name, rs, as, bs);
  }
  return 0;
}
"""

LEAN = """/-
  FloatCheck.lean -- GENERATED by gen.py. The level-0 check's Lean side:
  every definition of `Kinds.Axioms` whose type is its Sail axiom's type,
  called on points read from standard input. Nothing here is typed per
  operation; the table is generated from the two texts.
-/
import Kinds

open Kinds

def hexDigit (c : Char) : Nat :=
  let n := c.toNat
  if 48 ≤ n ∧ n ≤ 57 then n - 48
  else if 97 ≤ n ∧ n ≤ 102 then n - 87
  else if 65 ≤ n ∧ n ≤ 70 then n - 55
  else 0

def ofHex (s : String) : Nat := s.foldl (fun acc c => acc * 16 + hexDigit c) 0

def toHex (n : Nat) : String := String.mk (Nat.toDigits 16 n)

def rm2 {w : Nat} (f : BitVec 3 → BitVec w → BitVec w → BitVec 5 × BitVec w)
    (rm a b : Nat) : Nat × Nat :=
  let r := f (BitVec.ofNat 3 rm) (BitVec.ofNat w a) (BitVec.ofNat w b)
  (r.1.toNat, r.2.toNat)

def cmp2 {w : Nat} (f : BitVec w → BitVec w → BitVec 5 × Bool)
    (_rm a b : Nat) : Nat × Nat :=
  let r := f (BitVec.ofNat w a) (BitVec.ofNat w b)
  (r.1.toNat, if r.2 then 1 else 0)

def table : List (String × (Nat → Nat → Nat → Nat × Nat)) := [
@ROWS@
]

def main : IO Unit := do
  let inp ← IO.getStdin
  let out ← IO.getStdout
  repeat
    let line ← inp.getLine
    if line.isEmpty then break
    match (line.replace "\\n" "").splitOn " " with
    | [name, rs, as_, bs] =>
      match table.lookup name with
      | some f =>
        let r := f (ofHex rs) (ofHex as_) (ofHex bs)
        out.putStrLn (name ++ " " ++ rs ++ " " ++ as_ ++ " " ++ bs ++ " " ++ toHex r.1 ++ " " ++ toHex r.2)
      | none => out.putStrLn (name ++ " " ++ rs ++ " " ++ as_ ++ " " ++ bs ++ " UNKNOWN")
    | _ => pure ()
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--extras", required=True)
    ap.add_argument("--kinds", required=True)
    ap.add_argument("--sail", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    kb, ax, sv = kinds_bodies(args.kinds), emit_axioms(args.extras), sail_vals(args.sail)
    bound = sorted(n for n in ax if n in sv)          # the axioms Sail binds to a C++ function
    ops, refused = [], []
    for name in sorted(kb):
        atyp = ax.get(name)
        if atyp is None:
            refused.append({"name": name, "why": "no axiom of that name in the emit"})
            continue
        if atyp != kb[name]:
            refused.append({"name": name, "why": "type differs: axiom `%s`, body `%s`" % (atyp, kb[name])})
            continue
        if name not in sv:
            refused.append({"name": name, "why": "no Sail val binding a C++ function"})
            continue
        shape, w = shape_of(atyp)
        if shape is None:
            refused.append({"name": name, "why": "a type shape the harness does not call: %s" % atyp})
            continue
        operands = ["a", "b"]
        call, k = [], 0
        for t in sv[name]["args"]:
            if t == "bits_rm":
                call.append("rm")
            elif k < len(operands):
                call.append(operands[k])
                k += 1
            else:
                call = None
                break
        if call is None or k != 2 or (("rm" in call) != (shape == "rm2")):
            refused.append({"name": name, "why": "Sail's val arguments %s do not fit the shape %s" % (sv[name]["args"], shape)})
            continue
        ops.append({"name": name, "shape": shape, "width": w, "type": atyp,
                    "cpp": sv[name]["cpp"], "cpp_args": call})
    os.makedirs(args.out, exist_ok=True)
    entries = []
    for o in ops:
        res = "r.ztup1 ? 1 : 0" if o["shape"] == "cmp2" else "r.ztup1"
        entries.append('    else if (!std::strcmp(name, "%s")) { auto r = %s(%s); fl = r.ztup0; res = %s; }'
                       % (o["name"], o["cpp"], ", ".join(o["cpp_args"]), res))
    open(os.path.join(args.out, "harness.cpp"), "w").write(CPP.replace("@ENTRIES@", "\n".join(entries)))
    rows = ",\n".join('  ("%s", %s Axioms.%s)' % (o["name"], o["shape"], o["name"]) for o in ops)
    open(os.path.join(args.out, "FloatCheck.lean"), "w").write(LEAN.replace("@ROWS@", rows))
    doc = {"summary": {"axioms_bound_to_softfloat": len(bound), "bodies_in_kinds": len(kb),
                       "operations_checked": len(ops), "refused": len(refused),
                       "axioms_bound_without_a_body": len([n for n in bound if n not in kb])},
           "ops": ops, "refused": refused,
           "bound_without_a_body": [n for n in bound if n not in kb]}
    json.dump(doc, open(os.path.join(args.out, "ops.json"), "w"), indent=1)
    print("  axioms Sail binds to a softfloat function: %d; bodies in Kinds.Axioms: %d; checked: %d; refused: %d"
          % (len(bound), len(kb), len(ops), len(refused)))
    for r in refused:
        print("  REFUSED %s: %s" % (r["name"], r["why"]))
    by = {}
    for o in ops:
        by.setdefault((o["shape"], o["width"]), []).append(o["name"])
    for (s, w), ns in sorted(by.items()):
        print("  %-5s at %2d bits: %s" % (s, w, " ".join(ns)))


if __name__ == "__main__":
    main()
