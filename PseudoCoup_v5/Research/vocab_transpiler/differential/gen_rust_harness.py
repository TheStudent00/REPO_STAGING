#!/usr/bin/env python3
"""Generate a Rust program (harness/) that exercises the REAL
cranelift-assembler-x64 crate (v0.134.2, from crates.io) and prints one
`INSTRNAME|operandkey|hexbytes` line per (instruction, operand key) pair it
can construct.

Uses common_operands.py so the operand choices are identical to what
run_python_side.py drives through pc_vocab.

NOTE: this script does not itself require a Rust toolchain -- it only
*writes* harness/src/main.rs and harness/Cargo.toml. Building/running the
result requires `cargo` (see run.sh / README.md).
"""
import argparse
import os
import sys

import common_operands as co

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_ASSEMBLER_RS = os.path.normpath(
    os.path.join(HERE, "..", "..", "rust_routing", "sources", "encoder", "asm", "assembler.rs")
)


def rust_operand_expr(field, value):
    k = field.kind
    if k in ("gpr", "gprmem", "xmm", "xmmmem", "fixed", "fixed_xmm"):
        return f"{value}u8"
    if k == "imm8":
        return f"{value}u8"
    if k == "simm8":
        return f"{value}i8"
    if k == "imm16":
        return f"{value}u16"
    if k == "imm32":
        return f"{value}u32"
    if k == "simm32":
        return f"{value}i32"
    if k == "imm64":
        return f"{value}u64"
    if k == "trap":
        return "::cranelift_assembler_x64::TrapCode(::core::num::NonZeroU8::new(1).unwrap())"
    raise AssertionError(f"unhandled field kind for rust codegen: {k}")


def gen_call(inst):
    """Return (arg_exprs_for_low, arg_exprs_for_r14)."""
    calls = {}
    for key in co.OPERAND_KEYS:
        values = co.build_operand_values(inst, key)
        calls[key] = [rust_operand_expr(f, v) for f, v in values]
    return calls


RUST_PRELUDE = '''// GENERATED by gen_rust_harness.py -- do not edit by hand.
//
// Exercises the real `cranelift-assembler-x64` crate and prints
//   INSTRNAME|operandkey|hexbytes
// for every (instruction, operand key) pair the generator could construct.
//
// This file was generated but has NOT been compiled/run by the agent that
// wrote it (no `cargo` was available in that sandbox). See ../README.md.

use cranelift_assembler_x64::{inst, Registers};

pub struct Regs;
impl Registers for Regs {
    type ReadGpr = u8;
    type ReadWriteGpr = u8;
    type WriteGpr = u8;
    type ReadXmm = u8;
    type ReadWriteXmm = u8;
    type WriteXmm = u8;
}

fn to_hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{:02x}", b));
    }
    s
}

fn main() {
'''

RUST_POSTLUDE = '''}
'''


def emit_one(inst, key, args):
    ctor = f"inst::{inst.name}::<Regs>::new" if inst.generic else f"inst::{inst.name}::new"
    if not args:
        ctor_call = f"{ctor}()"
    else:
        ctor_call = f"{ctor}({', '.join(args)})"
    lines = []
    lines.append("    {")
    lines.append(f"        let __inst = {ctor_call};")
    lines.append("        let mut __buf: Vec<u8> = Vec::new();")
    lines.append("        __inst.encode(&mut __buf);")
    lines.append(
        f'        println!("{inst.name}|{key}|{{}}", to_hex(&__buf));'
    )
    lines.append("    }")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--assembler-rs", default=DEFAULT_ASSEMBLER_RS)
    ap.add_argument("--out-dir", default=os.path.join(HERE, "harness"))
    ap.add_argument("--skipped-file", default=os.path.join(HERE, "SKIPPED_RUST.txt"))
    args = ap.parse_args()

    instructions = co.parse_instructions(args.assembler_rs)
    ok, skipped = co.constructible_instructions(instructions)

    body_lines = []
    n_emitted_lines = 0
    codegen_failures = []
    for name, inst in ok.items():
        try:
            calls = gen_call(inst)
        except Exception as e:  # pragma: no cover - defensive
            codegen_failures.append((name, str(e)))
            continue
        for key in co.OPERAND_KEYS:
            body_lines.append(emit_one(inst, key, calls[key]))
            n_emitted_lines += 1

    # Anything that blew up during codegen (shouldn't happen given the field
    # classification already filtered to only known kinds) gets folded into
    # the skip list too, so nothing is silently dropped.
    for name, reason in codegen_failures:
        skipped[name] = instructions[name]
        skipped[name].skip_reason = f"rust codegen failed: {reason}"

    src_dir = os.path.join(args.out_dir, "src")
    os.makedirs(src_dir, exist_ok=True)

    main_rs = RUST_PRELUDE + "\n".join(body_lines) + "\n" + RUST_POSTLUDE
    with open(os.path.join(src_dir, "main.rs"), "w") as f:
        f.write(main_rs)

    cargo_toml = '''[package]
name = "differential-harness"
version = "0.1.0"
edition = "2021"

[dependencies]
cranelift-assembler-x64 = "0.134.2"

[[bin]]
name = "differential-harness"
path = "src/main.rs"
'''
    with open(os.path.join(args.out_dir, "Cargo.toml"), "w") as f:
        f.write(cargo_toml)

    with open(args.skipped_file, "w") as f:
        f.write("# Instructions gen_rust_harness.py could NOT generate a Rust constructor for.\n")
        f.write(f"# {len(skipped)} of {len(instructions)} total.\n\n")
        for name, inst in skipped.items():
            f.write(f"{name}\t{inst.skip_reason}\n")

    total = len(instructions)
    print("=== gen_rust_harness.py report ===")
    print(f"total instructions in assembler.rs : {total}")
    print(f"handled (Rust constructor emitted) : {len(ok)}  ({len(ok)/total:.1%})")
    print(f"skipped                            : {len(skipped)}  ({len(skipped)/total:.1%})")
    print(f"operand-key lines emitted          : {n_emitted_lines}  ({len(ok)} instrs x {len(co.OPERAND_KEYS)} keys)")
    print(f"wrote: {os.path.join(src_dir, 'main.rs')}")
    print(f"wrote: {os.path.join(args.out_dir, 'Cargo.toml')}")
    print(f"wrote: {args.skipped_file}")


if __name__ == "__main__":
    main()
