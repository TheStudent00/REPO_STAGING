#!/usr/bin/env python3
"""l3_php_recover.py -- recover php's twenty uncatchable fatals.

log 036 recorded php's construct lane as 33,660 rows of 33,680: twenty
probes died on a php FATAL, which no `catch` in php reaches.  The lane
restarted past each corpse, so each death cost exactly one probe.

WHAT THE FATALS WERE, read off the lane log rather than guessed at:
all twenty say `Cannot redeclare class R<x>_<n>`.  That is the harness's
own class-name suffix failing, not php refusing the construct.  The
`uniqcls()` function in the php driver suffixes a declared class name
with the PROBE NUMBER.  When one probe's two slots are filled by two
holders whose declaration text declares the SAME class name, both get
the same suffix and the second declaration redeclares the first.

THE FIX, and it is one line of the generator: the suffix is made per
SLOT as well as per probe -- the left declaration's classes end `_A`,
the right's `_B`, before the probe-number suffix goes on.  Nothing else
about the probe changes; the scaffold, the values and the id are the
same text they were.

The recovery runs ONLY the twenty indices, one php process each, so a
residual fatal still costs exactly one probe.  Output goes to its own
file and is folded beside the original rows rather than over them.
"""

import base64
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LANES = os.path.join(HERE, "lanes")
sys.path.insert(0, HERE)
from l3_construct import PHP_DRIVER, table, wrap64, b64gz   # noqa: E402

RAW = os.path.join(HERE, "raw")


def fatal_indices():
    """the probe numbers php died on, from the lane log, not guessed."""
    p = os.path.join(RAW, "kc_php.lane.log")
    xs = []
    for line in open(p, errors="replace"):
        m = re.search(r"fatal at (\d+)", line)
        if m:
            xs.append(int(m.group(1)))
    return sorted(set(xs))


PATCHES = [
    # the fix: distinguish the two slots BEFORE the per-probe suffix.
    ('rn($da, "a") . "\\n" . rn($db, "b") . "\\n"',
     'uniqcls(rn($da, "a"), "A") . "\\n" . uniqcls(rn($db, "b"), "B") . "\\n"'),
    # its own output file; the original rows are not overwritten.
    ('$OUT = fopen("/out/kc_php.txt", $START == 0 ? "w" : "a");',
     '$OUT = fopen("/out/kz_php.txt", "a");'),
    ('$IDX = "/work/kc_php/idx";', '$IDX = "/work/kz_php/idx";'),
]


def build_driver(idxs):
    d = PHP_DRIVER
    for a, b in PATCHES:
        if a not in d:
            raise SystemExit("php driver text moved: %r" % a[:50])
        d = d.replace(a, b)
    only = ",".join(str(i) for i in idxs)
    d = d.replace(
        'for ($n = $START; $n < count($plan); $n++) {',
        '$ONLY = array_flip(array_map("intval", explode(",", "%s")));\n'
        'for ($n = $START; $n < count($plan); $n++) {\n'
        '  if (!isset($ONLY[$n])) continue;\n'
        '  if ($n > $START) break;   // one probe per process\n' % only)
    # the summary line would lie about a twenty-probe run; drop it.
    d = d.replace('fwrite($OUT, sprintf("__SUMMARY__|%d|%d|%d|%d|%.3f\\n",',
                  'fwrite(STDOUT, sprintf("__RUN__|%d|%d|%d|%d|%.3f\\n",')
    return d


def main():
    idxs = fatal_indices()
    print("php recovery: %d fatal probe numbers read from the lane log"
          % len(idxs))
    print("  " + ", ".join(str(i) for i in idxs))
    drv = build_driver(idxs)
    tab = json.dumps(table("php"))
    sh = ["#!/bin/sh",
          "# php FATAL recovery -- generated by l3_php_recover.py.",
          "# Runs ONLY the twenty probe numbers php died on, one php",
          "# process each, so a residual fatal still costs one probe.",
          "set -u", "export HOME=/work", "ROOT=/work/kz_php",
          'rm -rf "$ROOT"; mkdir -p "$ROOT"',
          'echo "=== php FATAL recovery -- %d probes ==="' % len(idxs),
          "date -u +%Y-%m-%dT%H:%M:%SZ",
          "df -Pm /work | awk 'NR==2{print \"scratch check: free /work \""
          " $4 \" MB\"}'",
          ": > /out/kz_php.txt",
          "base64 -d <<'T_EOF' | gunzip > \"$ROOT/table.json\"",
          wrap64(b64gz(tab)), "T_EOF",
          "base64 -d <<'D_EOF' > \"$ROOT/drv.php\"",
          wrap64(base64.b64encode(drv.encode("utf-8")).decode("ascii")),
          "D_EOF",
          "I=0",
          "for N in %s; do" % " ".join(str(i) for i in idxs),
          "  I=$((I+1))",
          '  echo "[progress] php recovery [$I/%d] probe $N"' % len(idxs),
          '  php -d memory_limit=1G "$ROOT/drv.php" "$ROOT" "$N" '
          '|| echo "[fatal] probe $N died again (rc $?)"',
          "done",
          'echo "recovered rows: $(grep -c . /out/kz_php.txt)"',
          'echo "=== php recovery done ==="',
          "date -u +%Y-%m-%dT%H:%M:%SZ"]
    p = os.path.join(LANES, "kz_php.sh")
    open(p, "w").write("\n".join(sh) + "\n")
    os.chmod(p, 0o755)
    json.dump(dict(frozen="2026-08-19", fatal_indices=idxs,
                   fix="uniqcls suffix made per slot (A/B) as well as "
                       "per probe",
                   source="raw/kc_php.lane.log restart lines"),
              open(os.path.join(HERE, "manifest_php_recover.json"), "w"),
              indent=1)
    print("  lane %s (%d bytes)" % (p, os.path.getsize(p)))


if __name__ == "__main__":
    main()
