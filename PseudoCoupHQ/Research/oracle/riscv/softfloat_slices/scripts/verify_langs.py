#!/usr/bin/env python3
"""Differential test: the java, python, ruby and javascript emulations against
Berkeley SoftFloat, through the SAME oracle the other four are tested with.

`verify_emulations.py` links each of c, c++, rust and go to SoftFloat
IN-PROCESS and compares returned bits.  None of the four languages added on
2026-09-16 can do that without an FFI layer whose own correctness would then
be part of what is under test, so the comparison is made OUT OF PROCESS and
the split is stated rather than hidden:

  1. this file writes the input vectors -- one plan, in python, so every
     language is handed the identical bytes;
  2. a C program built against the SAME `sfref_<op>` oracle
     `verify_emulations.py` generates reads those inputs and writes the
     expected answers;
  3. each language reads both files, calls its own emulation, and reports
     the first mismatch per operation.

What is compared is therefore still SoftFloat's bits, not a transcript of
some intermediate language's opinion.  The oracle, the rounding-mode pin and
the `exact = true` pin are `verify_emulations.py`'s, imported, not copied.

    python3 scripts/verify_langs.py [mode] [n_random] [lang ...]
"""

import itertools
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import emul_spec as S                                           # noqa: E402
import verify_emulations as V                                   # noqa: E402

BASE = os.path.dirname(HERE)
EMU = os.path.join(BASE, "emulations")
WORK = os.environ.get("LANGV_WORK", os.path.join(V.SCRATCH, "langs"))
LANGS = ("java", "python", "ruby", "js")
MAX_CROSS = 4096          # edge crossings kept per operation


def mask(w):
    return (1 << w) - 1


def plan(op, n_rand, rng):
    """The input vectors for one operation: every edge crossing we keep,
    then uniform random patterns.  Deterministic, so a rerun compares."""
    params, _, _ = S.spec(op)
    edges = [S.edges(p) for p in params]
    vecs = []
    for combo in itertools.product(*edges):
        vecs.append([c & mask(p.width) for c, p in zip(combo, params)])
        if len(vecs) >= MAX_CROSS:
            break
    for _ in range(n_rand):
        vecs.append([rng() & mask(p.width) for p in params])
    return vecs


class Xorshift(object):
    """The same xorshift64 `verify_emulations.py` seeds its harnesses with."""

    def __init__(self, seed):
        self.s = seed

    def __call__(self):
        s = self.s
        s ^= (s << 13) & mask(64)
        s ^= s >> 7
        s ^= (s << 17) & mask(64)
        self.s = s
        return s


# ------------------------------------------------------------- the oracle --
def build_oracle_runner(mode, ops):
    """A C program: read `<op>.in`, write `<op>.exp`, using sfref_<op>."""
    d, obj = V.gen_oracle(mode)
    src = ['/* generated by scripts/verify_langs.py */',
           '#include <stdint.h>', '#include <stdio.h>', '#include <string.h>',
           '#include <stdlib.h>', '#include "oracle.h"', '',
           'int main(int argc, char **argv) {',
           '    if (argc != 4) return 2;',
           '    const char *op = argv[1];',
           '    FILE *in = fopen(argv[2], "r"), *out = fopen(argv[3], "w");',
           '    if (!in || !out) return 3;',
           '    char line[512];',
           '    while (fgets(line, sizeof line, in)) {',
           '        uint64_t a[3] = {0, 0, 0};',
           '        int n = sscanf(line, "%" SCNx64 " %" SCNx64 " %" SCNx64,',
           '                       &a[0], &a[1], &a[2]);',
           '        (void) n;',
           '        uint64_t r = 0;']
    first = True
    for op in ops:
        params, _, _ = S.spec(op)
        call = "sfref_%s(%s)" % (op, ", ".join("a[%d]" % i
                                               for i in range(len(params))))
        src.append('        %sif (!strcmp(op, "%s")) r = %s;'
                   % ("" if first else "else ", op, call))
        first = False
    src += ['        else return 4;',
            '        fprintf(out, "%" PRIx64 "\\n", r);',
            '    }',
            '    fclose(in); fclose(out);',
            '    return 0;',
            '}']
    src.insert(5, '#include <inttypes.h>')
    os.makedirs(WORK, exist_ok=True)
    c = os.path.join(WORK, "oracle_run.c")
    open(c, "w").write("\n".join(src) + "\n")
    exe = os.path.join(WORK, "oracle_run")
    rc, _, err = V.run(["clang", "-O2"] + V.DEFINES + V.INCLUDES
                       + ["-I" + d, c, obj] + V.softfloat_objects()
                       + ["-o", exe, "-lm"])
    if rc:
        raise SystemExit("oracle runner build failed:\n" + err)
    return exe


# --------------------------------------------------------------- runners ---
JAVA_MAIN = r'''
import java.io.*;
import java.lang.reflect.*;
import java.util.*;

public class Runner {
    public static void main(String[] a) throws Exception {
        String op = a[0], entry = a[1];
        int[] pw = new int[a.length - 4];
        for (int i = 0; i < pw.length; i++) pw[i] = Integer.parseInt(a[4 + i]);
        int rw = Integer.parseInt(a[3]);
        Class<?> k = Class.forName(op);
        Class<?>[] ps = new Class<?>[pw.length];
        for (int i = 0; i < pw.length; i++) ps[i] = box(pw[i]);
        Method m = k.getMethod(entry, ps);
        BufferedReader in = new BufferedReader(new FileReader(a[2]));
        StringBuilder sb = new StringBuilder();
        String line;
        while ((line = in.readLine()) != null) {
            String[] t = line.trim().split("\\s+");
            Object[] args = new Object[pw.length];
            for (int i = 0; i < pw.length; i++) args[i] = arg(pw[i], t[i]);
            Object r = m.invoke(null, args);
            sb.append(Long.toHexString(un(rw, r))).append('\n');
        }
        in.close();
        System.out.print(sb);
    }
    static Class<?> box(int w) {
        if (w == 1) return boolean.class;
        if (w == 64) return long.class;
        return int.class;
    }
    static Object arg(int w, String hex) {
        long v = Long.parseUnsignedLong(hex, 16);
        if (w == 1) return (v & 1L) != 0L;
        if (w == 64) return v;
        return (int) v;
    }
    static long un(int w, Object r) {
        if (w == 1) return ((Boolean) r) ? 1L : 0L;
        if (w == 64) return (Long) r;
        return ((Integer) r) & 0xffffffffL;
    }
}
'''

PY_RUNNER = r'''
import sys
sys.path.insert(0, sys.argv[1])
mod = __import__(sys.argv[2])
fn = getattr(mod, sys.argv[3])
rw = int(sys.argv[4])
m = (1 << rw) - 1
out = []
with open(sys.argv[5]) as fh:
    for line in fh:
        t = line.split()
        out.append("%x" % (fn(*[int(x, 16) for x in t]) & m))
sys.stdout.write("\n".join(out) + "\n")
'''

RB_RUNNER = r'''
$LOAD_PATH.unshift(ARGV[0])
require ARGV[1]
fn = method(ARGV[2].to_sym)
rw = ARGV[3].to_i
m = (1 << rw) - 1
out = []
File.foreach(ARGV[4]) do |line|
  t = line.split.map { |x| x.to_i(16) }
  out << (fn.call(*t) & m).to_s(16)
end
$stdout.write(out.join("\n") + "\n")
'''

JS_RUNNER = r'''
'use strict';
const fs = require('fs');
const path = require('path');
const mod = require(path.join(process.argv[2], process.argv[3] + '.js'));
const fn = mod[process.argv[4]];
const rw = BigInt(process.argv[5]);
const m = (1n << rw) - 1n;
const lines = fs.readFileSync(process.argv[6], 'utf8').split('\n');
const out = [];
for (const line of lines) {
  if (!line.trim()) continue;
  const t = line.trim().split(/\s+/).map((x) => BigInt('0x' + x));
  out.push((fn(...t) & m).toString(16));
}
process.stdout.write(out.join('\n') + '\n');
'''


def prepare_runners():
    os.makedirs(WORK, exist_ok=True)
    jd = os.path.join(WORK, "java")
    os.makedirs(jd, exist_ok=True)
    open(os.path.join(jd, "Runner.java"), "w").write(JAVA_MAIN)
    rc, _, err = V.run(["javac", "-d", jd, "-cp", os.path.join(EMU, "java"),
                        os.path.join(jd, "Runner.java")])
    if rc:
        raise SystemExit("Runner.java build failed:\n" + err)
    rc, _, err = V.run(["javac", "-d", jd]
                       + [os.path.join(EMU, "java", f)
                          for f in sorted(os.listdir(os.path.join(EMU, "java")))
                          if f.endswith(".java")])
    if rc:
        raise SystemExit("java emulations build failed:\n" + err)
    for name, text in (("run.py", PY_RUNNER), ("run.rb", RB_RUNNER),
                       ("run.js", JS_RUNNER)):
        open(os.path.join(WORK, name), "w").write(text)
    return jd


def run_lang(lang, jd, op, entry, sig, infile):
    rw = sig["ret"]
    if lang == "java":
        cmd = ["java", "-cp", jd, "Runner", op, entry, infile, str(rw)] \
            + [str(w) for w in sig["params"]]
    elif lang == "python":
        cmd = [sys.executable, os.path.join(WORK, "run.py"),
               os.path.join(EMU, "python"), op, entry, str(rw), infile]
    elif lang == "ruby":
        cmd = ["ruby", os.path.join(WORK, "run.rb"),
               os.path.join(EMU, "ruby"), op, entry, str(rw), infile]
    else:
        cmd = ["node", os.path.join(WORK, "run.js"),
               os.path.join(EMU, "js"), op, entry, str(rw), infile]
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    out, err = p.communicate()
    return p.returncode, out.decode(), err.decode()[:400]


def main():
    mode = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    n_rand = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
    want = [a for a in sys.argv[3:]] or list(LANGS)
    idx = json.load(open(os.path.join(EMU, "_index.json")))
    emitted = json.load(open(os.path.join(EMU, "_emitted.json")))
    ops = sorted(idx["entries"])
    V.note("building SoftFloat and the oracle runner (mode %d)" % mode)
    V.build_softfloat()
    exe = build_oracle_runner(mode, ops)
    jd = prepare_runners() if "java" in want else None

    os.makedirs(os.path.join(WORK, "vec"), exist_ok=True)
    results = {lang: {} for lang in want}
    for op in ops:
        rng = Xorshift(int(V.SEED, 16))
        vecs = plan(op, n_rand, rng)
        infile = os.path.join(WORK, "vec", op + ".in")
        expfile = os.path.join(WORK, "vec", op + ".exp")
        with open(infile, "w") as fh:
            for v in vecs:
                fh.write(" ".join("%x" % x for x in v) + "\n")
        rc, _, err = V.run([exe, op, infile, expfile])
        if rc:
            raise SystemExit("oracle run failed for %s: %s" % (op, err))
        exp = open(expfile).read().split()
        line = "  %-16s %6d vectors " % (op, len(vecs))
        for lang in want:
            entry = idx["entries"][op][lang]
            rc, out, err = run_lang(lang, jd, op, entry,
                                    emitted[op]["signature"], infile)
            if rc:
                results[lang][op] = {"ok": False, "error": err.strip()[:200]}
                line += " %s:ERR" % lang
                continue
            got = out.split()
            bad = [i for i, (g, e) in enumerate(zip(got, exp)) if g != e]
            if len(got) != len(exp):
                results[lang][op] = {"ok": False,
                                     "error": "%d answers for %d vectors"
                                              % (len(got), len(exp))}
                line += " %s:LEN" % lang
            elif bad:
                i = bad[0]
                results[lang][op] = {
                    "ok": False, "mismatches": len(bad),
                    "first": {"inputs": vecs[i], "expected": exp[i],
                              "got": got[i]}}
                line += " %s:%d" % (lang, len(bad))
            else:
                results[lang][op] = {"ok": True, "vectors": len(vecs)}
                line += " %s:ok" % lang
        print(line, flush=True)

    out = {"mode": mode, "n_random": n_rand, "max_cross": MAX_CROSS,
           "seed": V.SEED, "languages": results,
           "what": "java, python, ruby and javascript emulations against the "
                   "Berkeley SoftFloat oracle of verify_emulations.py, "
                   "compared out of process over identical input vectors"}
    dst = os.path.join(BASE, "measurements", "verify_langs.json")
    json.dump(out, open(dst, "w"), indent=1, sort_keys=True)
    print()
    for lang in want:
        ok = sum(1 for r in results[lang].values() if r.get("ok"))
        print("  %-8s %d of %d operations bit-exact" % (lang, ok, len(ops)))
    print("wrote %s" % dst)


if __name__ == "__main__":
    main()
