#!/usr/bin/env python3
"""dominance_lane.py -- build the Airlock lane that runs dominance.py,
and fold its products back.

the owner's ruling: the run of record is a lane.  Local debugging is fine;
what is reported is what Airlock ran.

PseudoCoupHQ is not mounted in the container, so the pass, the lifter
and the data travel INSIDE the lane script, gzip+base64.  Nothing is
fetched except the pinned solver and lifter from pip.

The unit records embedded are SLIM: only the fields the pass reads
(lang, n, meta, bytes, mnem) plus the unit's own normalised result type
as the table already recorded it on its member row.

No operator token is used anywhere in the choosing.  The candidate set
is computed inside dominance.py from the class key and the existing
connection index; this file only packs what that computation reads.

usage:
  dominance_lane.py --build
  dominance_lane.py --fold
"""

import base64
import io
import json
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
KFC = os.path.join(os.path.dirname(HERE), "kind_fuzz_clustering")
# Airlock sits beside PseudoCoupHQ in the same programming tree.  It is
# located RELATIVE to this file, because the sandbox this is developed
# in mounts the tree somewhere else.
_PROGRAMMING = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
AIRLOCK = os.path.join(_PROGRAMMING, "Airlock")

LANE = "pc_dominance.sh"

LANGS = ["c", "cpp", "go", "rust", "swift"]

# The lifter dominant_table2.json and verdicts3b.json were produced
# with.  Pinned so the bridges are laid over one model of the machine
# and not two.
PYVEX_PIN = "9.2.213"

PRODUCTS = ["bridges.json", "dominant_table3.json",
            "dominant_table3.md", "table_digest3.md"]


def slim_units():
    """label -> the record the pass reads, with the result type the
    table already recorded on the member row carried alongside."""
    table = json.load(open(os.path.join(HERE, "dominant_table2.json")))
    result_types = {}
    for row in table["rows"]:
        for member in row["members"]:
            result_types[member["unit"]] = member["result_type"]
    out = {}
    for lang in LANGS:
        path = os.path.join(HERE, "sem_anchored_%s.json" % lang)
        doc = json.load(open(path))
        for n, u in doc["units"].items():
            label = "%s/op_%s" % (lang, n)
            out[label] = dict(lang=lang, n=n, meta=u["meta"],
                              bytes=u["bytes"], mnem=u["mnem"],
                              result_type=result_types.get(label))
    return out


def payload(units):
    buf = io.BytesIO()
    tar = tarfile.open(fileobj=buf, mode="w:gz")

    def add_file(path, name):
        data = open(path, "rb").read()
        info = tarfile.TarInfo(name)
        info.size = len(data)
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(data))

    def add_bytes(data, name):
        info = tarfile.TarInfo(name)
        info.size = len(data)
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(data))

    for name in ("arch_read.py", "arch_sem.py"):
        add_file(os.path.join(KFC, name), name)
    for name in ("sem_anchored.py", "verdicts.py", "z3_ext.py",
                 "result_vocab.py", "dominance.py",
                 "check_no_spelling_keys.py"):
        add_file(os.path.join(HERE, name), name)
    for name in ("dominant_table2.json", "verdicts3b.json"):
        add_file(os.path.join(HERE, name), name)
    # the guard reads its operator inventory out of the manifests, so
    # they travel too.  They are the ONE place a token is authored.
    for lang in LANGS:
        add_file(os.path.join(HERE, "probe_manifest_%s.json" % lang),
                 "probe_manifest_%s.json" % lang)
    add_bytes(json.dumps(units).encode(), "units.json")
    tar.close()
    raw = buf.getvalue()
    return base64.b64encode(raw).decode("ascii"), len(raw)


HEAD = """#!/bin/sh
# pc_dominance -- THE DIRECTIONAL BRIDGE / DOMINANCE RULING, run.
#
# the owner, 2026-08-26: "X dominates Y on projection P when at every reading
# Y's callers may perform, X answers identically, and X answers
# readings Y cannot."  Directional.  Classes stay split; a bridge
# merges nothing.  Generated by Research/op_pipeline/dominance_lane.py .
# Do not hand-edit.
#
# PseudoCoupHQ is not mounted in the container, so the pass, the lifter
# and the data travel INSIDE this script, gzip+base64 (%(size)d bytes
# packed, %(unitcount)d slim unit records).  Products land in /out.
set -u
export HOME=/work
ROOT=/work/pc_dominance
echo "=== op_pipeline -- the directional bridge ==="
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
if ! python3 --version >/dev/null 2>&1; then
  echo "!! REFUSING TO START: python3 is not runnable in this container."
  exit 4
fi
python3 --version
rm -rf "$ROOT"; mkdir -p "$ROOT" /out
df -Pm /work | awk 'NR==2{print "free /work: " $4 " MB"}'
FREE=`df -Pm /work | awk 'NR==2{print $4}'`
if [ "$FREE" -lt 200 ]; then
  echo "!! REFUSING TO START: only $FREE MB free on /work, need 200"
  exit 3
fi

echo "-- installing the solver and the lifter"
# the lifter is PINNED to the version dominant_table2.json and
# verdicts3b.json were produced with, so the bridges are laid over one
# model of the machine and not two.
python3 -m pip install --quiet --disable-pip-version-check \\
    z3-solver pyvex==%(pyvex)s archinfo==%(pyvex)s capstone 2>&1 | tail -5
if ! python3 -c "import z3, pyvex, archinfo, capstone" 2>&1; then
  echo "!! REFUSING TO CONTINUE: a dependency did not import."
  exit 4
fi
python3 -c "import z3, pyvex, archinfo, capstone; \\
print('z3', z3.get_version_string(), '/ pyvex', pyvex.__version__, \\
'/ archinfo', archinfo.__version__, '/ capstone', capstone.__version__)"

echo "-- unpacking the embedded pass and its data"
cd "$ROOT"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d > payload.tgz
md5sum payload.tgz
tar xzf payload.tgz --no-same-owner --no-same-permissions
if [ $? -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the embedded inputs did not unpack."
  exit 5
fi
rm -f payload.tgz
ls -l | awk '{print "   " $5 "  " $9}'

echo "-- the translation's own guard tests, before any pair is judged"
python3 z3_ext.py --selfcheck
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the translation failed its own guards."
  exit 5
fi

echo "-- the pass: progress every 100 candidate pairs"
python3 -u dominance.py --in "$ROOT" --out "$ROOT" --every 100
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the dominance pass exited $rc"
  exit $rc
fi

echo "-- THE SPELLING BAN: the mechanical guard, on every product"
python3 check_no_spelling_keys.py \\
        "$ROOT/bridges.json" \\
        "$ROOT/dominant_table3.json"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! THE GUARD FAILED: refusing to publish these products."
  exit $rc
fi

echo "-- publishing"
cp "$ROOT/bridges.json" /out/
cp "$ROOT/dominant_table3.json" /out/
cp "$ROOT/dominant_table3.md" /out/
cp "$ROOT/table_digest3.md" /out/
ls -la /out
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
echo "=== pc_dominance done ==="
exit 0
__PAYLOAD__
"""


def build():
    units = slim_units()
    blob, size = payload(units)
    head = HEAD % dict(size=size, unitcount=len(units), pyvex=PYVEX_PIN)
    lines = []
    i = 0
    while i < len(blob):
        lines.append(blob[i:i + 76])
        i = i + 76
    text = head + "\n".join(lines) + "\n"
    path = os.path.join(AIRLOCK, "agent", "drop", LANE)
    fh = open(path, "w")
    fh.write(text)
    fh.close()
    os.chmod(path, 0o755)
    print("units embedded  %d" % len(units))
    print("packed payload  %d bytes" % size)
    print("lane            %s (%d bytes)" % (path, len(text)))
    return 0


def fold():
    outdir = os.path.join(AIRLOCK, "agent", "out")
    moved = 0
    for name in PRODUCTS:
        src = os.path.join(outdir, name)
        if not os.path.exists(src):
            print("!! missing from the lane output: %s" % name)
            continue
        data = open(src, "rb").read()
        dst = os.path.join(HERE, name)
        fh = open(dst, "wb")
        fh.write(data)
        fh.close()
        print("folded %s (%d bytes)" % (name, len(data)))
        moved = moved + 1
    if moved != len(PRODUCTS):
        print("!! %d of %d products folded" % (moved, len(PRODUCTS)))
        return 1
    doc = json.load(open(os.path.join(HERE, "bridges.json")))
    print("bridges           %d" % doc["bridge_count"])
    print("by projection     %s"
          % json.dumps(doc["bridges_by_projection_kind"]))
    print("residue asked     %d" % doc["residue"]["asked"])
    print("residue resolved  %d" % doc["residue"]["resolved_by_dominance"])
    print("residue standing  %d" % doc["residue"]["still_standing"])
    return 0


def main(argv):
    if "--build" in argv:
        return build()
    if "--fold" in argv:
        return fold()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
