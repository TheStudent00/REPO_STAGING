#!/usr/bin/env python3
"""dominant_table_lane.py -- write lanes/pc_step8_table.sh.

the owner's ruling: analysis runs in Airlock.  This packages step 8 as one
lane.  The lane carries its inputs inside itself (a gzipped tar,
base64-armoured) and the builder `dominant_table.py` verbatim, so it
needs nothing from the network and nothing from the host but python3.

It writes /out/dominant_table.json and /out/dominant_table.md .

usage:
  dominant_table_lane.py
"""

import base64
import io
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))

LANGS = ["c", "cpp", "go", "rust", "swift"]


def input_names():
    names = ["verdicts4.json", "verdicts3b.json", "dominant_table.py"]
    for lang in LANGS:
        names.append("core_modes_%s.json" % lang)
        names.append("op_units_%s.json" % lang)
    return names


def payload():
    buf = io.BytesIO()
    tar = tarfile.open(fileobj=buf, mode="w:gz")
    for name in input_names():
        tar.add(os.path.join(HERE, name), arcname=name)
    tar.close()
    raw = buf.getvalue()
    text = base64.b64encode(raw).decode("ascii")
    lines = []
    i = 0
    while i < len(text):
        lines.append(text[i:i + 76])
        i = i + 76
    return "\n".join(lines), len(raw)


HEAD = """#!/bin/sh
# pc_step8_table -- step 8 of the ratified operator pipeline:
# the dominant-operator table.  Generated by
# Research/op_pipeline/dominant_table_lane.py .  Do not hand-edit.
#
# Inputs travel inside this file (gzipped tar, base64).  Nothing is
# fetched.  The lane writes /out/dominant_table.json and
# /out/dominant_table.md .
set -u
ROOT=/work/pc_step8
echo "=== step 8 -- the dominant-operator table ==="
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
if ! python3 -c 'import sys; print(sys.version)'; then
  echo "!! REFUSING TO START: python3 is not runnable in this container."
  exit 4
fi
rm -rf "$ROOT"
mkdir -p "$ROOT" /out
df -Pm /work | awk 'NR==2{print "free /work: " $4 " MB"}'
echo "unpacking the embedded inputs (%d bytes packed)"
base64 -d <<'PC_STEP8_EOF' > "$ROOT/inputs.tgz"
%s
PC_STEP8_EOF
# --no-same-owner: the lane runs as a different uid than the one that
# packed the tar, and without this tar reports an ownership error per
# file and exits nonzero even though every file extracted.
tar --no-same-owner -xzf "$ROOT/inputs.tgz" -C "$ROOT"
if [ $? -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the embedded inputs did not unpack."
  exit 5
fi
ls -la "$ROOT" | sed -n '1,40p'
cd "$ROOT"
python3 "$ROOT/dominant_table.py" --in "$ROOT" --out /out
RC=$?
if [ "$RC" -ne 0 ]; then
  echo "!! builder exited $RC"
  exit "$RC"
fi
echo "--- products"
ls -la /out
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
echo "=== step 8 done ==="
"""


def main():
    body, size = payload()
    text = HEAD % (size, body)
    outdir = os.path.join(HERE, "lanes")
    if not os.path.isdir(outdir):
        os.makedirs(outdir)
    path = os.path.join(outdir, "pc_step8_table.sh")
    fh = open(path, "w")
    fh.write(text)
    fh.close()
    print("wrote %s (%d bytes; %d bytes of packed input)"
          % (path, len(text), size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
