#!/usr/bin/env python3
"""dominance2_lane.py -- build the Airlock lane that re-runs dominance
with the MEASURED ordering projection, and fold its products back.

the owner's ruling: the run of record is a lane.

The lane packs exactly what dominance_lane.py packed, plus
`dominance2.py` and `ordering_encoding.json` -- the measurement the
sister lane `pc_ordering_probe.sh` produced and `ordering_encoding.py`
parsed.  Same inputs, same proof, same adapter table, same candidate
set as the earlier run; the only difference is that the ordering
result types now have a width that was read off the compiler instead
of a refusal.

usage:
  dominance2_lane.py --build
  dominance2_lane.py --fold
"""

import base64
import io
import json
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
KFC = os.path.join(os.path.dirname(HERE), "kind_fuzz_clustering")
_PROGRAMMING = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
AIRLOCK = os.path.join(_PROGRAMMING, "Airlock")

LANE = "pc_dominance2.sh"

LANGS = ["c", "cpp", "go", "rust", "swift"]

PYVEX_PIN = "9.2.213"

PRODUCTS = ["bridges2.json", "dominant_table3b.json",
            "dominant_table3b.md", "table_digest3b.md"]


def slim_units():
    """label -> the record the pass reads, with the result type the
    table already recorded on the member row carried alongside.  This
    is dominance_lane.py's own function, unchanged in behaviour."""
    table = json.load(open(os.path.join(HERE, "dominant_table2.json")))
    result_types = {}
    for row in table["rows"]:
        for member in row["members"]:
            result_types[member["unit"]] = member["result_type"]
    out = {}
    for lang in LANGS:
        path = os.path.join(HERE, "sem_anchored_%s.json" % lang)
        doc = json.load(open(path))
        for n, u in doc["units"].items():
            label = "%s/op_%s" % (lang, n)
            out[label] = dict(lang=lang, n=n, meta=u["meta"],
                              bytes=u["bytes"], mnem=u["mnem"],
                              result_type=result_types.get(label))
    return out


def payload(units):
    buf = io.BytesIO()
    tar = tarfile.open(fileobj=buf, mode="w:gz")

    def add_file(path, name):
        data = open(path, "rb").read()
        info = tarfile.TarInfo(name)
        info.size = len(data)
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(data))

    def add_bytes(data, name):
        info = tarfile.TarInfo(name)
        info.size = len(data)
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(data))

    for name in ("arch_read.py", "arch_sem.py"):
        add_file(os.path.join(KFC, name), name)
    for name in ("sem_anchored.py", "verdicts.py", "z3_ext.py",
                 "result_vocab.py", "dominance.py", "dominance2.py",
                 "check_no_spelling_keys.py"):
        add_file(os.path.join(HERE, name), name)
    for name in ("dominant_table2.json", "verdicts3b.json",
                 "ordering_encoding.json"):
        add_file(os.path.join(HERE, name), name)
    for lang in LANGS:
        add_file(os.path.join(HERE, "probe_manifest_%s.json" % lang),
                 "probe_manifest_%s.json" % lang)
    add_bytes(json.dumps(units).encode(), "units.json")
    tar.close()
    raw = buf.getvalue()
    return base64.b64encode(raw).decode("ascii"), len(raw)


HEAD = """#!/bin/sh
# pc_dominance2 -- the ordering result types get a MEASURED projection.
#
# dominance.py refuses a projection it was not told, and says so:
# reading `partial_ordering` as "some number of bits" would be human
# interpretation of stated design, the weakest evidence class.  The
# sister lane pc_ordering_probe.sh replaced that interpretation with a
# measurement -- two independent readings of the compiler's own output,
# which agree -- and this lane re-runs dominance with it.
#
# Same inputs, same proof, same adapter table, same candidate set.
#
# THE SPELLING BAN, ABSOLUTE (the owner, 2026-08-25).  No operator token
# takes part in any key, grouping, pairing, row structure, candidate
# selection or comparison scope here.  Every JSON product is handed to
# check_no_spelling_keys.py and a FAIL refuses the publish.
#
# Generated by Research/op_pipeline/dominance2_lane.py .  Do not
# hand-edit.  %(size)d bytes packed, %(unitcount)d slim unit records.
set -u
export HOME=/work
ROOT=/work/pc_dominance2
echo "=== op_pipeline -- dominance with the measured projection ==="
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
if ! python3 --version >/dev/null 2>&1; then
  echo "!! REFUSING TO START: python3 is not runnable in this container."
  exit 4
fi
python3 --version
rm -rf "$ROOT"; mkdir -p "$ROOT" /out
df -Pm /work | awk 'NR==2{print "free /work: " $4 " MB"}'
FREE=`df -Pm /work | awk 'NR==2{print $4}'`
if [ "$FREE" -lt 200 ]; then
  echo "!! REFUSING TO START: only $FREE MB free on /work, need 200"
  exit 3
fi

echo "-- installing the solver and the lifter"
python3 -m pip install --quiet --disable-pip-version-check \\
    z3-solver pyvex==%(pyvex)s archinfo==%(pyvex)s capstone 2>&1 | tail -5
if ! python3 -c "import z3, pyvex, archinfo, capstone" 2>&1; then
  echo "!! REFUSING TO CONTINUE: a dependency did not import."
  exit 4
fi
python3 -c "import z3, pyvex, archinfo, capstone; \\
print('z3', z3.get_version_string(), '/ pyvex', pyvex.__version__, \\
'/ archinfo', archinfo.__version__, '/ capstone', capstone.__version__)"

echo "-- unpacking the embedded pass and its data"
cd "$ROOT"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d > payload.tgz
md5sum payload.tgz
tar xzf payload.tgz --no-same-owner --no-same-permissions
if [ $? -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the embedded inputs did not unpack."
  exit 5
fi
rm -f payload.tgz
ls -l | awk '{print "   " $5 "  " $9}'

echo "-- the measurement this run rests on"
python3 -c "import json; d=json.load(open('ordering_encoding.json')); \\
print(json.dumps(d['projection'], indent=1))"

echo "-- the translation's own guard tests, before any pair is judged"
python3 z3_ext.py --selfcheck
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! REFUSING TO CONTINUE: the translation failed its own guards."
  exit 5
fi

echo "-- the pass: progress every 100 candidate pairs"
python3 -u dominance2.py --in "$ROOT" --out "$ROOT" --every 100
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! the dominance2 pass exited $rc"
  exit $rc
fi

echo "-- THE SPELLING BAN: the mechanical guard, on every product"
python3 check_no_spelling_keys.py \\
        "$ROOT/bridges2.json" \\
        "$ROOT/dominant_table3b.json"
rc=$?
if [ $rc -ne 0 ]; then
  echo "!! THE GUARD FAILED: refusing to publish these products."
  exit $rc
fi

echo "-- publishing"
cp "$ROOT/bridges2.json" /out/
cp "$ROOT/dominant_table3b.json" /out/
cp "$ROOT/dominant_table3b.md" /out/
cp "$ROOT/table_digest3b.md" /out/
ls -la /out
date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ
echo "=== pc_dominance2 done ==="
exit 0
__PAYLOAD__
"""


def build():
    units = slim_units()
    blob, size = payload(units)
    head = HEAD % dict(size=size, unitcount=len(units), pyvex=PYVEX_PIN)
    lines = []
    i = 0
    while i < len(blob):
        lines.append(blob[i:i + 76])
        i = i + 76
    text = head + "\n".join(lines) + "\n"
    archive = os.path.join(HERE, "lanes", LANE)
    fh = open(archive, "w")
    fh.write(text)
    fh.close()
    path = os.path.join(AIRLOCK, "agent", "drop", LANE)
    fh = open(path, "w")
    fh.write(text)
    fh.close()
    os.chmod(path, 0o755)
    print("packed payload  %d bytes" % size)
    print("archived        %s" % archive)
    print("lane            %s (%d bytes)" % (path, len(text)))
    return 0


def fold():
    outdir = os.path.join(AIRLOCK, "agent", "out")
    moved = 0
    for name in PRODUCTS:
        src = os.path.join(outdir, name)
        if not os.path.exists(src):
            print("!! missing from the lane output: %s" % name)
            continue
        data = open(src, "rb").read()
        dst = os.path.join(HERE, name)
        fh = open(dst, "wb")
        fh.write(data)
        fh.close()
        print("folded %s (%d bytes)" % (name, len(data)))
        moved = moved + 1
    if moved != len(PRODUCTS):
        print("!! %d of %d products folded" % (moved, len(PRODUCTS)))
        return 1
    old = json.load(open(os.path.join(HERE, "bridges.json")))
    new = json.load(open(os.path.join(HERE, "bridges2.json")))
    print("bridges        %d -> %d" % (old["bridge_count"],
                                       new["bridge_count"]))
    print("not bridged    %d -> %d" % (old["class_pairs_not_bridged"],
                                       new["class_pairs_not_bridged"]))
    return 0


def main(argv):
    if "--build" in argv:
        return build()
    if "--fold" in argv:
        return fold()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
