#!/usr/bin/env python3
"""signatures.py -- layer 3, phase 2: the FIRST BEHAVIOR SIGNATURES.

A SIGNATURE is, for one probed kind (or one anonymous token off a grammar
menu), the map

    (layer-1 form, layer-2 representation, value class) [per operand]  ->  answer

together with the DOMAIN it accepted: how many inputs were answered, how many
raised, how many the compiler refused outright. The CORE compares kinds by that
pair -- domain and answer -- never by a flat signature, so this file is shaped
to be compared that way in phase 4.

Reads probes_python.json (what was asked) and raw/l3_python.txt (what came
back). Writes behavior_python.json and the readable slice behavior_python.md.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def classify(answer):
    if answer.startswith("<compile-error"):
        return "refused"
    if answer.startswith("<compile-timeout>") or answer == "<timeout>":
        return "timeout"
    if answer.startswith("<raise:"):
        return "raised"
    if answer.startswith("<no-answer>") or answer.startswith("<absent>"):
        return "silent"
    return "answered"


def main():
    spec = json.load(open(os.path.join(HERE, "probes_python.json")))
    results = {}
    for line in open(os.path.join(HERE, "raw", "l3_python.txt")):
        line = line.rstrip("\n")
        if not line or "|" not in line:
            continue
        pid, answer = line.split("|", 1)
        results[pid] = answer

    sigs = {}
    missing = []
    disagreements = []
    for probe in spec["probes"]:
        answer = results.get(probe["id"])
        if answer is None:
            missing.append(probe["id"])
            continue
        token = probe["token"]
        key = probe["kind"] + (":" + token if token else "")
        sig = sigs.setdefault(key, {
            "kind": probe["kind"], "token": token, "family": probe["family"],
            "wrap": probe["wrap"],
            "domain": {"answered": 0, "raised": 0, "refused": 0,
                       "timeout": 0, "silent": 0},
            "raises": {}, "answer_types": {}, "cells": {},
        })
        verdict = classify(answer)
        sig["domain"][verdict] += 1
        if verdict == "raised":
            name = answer[len("<raise:"):-1]
            sig["raises"][name] = sig["raises"].get(name, 0) + 1
        elif verdict == "refused":
            name = answer[len("<compile-error:"):-1]
            sig["raises"]["compile:" + name] = \
                sig["raises"].get("compile:" + name, 0) + 1
        elif verdict == "answered":
            t = answer.split(":", 1)[0]
            sig["answer_types"][t] = sig["answer_types"].get(t, 0) + 1
        inputs = " x ".join(probe["operands"][s]
                            for s in sorted(probe["operands"]))
        cell = sig["cells"].setdefault(inputs, {})
        cell[probe["mode"]] = answer
    for key, sig in sigs.items():
        for inputs, cell in sig["cells"].items():
            if len(cell) == 2 and cell["opaque"] != cell["direct"]:
                disagreements.append({
                    "signature": key, "inputs": inputs,
                    "opaque": cell["opaque"], "direct": cell["direct"]})
        sig["counts"] = {"probes": sum(sig["domain"].values()),
                         "inputs": len(sig["cells"])}

    totals = {"answered": 0, "raised": 0, "refused": 0, "timeout": 0,
              "silent": 0}
    for sig in sigs.values():
        for k, v in sig["domain"].items():
            totals[k] += v
    out = {
        "language": "python", "layer": 3,
        "what": ("per probed kind or menu token, the map "
                 "(form, representation, value class) -> answer, with the "
                 "domain it accepted"),
        "evidence": "raw/l3_python.txt, produced by lanes/l3_python.sh",
        "counts": {"signatures": len(sigs), "probes": len(spec["probes"]),
                   "results": len(results), "missing": len(missing),
                   "totals": totals,
                   "mode_disagreements": len(disagreements)},
        "mode_disagreements": disagreements,
        "missing": missing,
        "signatures": sigs,
    }
    with open(os.path.join(HERE, "behavior_python.json"), "w") as h:
        json.dump(out, h, indent=1, sort_keys=True)

    # ---- the readable slice
    lines = ["# behavior_python -- the readable slice", "",
             "Generated by `signatures.py`. Full map: `behavior_python.json`.",
             "One line per probed kind or menu token: how wide a domain it",
             "accepted, and what it answered with.", "",
             "| kind | token | inputs | answered | raised | refused | timeout |"
             " answer types | raises |",
             "|---|---|---|---|---|---|---|---|---|"]
    for key in sorted(sigs, key=lambda k: (sigs[k]["family"], k)):
        s = sigs[key]
        types = ", ".join("%s %d" % kv for kv in
                          sorted(s["answer_types"].items(),
                                 key=lambda kv: -kv[1])[:4]) or "-"
        raises = ", ".join("%s %d" % kv for kv in
                           sorted(s["raises"].items(),
                                  key=lambda kv: -kv[1])[:4]) or "-"
        lines.append("| %s | %s | %d | %d | %d | %d | %d | %s | %s |" % (
            s["kind"], "`%s`" % s["token"] if s["token"] else "-",
            s["counts"]["inputs"], s["domain"]["answered"],
            s["domain"]["raised"], s["domain"]["refused"],
            s["domain"]["timeout"], types, raises))
    lines += ["", "## where the two spellings disagree", "",
              "A probe is written twice where both operands can be spelled as",
              "literals: once through a variable (opaque to the compiler) and",
              "once as the literal in place (open to constant folding). A",
              "difference between the two is a finding about the COMPILER, not",
              "about the data.", ""]
    if disagreements:
        lines += ["| signature | inputs | opaque | direct |", "|---|---|---|---|"]
        for d in disagreements[:60]:
            lines.append("| %s | %s | %s | %s |" % (
                d["signature"], d["inputs"], d["opaque"], d["direct"]))
    else:
        lines.append("None. Every doubly-spelled probe answered identically "
                     "both ways (%d pairs checked)."
                     % sum(1 for s in sigs.values()
                           for c in s["cells"].values() if len(c) == 2))
    with open(os.path.join(HERE, "behavior_python.md"), "w") as h:
        h.write("\n".join(lines) + "\n")

    print("signatures=%d probes=%d results=%d missing=%d"
          % (len(sigs), len(spec["probes"]), len(results), len(missing)))
    print("totals:", totals)
    print("mode disagreements:", len(disagreements))


if __name__ == "__main__":
    main()
