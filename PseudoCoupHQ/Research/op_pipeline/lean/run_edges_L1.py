#!/usr/bin/env python3
"""run_edges_L1.py -- state each selected pair as a Lean theorem and run it.

One theorem per pair: `theorem edge_NN (v0 v1 : BitVec w) : tA = tB := by
bv_decide`, where tA and tB are the two entries' layer-4 terms translated by
term_to_lean.py.  Each theorem is elaborated by its OWN `lean` process, so its
wall clock and its peak RSS are that theorem's and no one else's; they are read
from `os.wait4`, which returns the child's rusage.

MODES
  ten          the ten selected PROVED pairs
  undecided    the three UNDECIDED pairs, whose terms are NOT on the pair
               record (t100's sub-process was stopped at 120 s before it wrote
               one) and are therefore read from the_pool5.json's entries
  divide       a division cost ladder: the division identity at 8, 16, 32 and
               64 bits, to measure what bit-blasting a divider costs Lean.
               These are NOT corpus pairs and are labelled as such.

MEMORY
  The largest read is the_pool5.json (32 MB) in `undecided` mode; the ten and
  the ladder read only L1_edges_selected.json.  The named abort is
  ABORT_MEMORY_L1 at 6 GB of this process's own peak.
"""

import json
import os
import resource
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import term_to_lean  # noqa: E402

LEANDIR = "PseudoCoupHQ/Research/op_pipeline/lean"
PROJ = os.path.join(LEANDIR, "archproof")
POOL5 = "PseudoCoupHQ/Research/op_pipeline/the_pool5.json"
SELECTED = os.path.join(LEANDIR, "L1_edges_selected.json")
ABORT_MEMORY_L1_KB = 6 * 1024 * 1024
PER_THEOREM_SECONDS = 900


def memory_check(where):
    kb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    if kb > ABORT_MEMORY_L1_KB:
        sys.stderr.write("ABORT_MEMORY_L1 at %s: peak %d kB\n" % (where, kb))
        sys.exit(3)
    return kb


def run_lean(path, seconds=PER_THEOREM_SECONDS):
    """One `lean` process on one file. Returns (exit, out, wall, peak_kb, timed_out)."""
    t0 = time.time()
    proc = subprocess.Popen(["lean", path], stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, cwd=PROJ)
    timed_out = False
    out = b""
    try:
        out, _ = proc.communicate(timeout=seconds)
    except subprocess.TimeoutExpired:
        timed_out = True
        proc.terminate()
        try:
            out, _ = proc.communicate(timeout=30)
        except subprocess.TimeoutExpired:
            proc.kill()
            out, _ = proc.communicate()
    wall = time.time() - t0
    peak = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
    return proc.returncode, out.decode("utf-8", "replace"), wall, peak, timed_out


def symbols_used(texts):
    import re
    seen = set()
    for t in texts:
        for m in re.finditer(r"\bv[0-9]+\b", t or ""):
            seen.add(m.group(0))
    return sorted(seen, key=lambda s: int(s[1:]))


def theorem_file(name, binders, body, tactic="bv_decide"):
    lines = ["-- generated by Research/op_pipeline/lean/run_edges_L1.py",
             "import Std.Tactic.BVDecide", ""]
    b = " ".join(binders)
    lines.append("theorem %s %s :" % (name, b))
    lines.append("    %s := by" % body)
    lines.append("  %s" % tactic)
    return "\n".join(lines) + "\n"


def one_pair(idx, rec, out_dir, tag):
    widths = {k: v for k, v in (rec.get("free_symbol_widths") or {}).items()}
    ta = term_to_lean.translate(rec["text_a"], widths, rec.get("result_width_a")
                                or rec.get("answer_width"))
    tb = term_to_lean.translate(rec["text_b"], widths, rec.get("result_width_b")
                                or rec.get("answer_width"))
    row = {
        "entry_a": rec["entry_a"], "entry_b": rec["entry_b"],
        "type_key": rec["type_key"], "answer_width": rec.get("answer_width"),
        "representative_a": rec.get("representative_a"),
        "representative_b": rec.get("representative_b"),
        "text_a": rec["text_a"], "text_b": rec["text_b"],
        "translation_a": {k: ta.get(k) for k in
                          ("lean", "refused", "roundtrip_ok", "z3_reprint")},
        "translation_b": {k: tb.get(k) for k in
                          ("lean", "refused", "roundtrip_ok", "z3_reprint")},
    }
    if ta["refused"] or tb["refused"]:
        row["outcome"] = "REFUSED_BEFORE_LEAN"
        row["cause"] = (ta["refused"] or tb["refused"])[0]
        row["cause_detail"] = (ta["refused"] or tb["refused"])[1]
        return row

    syms = symbols_used([rec["text_a"], rec["text_b"]])
    binders = ["(%s : BitVec %d)" % (s, widths[s]) for s in syms]
    name = "%s_%02d_%s_%s" % (tag, idx, rec["entry_a"], rec["entry_b"])
    body = "%s = %s" % (ta["lean"], tb["lean"])
    path = os.path.join(out_dir, "%s.lean" % name)
    with open(path, "w") as fh:
        fh.write(theorem_file(name, binders, body))
    row["lean_file"] = path
    row["theorem"] = "theorem %s %s : %s := by bv_decide" % (name, " ".join(binders), body)
    code, out, wall, peak, timed = run_lean(path)
    row["lean_exit"] = code
    row["wall_seconds"] = round(wall, 3)
    row["children_peak_rss_kb"] = peak
    row["timed_out_at_seconds"] = PER_THEOREM_SECONDS if timed else None
    row["lean_output"] = out.strip()
    row["outcome"] = ("TIMED_OUT" if timed else
                      ("PROVED_BY_LEAN" if code == 0 else "LEAN_ERROR"))
    return row


def report(rows, title):
    print("| # | type_key | entries | outcome | wall s | child peak MB | cause |")
    print("|---|---|---|---|---|---|---|")
    for i, r in enumerate(rows):
        pair = ("(not a pool pair)" if r["entry_a"] is None
                else "%s == %s" % (r["entry_a"], r["entry_b"]))
        print("| %d | `%s` | %s | %s | %s | %s | %s |"
              % (i, r["type_key"], pair, r["outcome"],
                 r.get("wall_seconds", "-"),
                 (round(r["children_peak_rss_kb"] / 1024.0, 1)
                  if r.get("children_peak_rss_kb") else "-"),
                 r.get("cause", "-")))
    print("")
    print("--- %s: per theorem, LITERAL" % title)
    for i, r in enumerate(rows):
        pair = ("(not a pool pair)" if r["entry_a"] is None
                else "%s == %s" % (r["entry_a"], r["entry_b"]))
        print("### %d  %s  (%s)" % (i, pair, r["type_key"]))
        print("    layer-5 a: %s" % r["text_a"])
        print("    layer-5 b: %s" % r["text_b"])
        if r.get("theorem"):
            print("    theorem:   %s" % r["theorem"])
        if r.get("lean_output"):
            print("    lean says: %s" % r["lean_output"].replace("\n", "\n               "))
        if r.get("cause"):
            print("    refused:   %s -- %s" % (r["cause"], r.get("cause_detail")))


def mode_ten():
    sel = json.load(open(SELECTED))
    out_dir = os.path.join(PROJ, "Edges")
    os.makedirs(out_dir, exist_ok=True)
    rows = []
    total = len(sel["the_ten"])
    for i, rec in enumerate(sel["the_ten"]):
        print("[%d/%d] %s == %s" % (i + 1, total, rec["entry_a"], rec["entry_b"]))
        rows.append(one_pair(i, rec, out_dir, "edge"))
        memory_check("pair %d" % i)
    with open(os.path.join(LEANDIR, "L1_ten_edges.json"), "w") as fh:
        json.dump({"meta": {"written_by": "run_edges_L1.py ten",
                            "per_theorem_seconds": PER_THEOREM_SECONDS},
                   "rows": rows}, fh, indent=1, sort_keys=True)
    report(rows, "the ten")
    print("this process peak rss kB: %d" % resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)


def entry_text(entry):
    """A pool5 entry's printed layer-5 text, and how many distinct ones it
    holds. The field is `layer5_normalized_texts` -- a LIST, one element per
    distinct printed text among the entry's members."""
    texts = entry.get("layer5_normalized_texts") or []
    if isinstance(texts, dict):
        texts = sorted(texts.keys())
    texts = [t for t in texts if t]
    return (texts[0] if len(texts) == 1 else ""), len(texts)


def mode_undecided():
    """t100's UNDECIDED pair records carry no term at all, so the terms come
    from the_pool5.json's entries -- the same entries the pair named."""
    sel = json.load(open(SELECTED))
    want = sel.get("the_three_undecided_pairs") or []
    if not want:
        print("no UNDECIDED pairs were selected; nothing to run")
        return
    pool = json.load(open(POOL5))
    memory_check("after the_pool5.json")
    by_id = {}
    for e in pool.get("entries") or []:
        by_id[e.get("entry_id") or e.get("id")] = e
    print("the_pool5.json entries: %d; a sample entry's fields: %s"
          % (len(by_id), json.dumps(sorted(next(iter(by_id.values())).keys()))))
    for rec in want:
        for side in ("entry_a", "entry_b"):
            e = by_id.get(rec[side])
            if e:
                print("  %s %s: representative %s, distinct layer-5 texts %s, "
                      "member count %s"
                      % (side, rec[side], e.get("representative"),
                         e.get("distinct_layer5_text_count"), e.get("member_count")))
                print("     layer5_normalized_texts, LITERAL: %s"
                      % json.dumps(e.get("layer5_normalized_texts"))[:600])
                # Even where an entry DOES print a text, say straight away
                # whether Lean could state it at all, and by what cause not.
                for t in (e.get("layer5_normalized_texts") or [])[:2]:
                    probe = term_to_lean.translate(t, {"v0": 64, "v1": 64}, None,
                                                   check_roundtrip=False)
                    print("     translation probe: %s"
                          % ("accepted" if not probe["refused"]
                             else "REFUSED %s -- %s" % tuple(probe["refused"])))
    out_dir = os.path.join(PROJ, "Edges")
    os.makedirs(out_dir, exist_ok=True)
    rows = []
    for i, rec in enumerate(want):
        ea, eb = by_id.get(rec["entry_a"]), by_id.get(rec["entry_b"])
        print("[%d/%d] %s == %s" % (i + 1, len(want), rec["entry_a"], rec["entry_b"]))
        if not ea or not eb:
            rows.append({"entry_a": rec["entry_a"], "entry_b": rec["entry_b"],
                         "type_key": rec["type_key"], "text_a": "", "text_b": "",
                         "outcome": "REFUSED_BEFORE_LEAN",
                         "cause": "ENTRY_NOT_IN_POOL5", "cause_detail": ""})
            continue
        full = dict(rec)
        ta, na = entry_text(ea)
        tb, nb = entry_text(eb)
        full["text_a"], full["text_b"] = ta, tb
        full["representative_a"] = ea.get("representative")
        full["representative_b"] = eb.get("representative")
        full["distinct_layer5_texts"] = [na, nb]
        # A pool5 entry holds the DISTINCT printed texts of its members. When
        # an entry prints more than one, which of them is the representative's
        # is not recorded on the entry, and picking one would state a theorem
        # about a term nobody asked about.
        if na != 1 or nb != 1:
            rows.append({"entry_a": rec["entry_a"], "entry_b": rec["entry_b"],
                         "type_key": rec["type_key"], "text_a": ta, "text_b": tb,
                         "outcome": "REFUSED_BEFORE_LEAN",
                         "cause": ("NO_LAYER5_TEXT_ON_THE_ENTRY" if not (na and nb)
                                   else "MORE_THAN_ONE_TEXT_ON_THE_ENTRY"),
                         "cause_detail": "entry a prints %d distinct texts, entry b %d"
                                         % (na, nb)})
            continue
        rows.append(one_pair(i, full, out_dir, "und"))
        memory_check("undecided %d" % i)
    with open(os.path.join(LEANDIR, "L1_three_undecided.json"), "w") as fh:
        json.dump({"meta": {"written_by": "run_edges_L1.py undecided",
                            "terms_read_from": POOL5}, "rows": rows},
                  fh, indent=1, sort_keys=True)
    report(rows, "the three t100 left UNDECIDED")
    print("this process peak rss kB: %d" % resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)


DIVIDE_LADDER_NOTE = (
    "NOT a corpus pair. t100 left 1,099 pairs UNDECIDED and NONE of them "
    "carries a division node -- all three of their machine type keys are xmm "
    "(floating point), and the record carries no term at all. So the cost of "
    "bit-blasting a divider is measured directly here instead, on the division "
    "identity, which is true and needs the whole divider circuit.")


def mode_divide(sat_timeout=None):
    """The division cost ladder.

    `bv_decide` carries its OWN ceiling: the SAT solver's timeout, 10 seconds
    by default, reported as an error rather than as a wall clock. That is a
    limit on the tool, so it is raised and the run repeated, and both answers
    are reported -- never the first one alone.
    """
    out_dir = os.path.join(PROJ, "Edges")
    os.makedirs(out_dir, exist_ok=True)
    rows = []
    widths = [8, 16, 32, 64]
    tactic = ("bv_decide" if sat_timeout is None
              else "bv_decide (config := { timeout := %d })" % sat_timeout)
    for i, w in enumerate(widths):
        name = "divide_identity_%d%s" % (w, "" if sat_timeout is None
                                         else "_t%d" % sat_timeout)
        binders = ["(a b : BitVec %d)" % w]
        body = ("(if b == (0#%d) then true else (((a / b) * b + a %% b) == a)) = true" % w)
        path = os.path.join(out_dir, "%s.lean" % name)
        with open(path, "w") as fh:
            fh.write(theorem_file(name, binders, body, tactic=tactic))
        print("[%d/%d] the division identity at %d bits" % (i + 1, len(widths), w))
        code, out, wall, peak, timed = run_lean(path)
        # NOT "-": the spelling guard reads a hyphen on a row-structure field
        # as an operator token, and it is right to. A ladder row is not a pair
        # of pool entries at all, so the two entry fields carry nothing.
        rows.append({"entry_a": None, "entry_b": None,
                     "type_key": "constructed, %d bits" % w,
                     "text_a": DIVIDE_LADDER_NOTE if i == 0 else "(same shape)",
                     "text_b": "b = 0 or (a / b) * b + a %% b = a",
                     "theorem": "theorem %s %s : %s := by %s"
                                % (name, " ".join(binders), body, tactic),
                     "sat_timeout_seconds": sat_timeout,
                     "lean_exit": code, "wall_seconds": round(wall, 3),
                     "children_peak_rss_kb": peak,
                     "lean_output": out.strip(),
                     "outcome": ("TIMED_OUT" if timed else
                                 ("PROVED_BY_LEAN" if code == 0 else "LEAN_ERROR"))})
        memory_check("ladder %d" % w)
    out_name = ("L1_divide_ladder.json" if sat_timeout is None
                else "L1_divide_ladder_t%d.json" % sat_timeout)
    with open(os.path.join(LEANDIR, out_name), "w") as fh:
        json.dump({"meta": {"written_by": "run_edges_L1.py divide",
                            "note": DIVIDE_LADDER_NOTE,
                            "sat_timeout_seconds": sat_timeout,
                            "per_theorem_seconds": PER_THEOREM_SECONDS},
                   "rows": rows}, fh, indent=1, sort_keys=True)
    report(rows, "the division cost ladder")
    print("this process peak rss kB: %d" % resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)


if __name__ == "__main__":
    m = sys.argv[1] if len(sys.argv) > 1 else "ten"
    if m == "divide_more":
        mode_divide(sat_timeout=int(sys.argv[2]) if len(sys.argv) > 2 else 600)
    else:
        {"ten": mode_ten, "undecided": mode_undecided, "divide": mode_divide}[m]()
